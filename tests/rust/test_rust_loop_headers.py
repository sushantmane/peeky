"""Rust loop headers (#161), on a real build: `for` has two breakpoint locations, both
before its loop (`into_iter` and the iterator's binding), `while` and `loop` one each,
so each stops only before its loop and says so; `while let` binds at its loop's head,
so it stops at every pass and gets no such note."""

import json
import os

import pytest

from peeky.cli import main

MANIFEST = """[package]
name = "loops"
version = "0.1.0"
edition = "2024"

[dependencies]
"""
LOCK = """# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4

[[package]]
name = "loops"
version = "0.1.0"
"""
MAIN = """fn main() {
    let xs = vec![3, 6, 9];
    let mut total = 0;
    for x in &xs { // FOR
        total += x; // BODY
    }
    let mut k = 0;
    while k < 3 { // WHILE
        k += 1;
    }
    let mut it = xs.iter();
    while let Some(x) = it.next() { // WHILE_LET
        total += x;
    }
    let mut n = 0;
    loop { // LOOP
        n += 1;
        if n > 2 { break; }
    }
    for r in 0..5 {
        if r % 2 == 1 { while k < r + 2 { k += 1; } } // IFWHILE
    }
    for r in 0..3 {
        let mut m = 0; while m < 2 { m += 1; } total += m + r; // STMTWHILE
    }
    println!("TOTAL:{} {} {}", total, k, n);
}
"""


@pytest.fixture
def crate(tmp_path, monkeypatch):
    names = ("CARGO", "RUSTC", "DAP", "DWARFDUMP", "LINKER")
    if not all(os.environ.get("PEEKY_RUST_" + name) for name in names):
        pytest.skip("set PEEKY_RUST_* tool paths to enable Rust conformance")
    monkeypatch.setenv("PEEKY_STATE_DIR", str(tmp_path / "state"))
    root = tmp_path / "loops"
    (root / "src").mkdir(parents=True)
    (root / "Cargo.toml").write_text(MANIFEST)
    (root / "Cargo.lock").write_text(LOCK)
    (root / "src/main.rs").write_text(MAIN)
    return root


def probe(root, capsys, marker):
    line = next(i for i, text in enumerate(MAIN.splitlines(), 1) if f"// {marker}" in text)
    command = ["probe", str(root), "--at", f"src/main.rs:{line}", "--capture", "k"]
    assert main([*command, "--hits", "all", "--json", "--quiet", "--no-save"]) == 0
    result = json.loads(capsys.readouterr().out)
    assert result["status"] == "completed" and "TOTAL:45 5 3" in result["output"], result
    notes = [w for w in result["warnings"] if "loop header" in w]
    return line, result, notes


@pytest.mark.timeout(600)
def test_rust_loop_headers_say_when_they_stop_only_before_their_loop(crate, capsys):
    line, result, notes = probe(crate, capsys, "FOR")
    assert result["hits"] == 2
    assert notes == [
        f"Line {line} is a loop header: it stops twice each time its loop starts, before the "
        "first pass, never at the passes; put --at (or --set-at) on the first line of the "
        "loop's body for one stop per pass (each hit's stop, 1 to 2, says which)."
    ]
    # The loop note says more than #157's per-pass warning, which it replaces.
    assert not [w for w in result["warnings"] if "times per pass" in w], result["warnings"]
    assert [row["stop"] for row in result["rows"]] == [1, 2]
    line, result, notes = probe(crate, capsys, "WHILE")
    assert result["hits"] == 1 and len(notes) == 1, result["warnings"]
    assert notes[0].startswith(f"Line {line} is a loop header: it stops once"), notes
    # `loop {` holds no code of its loop's header, only a jump into it (as a `goto`
    # would): no note (review of #166).
    line, result, notes = probe(crate, capsys, "LOOP")
    assert result["hits"] == 1 and not notes, result["warnings"]
    # Review of #166: a loop entered under a condition, and a line holding a whole loop
    # and more, run at each pass of the loop around them: no note, and #157's per-pass
    # warning where the line has several locations.
    for marker, passes in (("IFWHILE", 5), ("STMTWHILE", 3)):
        line, result, notes = probe(crate, capsys, marker)
        assert result["hits"] >= passes and not notes, (marker, result["warnings"])
    assert [w for w in result["warnings"] if "times per pass" in w], result["warnings"]
    # At each pass (`while let` checks 4 times for 3 values): no note.
    for marker, hits in (("WHILE_LET", 4), ("BODY", 3)):
        line, result, notes = probe(crate, capsys, marker)
        assert result["hits"] >= hits and not notes, (marker, result["warnings"])
