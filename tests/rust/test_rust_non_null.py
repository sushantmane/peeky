"""A `NonNull<T>` local was withheld as `<not shown: may point at freed memory>`, while its
note said it "shows only its pointer"; `n.pointer` was refused, so the address showed
nowhere. A NonNull is a raw pointer that is never null: it now shows only its address, as a
raw pointer local does, never followed. What shows no address says it is not shown."""

import json
import os
import re

import pytest

from peeky.cli import main

MANIFEST = """[package]
name = "nonnull"
version = "0.1.0"
edition = "2024"

[dependencies]
"""
LOCK = """# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4

[[package]]
name = "nonnull"
version = "0.1.0"
"""
# No `unsafe` anywhere: making a NonNull, and letting it dangle, is safe.
MAIN = """use std::ptr::NonNull;

#[derive(Debug, Clone, Copy)]
pub struct Pt {
    x: i64,
    y: i64,
}

#[inline(never)]
fn churn() -> i64 {
    let mut total = 0;
    for _ in 0..32 {
        total += Box::leak(Box::new(Pt { x: 777, y: 888 })).x;
    }
    total
}

fn dangling() -> i64 {
    let b = Box::new(Pt { x: 5, y: 6 });
    let n = NonNull::from(&*b);
    let raw: *const Pt = &*b;
    let bytes: NonNull<u8> = n.cast();
    let v = vec![1i64, 2, 3];
    let s = NonNull::from(&v[..]);
    let t: (i64, &Pt) = (1, &*b);
    let k = t.0 + s.len() as i64;
    drop(b);
    let z = churn();
    let held = n.as_ptr() as i64 + raw as i64 + bytes.as_ptr() as i64;
    z + k + held * 0 + v.len() as i64 // OBSERVE
}

fn main() {
    println!("{}", dangling());
}
"""
ADDRESS = (
    "This Rust NonNull shows only its address: a NonNull is a raw pointer that is never null, "
    "and Peeky never follows a raw pointer, because nothing proves that what it points at "
    "still stands."
)
UNSHOWN = "<not shown: may point at freed memory>"


@pytest.fixture
def crate(tmp_path, monkeypatch):
    names = ("CARGO", "RUSTC", "DAP", "DWARFDUMP", "LINKER")
    if not all(os.environ.get("PEEKY_RUST_" + name) for name in names):
        pytest.skip("set PEEKY_RUST_* tool paths to enable Rust conformance")
    monkeypatch.setenv("PEEKY_STATE_DIR", str(tmp_path / "state"))
    root = tmp_path / "nonnull"
    (root / "src").mkdir(parents=True)
    (root / "Cargo.toml").write_text(MANIFEST)
    (root / "Cargo.lock").write_text(LOCK)
    (root / "src/main.rs").write_text(MAIN)
    return root


def line_of(text, marker):
    return next(i for i, line in enumerate(text.splitlines(), 1) if marker in line)


@pytest.mark.timeout(400)
def test_a_non_null_local_shows_its_address_and_its_note_says_so(crate, capsys):
    at = f"src/main.rs:{line_of(MAIN, '// OBSERVE')}"
    capture = "n,n.pointer,raw,bytes,s,t"
    code = main(["probe", str(crate), "--at", at, "--capture", capture, "--quiet", "--json"])
    result = json.loads(capsys.readouterr().out)
    assert code == 0, result.get("error")
    rows = {row["selector"]: row for row in result["rows"]}
    # The freed Box's bytes, or the leaked ones that may reuse them, are never read.
    assert not re.search(r"\b(?:777|888)\b", json.dumps(rows)), rows
    for name in ("n", "bytes"):
        row = rows[name]
        assert re.fullmatch(r"0x[0-9a-fA-F]+", row.get("value") or ""), row
        assert row.get("view") == "unproven" and row.get("unproven_pointer") == "raw", row
        assert row.get("note") == ADDRESS, row
        assert not row.get("children"), row
    # Its own value, the address the raw pointer made from the same Box holds, not where
    # the local is stored. `bytes`, a `NonNull<u8>`, shows no text read through it.
    assert int(rows["n"]["value"], 16) == int(rows["raw"]["value"], 16), rows
    assert int(rows["bytes"]["value"], 16) == int(rows["raw"]["value"], 16), rows
    # Selecting through it is refused in its row's words.
    assert (
        rows["n.pointer"]["error"] == "cannot expand 'n': " + ADDRESS[0].lower() + ADDRESS[1:-1]
    ), rows["n.pointer"]
    # A wide one (to a slice) has no one address: not shown, and its note says so and why.
    wide = rows["s"]
    assert wide.get("value") == UNSHOWN and wide.get("view") == "unproven", wide
    assert wide["note"].startswith("This Rust NonNull is not shown: Peeky shows a NonNull"), wide
    assert "this one is a wide pointer" in wide["note"] and "`.cast::<u8>()`" in wide["note"]
    # Nor does a tuple holding a reference past its proof claim to show its pointer.
    held = rows["t"]
    assert held.get("value") == UNSHOWN, held
    assert held["note"].startswith("This Rust value is not shown, because a pointer"), held
    for row in (wide, held):
        assert "shows only its pointer" not in row["note"], row
