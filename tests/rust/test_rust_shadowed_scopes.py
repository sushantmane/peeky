"""A Rust function binding a name twice (a roster: `entry` of a `match` arm and of a later
loop, `points` the `Vec<String>` and a loop's `&&str`). A field of the loop's `entry` reads,
though the other `entry`, out of scope at the stop, has another type; and `describe` lists
each binding apart, not one name (`entry (roster::Entry or roster::Entry *, lines 61,
82)`), as lldb-dap lists them as `points @ main.rs:73` and `points @ main.rs:81` where both
are in scope. Nor does it list the bindings a `?` desugars to."""

import json
import os

import pytest

from peeky.cli import main

MANIFEST = """[package]
name = "{name}"
version = "0.1.0"
edition = "2024"

[dependencies]
"""
LOCK = """# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4

[[package]]
name = "{name}"
version = "0.1.0"
"""
ROSTER = """use std::env;
use std::process;

/// One player, from an argument `NAME:CITY:POINTS`.
struct Entry {
    name: String,
    city: String,
    points: u32,
}

/// The table being printed: each column's width, and the rows so far.
struct Table {
    widths: Vec<usize>,
    text: String,
}

impl Table {
    /// Appends one row: text columns padded on the right, numbers on the left.
    fn row(&mut self, cells: [&str; 3]) {
        if !self.text.is_empty() {
            self.text.push(';');
        }
        for (i, cell) in cells.iter().enumerate() {
            if i > 0 {
                self.text.push_str(" | ");
            }
            let width = self.widths[i];
            if i == 2 {
                self.text.push_str(&format!("{cell:>width$}"));
            } else {
                self.text.push_str(&format!("{cell:<width$}"));
            }
        }
    }
}

/// The width a column needs: its title's, or its longest cell's.
fn widest(title: &str, cells: &[&str]) -> usize {
    let mut width = title.len();
    for cell in cells {
        width = width.max(cell.len());
    }
    width
}

fn parse(arg: &str) -> Result<Entry, String> {
    let mut parts = arg.split(':');
    let (Some(name), Some(city), Some(points), None) =
        (parts.next(), parts.next(), parts.next(), parts.next())
    else {
        return Err(format!("expected NAME:CITY:POINTS, got {arg:?}"));
    };
    let points = points.parse().map_err(|_| format!("bad points in {arg:?}"))?;
    Ok(Entry { name: name.to_string(), city: city.to_string(), points })
}

fn main() {
    let mut entries = Vec::new();
    for arg in env::args().skip(1) {
        match parse(&arg) {
            Ok(entry) => entries.push(entry),
            Err(message) => {
                eprintln!("roster: {message}");
                process::exit(2);
            }
        }
    }
    // Most points first; equal points keep the order given.
    entries.sort_by(|a, b| b.points.cmp(&a.points));

    let names: Vec<&str> = entries.iter().map(|e| e.name.as_str()).collect();
    let cities: Vec<&str> = entries.iter().map(|e| e.city.as_str()).collect();
    let points: Vec<String> = entries.iter().map(|e| e.points.to_string()).collect();
    let point_cells: Vec<&str> = points.iter().map(String::as_str).collect();

    let name_width = widest("Name", &names);
    let city_width = widest("City", &cities);
    let points_width = widest("Pts", &point_cells);
    let mut table = Table { widths: vec![name_width, city_width, points_width], text: String::new() };
    table.row(["Name", "City", "Pts"]);
    for (entry, points) in entries.iter().zip(&point_cells) {
        table.row([&entry.name, &entry.city, points]);
    }
    println!("TABLE:{}", table.text);
}
"""
PLAYERS = ["Renée:Malmö:12", "Paul:Oslo:7"]


@pytest.fixture
def state(tmp_path, monkeypatch):
    names = ("CARGO", "RUSTC", "DAP", "DWARFDUMP", "LINKER")
    if not all(os.environ.get("PEEKY_RUST_" + name) for name in names):
        pytest.skip("set PEEKY_RUST_* tool paths to enable Rust conformance")
    monkeypatch.setenv("PEEKY_STATE_DIR", str(tmp_path / "state"))
    return tmp_path / "state"


def crate_at(tmp_path, name, text):
    root = tmp_path / name
    (root / "src").mkdir(parents=True)
    (root / "Cargo.toml").write_text(MANIFEST.format(name=name))
    (root / "Cargo.lock").write_text(LOCK.format(name=name))
    (root / "src/main.rs").write_text(text)
    return root


def line_of(text, marker):
    return next(i for i, line in enumerate(text.splitlines(), 1) if marker in line)


def probe(capsys, crate, line, captures, *argv):
    command = ["probe", str(crate), "--at", f"src/main.rs:{line}", "--capture", captures]
    code = main([*command, *argv, "--json", "--quiet", "--", *PLAYERS])
    result = json.loads(capsys.readouterr().out)
    assert code == 0, result.get("error")
    return {(row["hit"], row["selector"]): row for row in result["rows"]}, result


def reads(row):
    return bool(os.environ.get("PEEKY_EXPECT_READ_MEMORY")) or row.get("view") == "memory"


@pytest.mark.timeout(400)
def test_an_out_of_scope_namesake_does_not_withhold_a_field(tmp_path, state, capsys):
    crate = crate_at(tmp_path, "roster", ROSTER)
    line = line_of(ROSTER, "table.row([&entry.name, &entry.city, points]);")
    rows, result = probe(capsys, crate, line, "entry.name,entry.city,entry.points", "--hits", "2")
    name = rows[(1, "entry.name")]
    assert "several locals named" not in json.dumps(result), result
    if reads(name):
        # Through `entry: &Entry`, used on the line itself, as an owned one reads.
        assert name["value"] == '"Renée"' and name["view"] == "memory", name
        assert rows[(1, "entry.city")]["value"] == '"Malmö"', rows
        assert rows[(2, "entry.name")]["value"] == '"Paul"', rows
    assert rows[(1, "entry.points")]["value"] == "12", rows


@pytest.mark.timeout(400)
def test_describe_lists_each_binding_of_a_name_by_its_selector(tmp_path, state, capsys):
    crate = crate_at(tmp_path, "roster", ROSTER)
    assert main(["describe", str(crate)]) == 0
    out = capsys.readouterr().out
    names = next(line for line in out.splitlines() if line.startswith("names in roster::main "))
    for shown in (
        "entry @ main.rs:61 (roster::Entry, line 61)",
        "entry @ main.rs:81 (&roster::Entry, line 82)",
        "points @ main.rs:73 (Vec<String>, lines 74-85)",
        "points @ main.rs:81 (&&str, line 82)",
    ):
        assert shown in names, names
    assert " or " not in names, names
    # Each selector reads its binding, also where lldb-dap lists it by its plain name.
    line = line_of(ROSTER, "let name_width = widest")
    rows, _ = probe(capsys, crate, line, "points @ main.rs:73,points")
    assert rows[(1, "points @ main.rs:73")]["value"] == rows[(1, "points")]["value"], rows
    assert rows[(1, "points @ main.rs:73")]["type"] == "Vec<String>", rows
    line = line_of(ROSTER, "table.row([&entry.name, &entry.city, points]);")
    rows, _ = probe(capsys, crate, line, "entry @ main.rs:81.points,entry @ main.rs:61")
    assert rows[(1, "entry @ main.rs:81.points")]["value"] == "12", rows
    assert "not found" in rows[(1, "entry @ main.rs:61")]["error"], rows


TWICE = """fn main() {
    let n = std::env::args().count();
    let x = n + 1; let x = format!("{x}!"); // TWICE
    std::hint::black_box(&x);
    println!("{x} {n}"); // AFTER
}
"""


@pytest.mark.timeout(400)
def test_two_bindings_on_one_line_are_not_selectable_by_line(tmp_path, state, capsys):
    # Both `x` are `x @ main.rs:3`, which names neither: `describe` doesn't offer
    # `x @ main.rs:3 (alloc::string::String or usize)` as one apparent selector.
    crate = crate_at(tmp_path, "twice", TWICE)
    assert main(["describe", str(crate)]) == 0
    out = capsys.readouterr().out
    names = next(line for line in out.splitlines() if line.startswith("names in twice::main "))
    twice = line_of(TWICE, "// TWICE")
    assert f"x @ main.rs:{twice} (2 bindings on this line: not selectable by line)" in names
    assert "String or usize" not in names and "usize or" not in names, names
    # lldb-dap lists both by it: the selector is refused, saying so; `n` still reads.
    rows, _ = probe(capsys, crate, line_of(TWICE, "// AFTER"), f"x @ main.rs:{twice},n")
    error = rows[(1, f"x @ main.rs:{twice}")]["error"]
    assert "2 bindings on this line: not selectable by line" in error, error
    assert rows[(1, "n")]["value"] == "3", rows


LEDGER = """use std::num::ParseIntError;

struct Expense {
    payer: *const i64,
    cents: i64,
}

fn parse(text: &str) -> Result<i64, ParseIntError> {
    let cents: i64 = text.trim().parse()?; // TRY
    let val = cents + 1; // OWN_VAL
    let residual = val * 2; // OWN_RESIDUAL
    Ok(residual)
}

fn both(text: &str) -> Result<i64, ParseIntError> {
    let val: i64 = text.parse()?; // SAME_LINE
    Ok(val)
}

fn credit(e: &Expense) -> i64 {
    e.cents + 1 // PARAM
}

struct Pair {
    x: i64,
    y: i64,
}

fn shadow(p: &mut Pair) -> i64 { // SIGNATURE
    p.y += 1; // PARAM_USE
    let q = &*p;
    let seen = q.x; // COPY
    let mut own = Pair { x: seen, y: 0 };
    let p = &mut own; // INNER
    p.y += 2; // SHADOWED
    p.x + p.y
}

static GLOBAL: Pair = Pair { x: 7, y: 8 };

fn redirect(mut p: &Pair) -> i64 {
    let first = p.x;
    p = &GLOBAL;
    first + p.y // REDIRECTED
}

fn aimed(mut p: &Pair) -> i64 {
    let first = p.x;
    let slot = &mut p;
    *slot = &GLOBAL;
    first + p.y // AIMED
}

fn settle(expenses: &[Expense]) -> i64 {
    let mut total = 0;
    for e in expenses {
        total += credit(e); // ITEM
    }
    total
}

fn main() {
    let one = 1i64;
    let expenses = vec![
        Expense { payer: &one, cents: parse("4").unwrap_or(0) },
        Expense { payer: &one, cents: both("x").unwrap_or(7) },
    ];
    let paid = settle(&expenses);
    let mut pair = Pair { x: 3, y: 4 };
    let shadowed = shadow(&mut pair) + redirect(&pair) + aimed(&pair);
    println!("{} {} {} {}", paid, expenses[0].payer == expenses[1].payer, shadowed, pair.y);
}
"""


@pytest.mark.timeout(400)
def test_describe_leaves_out_what_a_question_mark_binds(tmp_path, state, capsys):
    crate = crate_at(tmp_path, "ledger", LEDGER)
    assert main(["describe", str(crate), "--json"]) == 0
    scopes = {scope["scope"]: scope for scope in json.loads(capsys.readouterr().out)["scopes"]}
    parse = scopes["ledger::parse"]
    # Not `residual @ main.rs:9`, `residual @ main.rs:11`, `val @ main.rs:9` and
    # `val @ main.rs:10`: the program's own `val` and `residual` stay, each the one binding
    # of its name.
    assert parse["names"] == ["cents", "residual", "text", "val"], parse
    assert parse["types"]["residual"] == "i64" and parse["types"]["val"] == "i64", parse
    # A `val` of the program's on a line with a `?`: the line's two `val`s, which Peeky
    # can't tell apart by line, are both listed (shown when unsure); its `residual` is not.
    same = scopes["ledger::both"]
    assert "residual" not in json.dumps(same["names"]), same
    assert any(name.startswith("val") for name in same["names"]), same
