"""The eleventh agent evaluation's Rust Lows on real builds: references and raw pointers
spelled as Rust spells them (rota 3), the `for` loops' `iter` left out of `describe` and a
stop's listing (prep 7), and an element's unread field naming the loop's item (rota 8)."""

import json
import os

import pytest

from peeky.cli import main

MANIFEST = """[package]
name = "eval11"
version = "0.1.0"
edition = "2024"

[dependencies]
"""
LOCK = """# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4

[[package]]
name = "eval11"
version = "0.1.0"
"""
MAIN = """use std::ptr;

struct Engineer {
    name: String,
    shifts: u32,
    leave: Vec<u32>,
}

fn plan(team: &mut [Engineer], weeks: u32) -> usize {
    let mut last: Option<*const Engineer> = None;
    let mut picks = 0;
    for week in 1..=weeks {
        for (i, e) in team.iter().enumerate() {
            if e.leave.contains(&week) {
                continue;
            }
            if let Some(l) = last {
                if ptr::eq(e, l) { // EQ
                    continue;
                }
            }
            picks += i + e.shifts as usize;
        }
        last = Some(ptr::from_ref(&team[0]));
        let first = &team[0];
        picks += first.name.len(); // AFTER
    }
    picks
}

fn main() {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let mut team: Vec<Engineer> =
        args.iter().map(|a| Engineer { name: a.clone(), shifts: 0, leave: vec![2] }).collect();
    let mut n = 3u32;
    let counted = &mut n;
    *counted += 1;
    println!("{}", plan(&mut team, n));
}
"""
ARGS = ("--", "Ana", "Björn", "Chloé")


@pytest.fixture
def crate(tmp_path, monkeypatch):
    names = ("CARGO", "RUSTC", "DAP", "DWARFDUMP", "LINKER")
    if not all(os.environ.get("PEEKY_RUST_" + name) for name in names):
        pytest.skip("set PEEKY_RUST_* tool paths to enable Rust conformance")
    monkeypatch.setenv("PEEKY_STATE_DIR", str(tmp_path / "state"))
    root = tmp_path / "eval11"
    (root / "src").mkdir(parents=True)
    (root / "Cargo.toml").write_text(MANIFEST)
    (root / "Cargo.lock").write_text(LOCK)
    (root / "src/main.rs").write_text(MAIN)
    return root


def line_of(marker):
    return next(i for i, line in enumerate(MAIN.splitlines(), 1) if line.endswith(f"// {marker}"))


def reads_memory(row):
    return bool(os.environ.get("PEEKY_EXPECT_READ_MEMORY")) or row.get("view") == "memory"


def probe(capsys, crate, marker, *selectors, hits=1):
    at = f"src/main.rs:{line_of(marker)}"
    code = main(
        ["probe", str(crate), "--at", at, "--capture", ",".join(selectors), "--hits", str(hits)]
        + ["--json", *ARGS]
    )
    result = json.loads(capsys.readouterr().out)
    assert code == 0, result
    return {row["selector"]: row for row in result["rows"] if row["hit"] == hits}


@pytest.mark.timeout(400)
def test_describe_spells_references_and_leaves_out_loop_iterators(crate, capsys):
    assert main(["describe", str(crate), "--json"]) == 0
    scopes = {scope["scope"]: scope for scope in json.loads(capsys.readouterr().out)["scopes"]}
    plan = scopes["eval11::plan"]
    # Before: `e (eval11::Engineer *)`, `l (eval11::Engineer *)`, and `iter @ main.rs:12`
    # and `iter @ main.rs:13`, the loops' iterators.
    assert plan["types"]["e"] == "&eval11::Engineer", plan
    assert plan["types"]["l"] == "*const eval11::Engineer", plan
    assert plan["types"]["first"] == "&eval11::Engineer", plan
    assert not any(name.startswith("iter") for name in plan["names"]), plan
    closure = scopes["eval11::main::{{closure}}"]
    assert closure["types"]["a"] == "&alloc::string::String", closure
    assert scopes["eval11::main"]["types"]["counted"] == "&mut u32"
    assert main(["describe", str(crate)]) == 0
    text = capsys.readouterr().out
    assert "a (&String)" in text and "counted (&mut u32" in text, text


@pytest.mark.timeout(400)
def test_rows_spell_references_and_raw_pointers_as_rust(crate, capsys):
    rows = probe(capsys, crate, "EQ", "e", "l", "e.name", hits=2)
    shown = {name: (rows[name]["type"], rows[name].get("debugger_type")) for name in ("e", "l")}
    assert shown == {
        "e": ("&eval11::Engineer", "eval11::Engineer *"),
        "l": ("*const eval11::Engineer", "eval11::Engineer *"),
    }, rows
    # The raw pointer is still told apart by its mark, and read no further.
    assert rows["l"].get("unproven_pointer") == "raw", rows["l"]
    if reads_memory(rows["e.name"]):
        assert rows["e.name"]["value"] == '"Björn"', rows


@pytest.mark.timeout(400)
def test_a_stops_listing_leaves_out_loop_iterators(crate, capsys):
    at = f"src/main.rs:{line_of('EQ')}"
    assert main(["session", "start", str(crate), "--at", at, *ARGS]) == 0
    try:
        capsys.readouterr()
        assert main(["session", "inspect"]) == 0
        listed = capsys.readouterr().out
        assert "  e: &eval11::Engineer = " in listed, listed
        assert "  week: u32 = " in listed and "iter" not in listed, listed
    finally:
        main(["session", "close"])
        capsys.readouterr()
    rows = probe(capsys, crate, "EQ", "iter", "nosuch")
    assert rows["iter"]["error"].startswith("not found; visible: "), rows
    assert "iter" not in rows["nosuch"]["error"], rows


@pytest.mark.timeout(400)
def test_an_unread_element_field_names_the_loops_item(crate, capsys):
    # rota 8: `team[1].leave` said "such as a for loop's item" while `e` was in scope.
    rows = probe(capsys, crate, "EQ", "team[1].leave", "e.leave")
    if not reads_memory(rows["e.leave"]):
        pytest.skip("reading a slice's elements needs a debugger with readMemory (lldb-dap 20)")
    assert rows["team[1].leave"]["error"].endswith(
        "read it through a reference to the element: `e.leave`, at a stop where the `for` "
        "loop's item `e` is this element"
    ), rows
    assert rows["e.leave"]["value"] == "[2]", rows
    # `first` is a reference to an element, but no loop's item: the hint stays general.
    rows = probe(capsys, crate, "AFTER", "team[1].leave")
    assert rows["team[1].leave"]["error"].endswith(
        "read it through a reference to the element, such as a `for` loop's item"
    ), rows
