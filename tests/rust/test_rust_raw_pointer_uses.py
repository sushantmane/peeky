"""A reference whose last use makes it a raw pointer (`ptr::eq(f, e.payer)`) reads on that
very line. A line breakpoint there may be past the call that takes the pointer, which could
free what `f` points at; but a call of `std::ptr::eq` or `std::ptr::addr_eq` only compares
addresses, so `f.name` reads there. Where the proof
still fails, the note names what may have run since the last use, and where: a call on
the stop's own line (one of the crate's, which may do anything), or `clear()` on an
earlier line, which frees what the reference pointed at."""

import json
import os
import re

import pytest

from peeky.cli import main

MANIFEST = """[package]
name = "ptruses"
version = "0.1.0"
edition = "2024"

[dependencies]
"""
LOCK = """# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4

[[package]]
name = "ptruses"
version = "0.1.0"
"""
# No `unsafe` anywhere: comparing addresses, and letting a raw pointer dangle, is safe.
MAIN = """use std::ptr;

pub struct Friend {
    name: String,
    paid: i64,
}

#[inline(always)]
fn same(a: *const Friend, b: *const Friend) -> bool {
    a == b
}

fn by_eq(friends: &[Friend], wanted: *const Friend) -> usize {
    let mut found = friends.len();
    for (at, f) in friends.iter().enumerate() {
        if ptr::eq(f, wanted) { // EQ
            found = at;
        }
    }
    found
}

fn by_addr(friends: &[Friend], wanted: *const Friend) -> usize {
    let mut found = friends.len();
    for (at, f) in friends.iter().enumerate() {
        if ptr::addr_eq(f, wanted) { // ADDR_EQ
            found = at;
        }
    }
    found
}

fn by_own(friends: &[Friend], wanted: *const Friend) -> usize {
    let mut found = friends.len();
    for (at, f) in friends.iter().enumerate() {
        if same(f, wanted) { // SAME
            found = at;
        }
    }
    found
}

fn gone() -> i64 {
    let mut friends = vec![Friend { name: String::from("Ana"), paid: 5 }];
    let first = &friends[0];
    let addr: *const Friend = first;
    friends.clear(); // CLEAR
    let k = 1 + addr as usize as i64 * 0; // GONE
    k + friends.len() as i64
}

fn main() {
    let friends = vec![
        Friend { name: String::from("Åsa"), paid: 1 },
        Friend { name: String::from("Bo"), paid: 2 },
    ];
    let wanted: *const Friend = &friends[1];
    let paid = friends[0].paid + friends[1].paid;
    let found = (by_eq(&friends, wanted), by_addr(&friends, wanted), by_own(&friends, wanted));
    println!("{:?} {} {}", found, gone(), paid);
}
"""


@pytest.fixture
def crate(tmp_path, monkeypatch):
    names = ("CARGO", "RUSTC", "DAP", "DWARFDUMP", "LINKER")
    if not all(os.environ.get("PEEKY_RUST_" + name) for name in names):
        pytest.skip("set PEEKY_RUST_* tool paths to enable Rust conformance")
    monkeypatch.setenv("PEEKY_STATE_DIR", str(tmp_path / "state"))
    root = tmp_path / "ptruses"
    (root / "src").mkdir(parents=True)
    (root / "Cargo.toml").write_text(MANIFEST)
    (root / "Cargo.lock").write_text(LOCK)
    (root / "src/main.rs").write_text(MAIN)
    return root


def line_of(marker):
    return next(i for i, line in enumerate(MAIN.splitlines(), 1) if marker in line)


def probe(capsys, crate, marker, capture, hits=1):
    at = f"src/main.rs:{line_of(marker)}"
    code = main(
        ["probe", str(crate), "--at", at, "--capture", capture, "--hits", str(hits), "--json"]
    )
    result = json.loads(capsys.readouterr().out)
    assert code == 0, result.get("error")
    return result


def reads(row):
    """Whether the debugger reads a String's text (lldb-dap with readMemory)."""
    return bool(os.environ.get("PEEKY_EXPECT_READ_MEMORY")) or row.get("view") == "memory"


@pytest.mark.timeout(400)
@pytest.mark.parametrize("marker", ["EQ", "ADDR_EQ"])
def test_a_reference_compared_by_address_reads_on_that_line(crate, capsys, marker):
    # `f`'s last use makes it a raw pointer for the standard library's comparison; the
    # slice it points into stays borrowed, and the comparison frees nothing.
    result = probe(capsys, crate, marker, "f,f.name,f.paid", hits=2)
    rows = {(row["hit"], row["selector"]): row for row in result["rows"]}
    for hit, (name, paid) in enumerate((("Åsa", "1"), ("Bo", "2")), 1):
        f = rows[(hit, "f")]
        assert f.get("view") != "unproven" and "note" not in f, f
        assert rows[(hit, "f.paid")].get("value") == paid, rows[(hit, "f.paid")]
        text = rows[(hit, "f.name")]
        assert "error" not in text, text
        if reads(text):
            assert text.get("value") == f'"{name}"' and text.get("view") == "memory", text
    assert not any(warning.startswith("f:") for warning in result.get("warnings", [])), result


@pytest.mark.timeout(400)
def test_a_call_of_the_crate_s_own_on_the_line_keeps_it_withheld_and_says_so(crate, capsys):
    # `same` is the crate's own (inlined, so the stop may be past it): it is given only
    # a raw pointer, which keeps no borrow, and could free what `f` points at.
    result = probe(capsys, crate, "SAME", "f,f.name")
    rows = {row["selector"]: row for row in result["rows"]}
    assert rows["f"].get("view") == "unproven", rows["f"]
    assert "Åsa" not in json.dumps(rows, ensure_ascii=False), rows
    note = rows["f"]["note"]
    assert note == (
        "This Rust reference shows only its pointer: the build's MIR does not show that "
        "what it points at still stands here, because the stop may be past a call on this "
        "line that runs after `f`'s last use; probe a line that uses `f` before any call."
    ), note
    assert "may be past a call on this line" in rows["f.name"]["error"], rows["f.name"]


@pytest.mark.timeout(400)
def test_a_reference_whose_target_may_be_freed_names_the_call(crate, capsys):
    # `clear()` frees what `first` pointed at; `addr` made from it keeps no borrow, so it
    # does not count as a use of `first` later.
    result = probe(capsys, crate, "GONE", "first,first.name,addr")
    rows = {row["selector"]: row for row in result["rows"]}
    assert rows["first"].get("view") == "unproven", rows["first"]
    assert "Ana" not in json.dumps(rows, ensure_ascii=False), rows
    note = rows["first"]["note"]
    clear = line_of("CLEAR")
    assert re.search(rf"because `first` is not used ahead, and a call on line {clear} ", note), note
    assert note.endswith("probe a line that still uses `first`."), note
    assert rows["addr"].get("unproven_pointer") == "raw", rows["addr"]
    # No issue numbers in what Peeky prints.
    for row in rows.values():
        assert not re.search(r"#[0-9]", json.dumps(row)), row


# A crate's own `mod std`, which a macro declares from its argument, is
# dumped `std::ptr::eq` as the standard library's is. Its `eq` takes `owner` and drops
# it, so `f` points at freed memory past the call: nothing in it may be read.
SHADOWED = """macro_rules! make_mod {
    ($n:ident) => {
        mod $n {
            pub mod ptr {
                #[inline(always)]
                pub fn eq<T>(_: *const T, owner: Box<T>, _: ()) -> bool {
                    drop(owner);
                    true
                }
            }
        }
    };
}
make_mod!(std);

pub struct Friend {
    name: String,
}

fn main() {
    let owner = Box::new(Friend { name: String::from("Ana") });
    let f = &*owner;
    if std::ptr::eq::<Friend>(f, owner, ()) { // SHADOWED
        let other = Box::new(Friend { name: String::from("Bo") });
        println!("{}", other.name.len());
    }
}
"""


@pytest.mark.timeout(400)
def test_a_crate_s_own_std_ptr_eq_is_no_comparison(crate, capsys):
    (crate / "src/main.rs").write_text(SHADOWED)
    at = f"src/main.rs:{line_of_in(SHADOWED, '// SHADOWED')}"
    code = main(["probe", str(crate), "--at", at, "--capture", "f,f.name", "--json"])
    result = json.loads(capsys.readouterr().out)
    assert code == 0, result.get("error")
    rows = {row["selector"]: row for row in result["rows"]}
    assert rows["f"].get("view") == "unproven", rows["f"]
    assert "error" in rows["f.name"] and "value" not in rows["f.name"], rows["f.name"]
    assert rows["f.name"].get("view") != "memory", rows["f.name"]
    assert "may be past a call on this line" in rows["f"]["note"], rows["f"]


def line_of_in(text, marker):
    return next(i for i, line in enumerate(text.splitlines(), 1) if marker in line)
