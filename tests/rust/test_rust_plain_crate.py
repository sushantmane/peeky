@pytest.mark.timeout(120)
@pytest.mark.parametrize(
    "change, message",
    [
        (("src/lib.rs", "pub fn f() {}"), "A library target (src/lib.rs) is not supported"),
        (("build.rs", "fn main() {}"), "Cargo build scripts (build.rs) are not supported"),
        (("src/bin/other.rs", "fn main() {}"), "More binaries (src/bin) are not supported"),
        (("Cargo.toml", MANIFEST + 'serde = "1"\n'), "[dependencies] must be empty"),
        (("tests/a.rs", ""), None),
    ],
)
def test_crates_beyond_the_supported_shape_are_refused_with_the_reason(
    plain, capsys, change, message
):
    path, text = change
    (plain / path).parent.mkdir(parents=True, exist_ok=True)
    (plain / path).write_text(text)
    if message is None:
        # Two discovered tests: Peeky runs at most one.
        (plain / "tests/b.rs").write_text("")
        message = "At most one Cargo integration test is supported"
    at = f"src/main.rs:{line_of(MAIN)}"
    code, result = run(capsys, "probe", str(plain), "--at", at, "--capture", "a", "--quiet")
    assert code != 0 and message in result["error"]["message"], result["error"]
    assert "docs/RUST_AGENT.md" in result["error"]["message"] or "must be empty" in message


