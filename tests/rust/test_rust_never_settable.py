"""#138: a `--set` no stop of the build can apply (a Rust local the IR keeps in a
register, a field through a reference) is refused before the program runs, and rows and
`describe` say which locals are never settable."""

import json
import os

import pytest

from peeky.cli import main

MANIFEST = """[package]
name = "{name}"
version = "0.1.0"
edition = "2024"

[dependencies]
"""
LOCK = """# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4

[[package]]
name = "{name}"
version = "0.1.0"
"""
# The sixth evaluation's `limiter` (by-value parameters in registers even at opt-level 0).
LIMITER = """use std::env;

#[derive(Debug, Clone, Copy)]
struct Window {
    start: u64,
    count: u32,
}

fn allow(w: &mut Window, now: u64, limit: u32, width: u64) -> bool {
    if now - w.start > width { // ALLOW
        w.start = now;
        w.count = 0;
    }
    if w.count < limit {
        w.count += 1;
        true
    } else {
        false
    }
}

fn main() {
    let args: Vec<String> = env::args().collect();
    let limit: u32 = args[1].parse().unwrap();
    let width: u64 = args[2].parse().unwrap();
    let times: Vec<u64> = args[3].split(',').map(|t| t.parse().unwrap()).collect();
    let mut w = Window { start: times[0], count: 0 };
    let mut accepted = Vec::new();
    for &now in &times {
        if allow(&mut w, now, limit, width) {
            accepted.push(now.to_string());
        }
    }
    println!("ACCEPTED:{}", accepted.join(","));
}
"""
SCALE = """#[derive(Debug, Clone, Copy)]
struct Span {
    start: u64,
    end: u64,
}

fn scale(values: &[u64], factor: u64, offset: u64) -> u64 {
    let mut total: u64 = 0; // DECLARED
    std::hint::black_box(&mut total);
    for v in values {
        total += v * factor + offset; // LOOP
    }
    let doubled: u64 = values.iter().map(|v| v * factor).sum::<u64>() + total; // SHARED
    doubled
}

fn main() {
    let args: Vec<String> = std::env::args().collect();
    let factor: u64 = args.len() as u64 + 1;
    let mut s = Span { start: 1, end: 2 };
    std::hint::black_box(&mut s);
    let r = &mut s;
    println!("SCALED {}", scale(&[1, 2, 3], factor, 4) + r.end); // CALL
    println!("SPAN {:?}", s);
}
"""


def crate_at(tmp_path, name, text):
    root = tmp_path / name
    (root / "src").mkdir(parents=True)
    (root / "Cargo.toml").write_text(MANIFEST.format(name=name))
    (root / "Cargo.lock").write_text(LOCK.format(name=name))
    (root / "src/main.rs").write_text(text)
    return root


@pytest.fixture
def state(tmp_path, monkeypatch):
    names = ("CARGO", "RUSTC", "DAP", "DWARFDUMP", "LINKER")
    if not all(os.environ.get("PEEKY_RUST_" + name) for name in names):
        pytest.skip("set PEEKY_RUST_* tool paths to enable Rust conformance")
    monkeypatch.setenv("PEEKY_STATE_DIR", str(tmp_path / "state"))
    return tmp_path / "state"


def line_of(text, marker):
    return next(i for i, line in enumerate(text.splitlines(), 1) if marker in line)


def probe(capsys, crate, line, *argv):
    code = main(["probe", str(crate), "--at", f"src/main.rs:{line}", *argv, "--json", "--quiet"])
    return code, json.loads(capsys.readouterr().out)


def refused_before_launch(result, code="MUTATION_REJECTED"):
    error = result.get("error") or {}
    assert result["status"] == "failed" and error.get("code") == code, result
    # Nothing ran: no stop, no output, no run saved.
    assert result["hits"] == 0 and not result.get("output") and not result["rows"], result
    assert result.get("refused_before_launch") is True and "evidence" not in result, result
    assert "Refused before the program runs" in error["message"], error
    return error["message"]


@pytest.mark.timeout(300)
def test_a_register_parameter_is_refused_before_the_run_and_marked(tmp_path, state, capsys):
    # Sixth evaluation (#138): `--set width=9 --set-hit 3` ran to hit 3, then was refused
    # ("kept in a register ... settable here: none"), and the run's output was lost.
    crate = crate_at(tmp_path, "limiter", LIMITER)
    at, run = line_of(LIMITER, "// ALLOW"), ["--arg", "2", "--arg", "10", "--arg", "0,1,10,11"]
    code, result = probe(
        capsys, crate, at, *run, "--hits", "3", "--set", "width=9", "--set-hit", "3"
    )
    assert code == 1
    message = refused_before_launch(result)
    assert "in limiter::allow, `width` is a parameter kept in a register" in message, message
    assert "only shows a copy" in message and "COOKBOOK 6.6" in message, message
    assert "`mut width` in the signature and `std::hint::black_box(&mut width);`" in message
    assert message.endswith("settable here: none"), message
    assert "black_box" in result["error"]["hint"], result["error"]
    assert not (state / "evidence" / "evidence.db").exists()
    # The observation rows say so, and `describe` lists them per function.
    code, result = probe(capsys, crate, at, *run, "--capture", "now,width,limit,w")
    assert code == 0, result.get("error")
    rows = {row["selector"]: row for row in result["rows"]}
    for name in ("now", "width", "limit"):
        assert rows[name]["settable"] is False and rows[name]["not_settable"] == "register", rows
    assert "not_settable" not in rows["w"], rows["w"]
    assert main(["describe", str(crate)]) == 0
    mutable = next(line for line in capsys.readouterr().out.splitlines() if "mutable:" in line)
    assert "kept in a register" in mutable and "limiter::allow: limit, now, width" in mutable
    assert main(["probe", str(crate), "--at", f"src/main.rs:{at}", *run, "--capture", "width"]) == 0
    assert "10  [not settable: register]" in capsys.readouterr().out
    # As the refusal advises (COOKBOOK 6.6): kept in memory, set in the same probe.
    edit = ["--old", "limit: u32, width: u64) -> bool {", "--new"]
    edit.append("limit: u32, mut width: u64) -> bool { std::hint::black_box(&mut width);")
    argv = [*run, "--capture", "width", *edit, "--hits", "3", "--set-hit", "3", "--set", "width=9"]
    code, result = probe(capsys, crate, at, *argv)
    assert code == 0 and result["interventions"][0]["after"] == "9", result.get("error")
    assert "ACCEPTED:0,1,10,11" in result["output"], result["output"]


@pytest.mark.timeout(400)
def test_only_what_fails_in_every_function_on_the_line_is_refused_before_the_run(
    tmp_path, state, capsys
):
    crate = crate_at(tmp_path, "scale", SCALE)
    loop, shared, call = (line_of(SCALE, f"// {m}") for m in ("LOOP", "SHARED", "CALL"))
    code, result = probe(capsys, crate, loop, "--set", "offset=3")
    message = refused_before_launch(result)
    assert "in scale::scale, `offset` is a parameter kept in a register" in message, message
    # Bound in scope there and kept in memory (once assigned).
    assert message.endswith("settable here: factor, total"), message
    # A line `scale` shares with its closure: refused where it fails in both.
    code, result = probe(capsys, crate, shared, "--set", "offset=3")
    message = refused_before_launch(result)
    assert "in scale::scale, `offset` is a parameter kept in a register" in message, message
    assert "{closure#0} has no local `offset`" in message, message
    # `factor` is in memory in `scale` (the closure borrows it): not refused there.
    code, result = probe(capsys, crate, shared, "--capture", "factor", "--set", "factor=3")
    assert code == 0 and result["interventions"][0]["after"] == "3", result.get("error")
    # Never through a reference; a name no function there has is not found.
    code, result = probe(capsys, crate, call, "--set", "r.end=5")
    assert "in scale::main, `r` is a pointer" in refused_before_launch(result)
    code, result = probe(capsys, crate, call, "--set", "nope=5")
    assert "scale::main has no local `nope`" in refused_before_launch(result, "NOT_FOUND")
    # The struct the reference points at, held by the frame, changes.
    code, result = probe(capsys, crate, call, "--capture", "s.end", "--set", "s.end=5")
    assert code == 0 and "SPAN Span { start: 1, end: 5 }" in result["output"], result


@pytest.mark.timeout(300)
def test_a_local_settable_at_other_stops_is_left_to_the_stop(tmp_path, state, capsys):
    # `total` is kept in memory, but not yet declared on its own `let` line: the build
    # allows the change, so the probe runs and the stop says why not there.
    crate = crate_at(tmp_path, "scale", SCALE)
    declared, loop = line_of(SCALE, "// DECLARED"), line_of(SCALE, "// LOOP")
    code, result = probe(capsys, crate, declared, "--capture", "factor", "--set", "total=7")
    assert code == 1 and result["hits"] == 1, result
    assert result["error"]["code"] == "NOT_FOUND" and "refused_before_launch" not in result
    code, result = probe(capsys, crate, loop, "--capture", "total,offset", "--set", "total=7")
    assert code == 0, result.get("error")
    rows = {(row["phase"], row["selector"]): row for row in result["rows"]}
    assert [rows[phase, "total"]["value"] for phase in ("observed", "after-set")] == ["0", "7"]
    for phase in ("observed", "after-set"):
        # Marked [settable] where it may change; the register-held parameter never is.
        assert (
            rows[phase, "total"]["settable"] is True and "not_settable" not in rows[phase, "total"]
        )
        assert rows[phase, "offset"]["not_settable"] == "register", rows


SHAPES = """use std::future::Future;
use std::hint::black_box;
use std::pin::{pin, Pin};
use std::task::{Context, Poll, Waker};

#[derive(Clone, Copy, Debug)]
struct Span {
    start: i32,
    end: i32,
}

#[inline(never)]
fn arrs() -> i64 {
    let mut grid = [[1i32, 2], [3, 4]];
    let mut sp = [Span { start: 1, end: 2 }, Span { start: 3, end: 4 }];
    black_box(&mut grid);
    black_box(&mut sp);
    let r = grid[1][0] as i64 + sp[1].end as i64; // ARR
    r
}

struct Yield(bool);
impl Future for Yield {
    type Output = ();
    fn poll(mut self: Pin<&mut Self>, _cx: &mut Context<'_>) -> Poll<()> {
        if self.0 { Poll::Ready(()) } else { self.0 = true; Poll::Pending }
    }
}

fn block_on<F: Future>(future: F) -> F::Output {
    let mut future = pin!(future);
    let mut cx = Context::from_waker(Waker::noop());
    loop {
        if let Poll::Ready(value) = future.as_mut().poll(&mut cx) {
            return value;
        }
    }
}

async fn aw(n: i32) -> i32 {
    let mut k = n + 1;
    black_box(&mut k);
    Yield(false).await;
    let mut q = 3;
    black_box(&mut q);
    let r = q + k; // ASYNC
    r
}

fn main() {
    println!("arrs {}", arrs());
    println!("async {}", block_on(aw(10)));
}
"""


@pytest.mark.timeout(400)
def test_an_index_is_judged_as_the_stop_reads_it(tmp_path, state, capsys):
    # Review of #138: `sp[-1].end` and `sp[01].end` change `sp[1].end` at the stop (the
    # walk counts `-1` from the array's end and reads `01` as 1), but were refused before
    # the run ("`sp` is an array: select an element as `sp[0]`").
    crate = crate_at(tmp_path, "shapes", SHAPES)
    at = line_of(SHAPES, "// ARR")
    for selector in ("sp[-1].end", "sp[01].end"):
        code, result = probe(capsys, crate, at, "--capture", "sp[1].end", "--set", f"{selector}=9")
        assert code == 0, (selector, result.get("error"))
        assert "arrs 12" in result["output"], (selector, result["output"])
    # Whatever the stop makes of an index (here: no length for a nested array's `[-1]`),
    # the build does not rule it out.
    code, result = probe(capsys, crate, at, "--set", "grid[-1][0]=9")
    assert result["hits"] == 1 and "refused_before_launch" not in result, result
    # Past the start of the array, or into a field it does not have: still judged.
    code, result = probe(capsys, crate, at, "--set", "sp[-1].middle=9")
    assert "lists no field `middle`" in refused_before_launch(result)


@pytest.mark.timeout(400)
def test_a_local_an_async_body_keeps_across_an_await_says_so(tmp_path, state, capsys):
    # Review of #138: `k`, black-boxed but kept in the future's state across the
    # `.await`, was refused as "kept in a register" with `black_box` advice that cannot
    # help: the poll reaches it through a pointer at every stop of the body.
    crate = crate_at(tmp_path, "shapes", SHAPES)
    at = line_of(SHAPES, "// ASYNC")
    code, result = probe(capsys, crate, at, "--set", "k=9")
    message = refused_before_launch(result)
    assert "`k` is held in the async body's state across an `.await`" in message, message
    assert "register" not in message and "black_box(&mut k)" not in message, message
    assert "`let mut k2 = k; std::hint::black_box(&mut k2);`" in message, message
    assert message.endswith("settable here: q"), message
    assert "copy it into a local of the poll's own" in result["error"]["hint"]
    code, result = probe(capsys, crate, at, "--capture", "k,q")
    rows = {row["selector"]: row for row in result["rows"]}
    assert rows["k"]["not_settable"] == "async state" and rows["q"]["settable"] is True, rows
    assert main(["describe", str(crate)]) == 0
    mutable = next(line for line in capsys.readouterr().out.splitlines() if "mutable:" in line)
    assert "held in an async body's state across an `.await`" in mutable, mutable
    assert "shapes::aw::{{closure}}: k" in mutable, mutable
    # As advised: a copy the poll keeps itself, set in the same probe.
    edit = ["--old", "    black_box(&mut q);", "--new"]
    edit += ["    black_box(&mut q); let mut k2 = k; black_box(&mut k2);"]
    edit += ["--old", "let r = q + k;", "--new", "let r = q + k2;"]
    code, result = probe(capsys, crate, at, "--capture", "k2", *edit, "--set", "k2=9")
    assert code == 0 and "async 12" in result["output"], result.get("error")
