@pytest.mark.timeout(300)
def test_a_previews_fields_say_their_root_is_kept_in_a_register(tmp_path, state, capsys):
    # #138 with #106: a struct parameter kept in a register is previewed from what the
    # debugger shows; its fields read with the reason no stop changes them, as `set`
    # refuses them before the run. A struct kept in memory has [settable] fields.
    crate = crate_at(tmp_path, "previewed", PREVIEWED)
    at = line_of(PREVIEWED, "// GROW")
    assert main(["session", "start", str(crate), "--at", f"src/main.rs:{at}"]) == 0
    capsys.readouterr()
    try:
        assert main(["session", "get", "m", "--json"]) == 0
        [shown] = json.loads(capsys.readouterr().out)
        assert main(["session", "get", "kept", "--json"]) == 0
        [kept] = json.loads(capsys.readouterr().out)
        assert main(["session", "get", "m"]) == 0
        text = capsys.readouterr().out
    finally:
        main(["session", "close"])
        capsys.readouterr()
    # Without memory reads (lldb-dap 18) there is no preview, and the field is the
    # debugger's own child: marked the same.
    if os.environ.get("PEEKY_EXPECT_READ_MEMORY") or shown.get("view") == "memory":
        assert shown["value"] == "Meters { v: 5 }", shown
    [field] = shown["children"]
    assert (field["value"], field["settable"], field["not_settable"]) == ("5", False, "register")
    assert "m.v: " in text and "= 5  [not settable: register]" in text, text
    [field] = kept["children"]
    assert field["value"] == "3" and field["settable"] is True, kept
    assert "not_settable" not in field, kept
    code, result = probe(capsys, crate, at, "--set", "m.v=9")
    assert code == 2
    assert "`m` is a parameter kept in a register" in refused_before_launch(result)


@pytest.mark.timeout(400)
def test_a_set_at_is_judged_before_the_run_against_its_own_lines_functions(tmp_path, state, capsys):
    # #137 with #138: each --set-at is judged before the run at its own line, by the same
    # rules as --set at the --at line, and a --set at the --at line only there.
    crate = crate_at(tmp_path, "scale", SCALE)
    loop, call = line_of(SCALE, "// LOOP"), line_of(SCALE, "// CALL")
    # `offset` is a parameter of `scale` kept in a register: no stop of LOOP changes it.
    code, result = probe(
        capsys, crate, call, "--capture", "s.end", "--set-at", f"{loop}@2", "offset=3"
    )
    assert code == 2
