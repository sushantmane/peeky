"""#105: `--set` on scalar fields and elements of Rust locals the build keeps in memory
and proves initialized, read back and seen by the program; everything else refused."""

import json
import os

import pytest

from peeky.cli import _load, _Remote, _stop, main
from peeky.probe import Probe, run_probe

MANIFEST = """[package]
name = "spans"
version = "0.1.0"
edition = "2024"

[dependencies]
"""
LOCK = """# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4

[[package]]
name = "spans"
version = "0.1.0"
"""
MAIN = """#[derive(Debug, Clone, Copy)]
struct Span {
    start: i64,
    end: i64,
}

#[derive(Debug)]
struct Outer {
    span: Span,
    marks: [u32; 3],
    pair: (i32, u16),
    flag: bool,
    ch: char,
    ratio: f64,
    small: u8,
}

#[repr(C, packed)]
struct Packed {
    a: u8,
    b: u32,
}

struct Owned {
    n: i64,
    name: String,
}

#[inline(never)]
fn width(s: &Span) -> i64 {
    s.end - s.start // WIDTH
}

fn main() {
    let mut s = Span { start: 1, end: 2 };
    s.start += 0;
    let o = Outer { span: s, marks: [1, 2, 3], pair: (4, 5), flag: true, ch: 'x', ratio: 1.5, small: 7 };
    let t = (10i64, 20u32);
    let arr = [7i64, 8, 9];
    let pk = Packed { a: 1, b: 2 };
    let bx = Box::new(Span { start: 3, end: 4 });
    let kept = bx;
    let gone = Owned { n: 5, name: String::from("x") };
    drop(gone);
    let r = &o.span;
    let later: Span;
    let seen = r.end; // STOP: one stop (a println! line stops once per argument)
    later = Span { start: 5, end: 9 };
    let w = width(&s);
    println!("RESULT {} {} {} {} {} {} {} {}", s.end, o.span.start, o.marks[1], o.pair.0, o.pair.1, t.0, t.1, arr[2]);
    let b = pk.b;
    println!("REST {} {} {} {} {} {:?}", seen, b, kept.end, later.end, w, o);
}
"""


@pytest.fixture
def crate(tmp_path, monkeypatch):
    names = ("CARGO", "RUSTC", "DAP", "DWARFDUMP", "LINKER")
    if not all(os.environ.get("PEEKY_RUST_" + name) for name in names):
        pytest.skip("set PEEKY_RUST_* tool paths to enable Rust conformance")
    monkeypatch.setenv("PEEKY_STATE_DIR", str(tmp_path / "state"))
    root = tmp_path / "spans"
    (root / "src").mkdir(parents=True)
    (root / "Cargo.toml").write_text(MANIFEST)
    (root / "Cargo.lock").write_text(LOCK)
    (root / "src/main.rs").write_text(MAIN)
    return root


def line_of(marker):
    return next(i for i, line in enumerate(MAIN.splitlines(), 1) if marker in line)


def change(capsys, assignment):
    code = main(["session", "set", assignment, "--json"])
    return code, json.loads(capsys.readouterr().out)


def refused(capsys, assignment, *words):
    code, result = change(capsys, assignment)
    error = result.get("error", {})
    assert code == 2 and error.get("code") == "MUTATION_REJECTED", (assignment, result)
    for word in words:
        assert word in error["message"], (assignment, error["message"])


@pytest.mark.timeout(400)
def test_rust_fields_elements_and_tuple_fields_change_and_the_program_sees_them(crate, capsys):
    at = f"src/main.rs:{line_of('// STOP')}"
    assert main(["session", "start", str(crate), "--at", at]) == 0
    capsys.readouterr()
    for assignment, before, after in (
        ("s.end=20", "2", "20"),  # a struct's field
        ("o.span.start=11", "1", "11"),  # a nested struct's
        ("o.marks[1]=12", "2", "12"),  # an array element in a struct
        ("o.pair.__0=-13", "4", "-13"),  # a tuple's field, in a struct
        ("o.pair.__1=14", "5", "14"),
        ("t.__0=15", "10", "15"),  # a tuple local's
        ("t.__1=16", "20", "16"),
        ("arr[2]=17", "9", "17"),  # an array local's element
    ):
        code, result = change(capsys, assignment)
        assert code == 0, (assignment, result)
        assert (result["before"], result["after"]) == (before, after), (assignment, result)
    refused(capsys, "pk.b=3", "`pk` is a packed struct (Packed)")
    # A Box is a pointer to the heap: what it points at may be moved or freed (#101).
    refused(capsys, "kept.end=3", "`kept` is a pointer")
    refused(capsys, "bx.end=3", "has no fields or elements")  # moved: no longer read
    refused(capsys, "r.end=3", "`r` is a pointer")  # a reference: LLDB's pointer
    # Moved into drop(), or not yet assigned: the MIR does not prove it initialized.
    refused(capsys, "gone.n=3", "does not prove `gone` initialized")
    refused(capsys, "later.end=3", "does not prove `later` initialized")
    refused(capsys, "o.flag=0", "is a boolean (bool)")
    refused(capsys, "o.ch=3", "is a character (char)")
    refused(capsys, "o.ratio=3", "is a floating-point value (f64)")
    refused(capsys, "o.small=3", "only 16-, 32- and 64-bit integers")
    refused(capsys, "t.__1=-1", "outside the range of `t.__1` (u32: 0 to 4294967295)")
    refused(capsys, "o.pair.__1=70000", "outside the range of `o.pair.__1` (u16: 0 to 65535)")
    assert main(["session", "continue", "--to", str(line_of("// WIDTH"))]) == 0
    capsys.readouterr()
    # A reference parameter: what it points at is the caller's.
    refused(capsys, "s.end=3", "`s` is a pointer", "session step --out")
    # A caller's local: a call it is making may hold a copy of the old value.
    record, client = _load("default")
    remote, stop = _Remote(client), _stop(record)
    snapshot = remote.dispatch("inspect", {**stop, "frame": 1, "names": ["o"]})
    row = next(v for s in snapshot["scopes"] for v in s["variables"] if v["name"] == "o")
    with pytest.raises(Exception, match="in a caller's frame, whose values cannot be changed"):
        remote.dispatch(
            "set_variable",
            {**stop, "handle": row["variablesReference"], "name": "small", "value": "4"},
        )
    assert main(["session", "continue", "--to-exit"]) == 0
    capsys.readouterr()
    assert main(["session", "report", "--json"]) == 0
    text = json.loads(capsys.readouterr().out)["output"]
    assert main(["session", "close"]) == 0
    assert "RESULT 20 11 12 -13 14 15 16 17" in text, text
    # width saw the changed `s`; the refused changes left the program as it was.
    assert "REST 2 2 4 9 19 Outer { span: Span { start: 11, end: 2 }" in text, text
    assert "small: 7 }" in text, text


@pytest.mark.timeout(400)
def test_an_optimized_rust_build_refuses_field_changes(crate):
    from peeky.rust import RustTarget

    target = RustTarget(
        sources=("src/main.rs",),
        tests=(),
        cargo=os.environ["PEEKY_RUST_CARGO"],
        rustc=os.environ["PEEKY_RUST_RUSTC"],
        adapter=os.environ["PEEKY_RUST_DAP"],
        dwarfdump=os.environ["PEEKY_RUST_DWARFDUMP"],
        linker=os.environ["PEEKY_RUST_LINKER"],
        dsymutil=os.environ.get("PEEKY_RUST_DSYMUTIL"),
        sysroot=os.environ.get("PEEKY_RUST_SYSROOT"),
        opt_level="1",
    )
    probe = Probe("src/main.rs", line_of("// STOP"), ("t",), (("t.__0", "3"),))
    result = run_probe(crate, probe, adapter=target)
    error = result.get("error") or {}
    assert error.get("code") == "MUTATION_REJECTED", result
    assert "refused in an optimized build (opt-level=1)" in error["message"], error


MID = """#[derive(Debug, Clone, Copy)]
struct Tri {
    a: i32,
    b: i32,
    c: i32,
}

#[inline(never)]
fn f() -> i32 {
    1000
}

fn temp_out() {
    let mut s = Tri { a: 1, b: 2, c: 3 };
    let mut x = 1i32;
    s.c += 1;
    x += 0;
    let t = x + s.a + f(); // TEMP_OUT
    println!("tempout {} {} {}", t, s.a, x);
}

fn temp_across() {
    let mut s = Tri { a: 1, b: 2, c: 3 };
    s.c += 1;
    let t = s.a
        + f(); // TEMP_SECOND
    println!("temp {} {}", t, s.a);
}

fn shadow() {
    let mut s = Tri { a: 1, b: 2, c: 3 }; // OUTER
    s.a += 1;
    let mut s = Tri { a: 10, b: 20, c: 30 }; // INNER
    s.a += 1; // SHADOW
    println!("shadow {:?}", s);
}

fn big() {
    let mut a = [0u32; 1000];
    for i in 0..1000 {
        a[i] = i as u32;
    }
    a[0] += 1; // BIG
    println!("big {} {}", a[257], a[999]);
}

fn main() {
    temp_out();
    temp_across();
    shadow();
    big();
}
"""


def mid_line(marker):
    return next(i for i, line in enumerate(MID.splitlines(), 1) if marker in line)


def settable(capsys, name):
    assert main(["session", "inspect", "--json"]) == 0
    snapshot = json.loads(capsys.readouterr().out)
    rows = [v for s in snapshot["scopes"] for v in s["variables"] if v["name"] == name]
    return rows[0].get("settable")


def start_mid(crate, capsys, marker):
    (crate / "src/main.rs").write_text(MID)
    at = f"src/main.rs:{mid_line(marker)}"
    assert main(["session", "start", str(crate), "--at", at]) == 0
    capsys.readouterr()


def finish(capsys):
    assert main(["session", "continue", "--to-exit"]) == 0
    capsys.readouterr()
    assert main(["session", "report", "--json"]) == 0
    text = json.loads(capsys.readouterr().out)["output"]
    assert main(["session", "close"]) == 0
    return text


@pytest.mark.timeout(400)
def test_rust_a_change_part_way_through_a_statement_is_refused(crate, capsys):
    # Review of #105: back from `f` (`step --out`), `t = x + s.a + f()` already held
    # `s.a` in a temporary, and a change reported `1 -> 50` while the program printed
    # `1001`; so did a breakpoint on `+ f();` under `let t = s.a`.
    start_mid(crate, capsys, "// TEMP_OUT")
    # At the statement's start nothing is read yet: the change reaches it.
    assert settable(capsys, "x") is True
    code, result = change(capsys, "s.a=40")
    assert code == 0 and result["after"] == "40", result
    assert main(["session", "step", "--into"]) == 0
    assert main(["session", "step", "--out"]) == 0
    capsys.readouterr()
    assert settable(capsys, "x") is False
    line = mid_line("// TEMP_OUT")
    refused(capsys, "s.a=50", "cannot be changed here", f"part-way through line {line}")
    refused(capsys, "x=7", "cannot be changed here", "would not see the change")
    # A step onto a line starts it: nothing of the line is read yet.
    assert main(["session", "step"]) == 0
    capsys.readouterr()
    code, result = change(capsys, "s.a=45")
    assert code == 0 and result["after"] == "45", result
    # A breakpoint on a line that continues a statement an earlier line started.
    assert main(["session", "continue", "--to", str(mid_line("// TEMP_SECOND"))]) == 0
    capsys.readouterr()
    refused(capsys, "s.a=60", "already read it into a temporary")
    text = finish(capsys)
    # Only the changes made where a statement started reached the program.
    assert "tempout 1041 45 1" in text and "temp 1001 1" in text, text


@pytest.mark.timeout(400)
def test_rust_a_shadowed_root_is_selected_by_where_it_is_declared(crate, capsys):
    # Review of #105: lldb-dap names `s @ main.rs:N` for each of the two `s` (as in
    # `let mut w = w;`), which no selector could name, and plain `s` is not listed.
    start_mid(crate, capsys, "// SHADOW")
    inner, outer = mid_line("// INNER"), mid_line("// OUTER")
    code, result = change(capsys, f"s @ main.rs:{inner}.b=50")
    assert code == 0 and result["after"] == "50", result
    code, result = change(capsys, f"s@main.rs:{outer}.b=40")
    assert code == 0 and result["after"] == "40", result
    assert "shadow Tri { a: 11, b: 50, c: 30 }" in finish(capsys)


@pytest.mark.timeout(400)
def test_rust_an_element_of_a_large_array_local_is_changed(crate, capsys):
    # Review of #105: `a[257]` of a 1,000-element local exhausted the expansion
    # budget (arrays inside structs worked); the element is now fetched alone.
    start_mid(crate, capsys, "// BIG")
    code, result = change(capsys, "a[257]=9")
    assert code == 0 and result["after"] == "9", result
    assert "big 9 999" in finish(capsys)


STEPS = """#[derive(Clone, Copy, Debug)]
struct Tri {
    a: i32,
    b: i32,
    c: i32,
}

#[inline(never)]
fn add3(a: i32, b: i32, c: i32) -> i32 {
    a * 100 + b * 10 + c
}

fn array_lit() {
    let mut s = Tri { a: 1, b: 2, c: 3 };
    s.c += 1;
    let k = 7;
    let arr = [s.a, // ARR_1
               k,
               s.b]; // ARR_3
    println!("arr {:?} {}", arr, s.a);
}

fn call_args() {
    let mut s = Tri { a: 1, b: 2, c: 3 };
    s.c += 1;
    let k = 7;
    let r = add3(s.a, // CALL_1
                 k,
                 s.b); // CALL_3
    println!("call {} {}", r, s.a);
}

fn shadowed() {
    let mut x = 1i32; // X_OUTER
    x += 1;
    let mut x = 10i32; // X_INNER
    x += 1; // X_STOP
    println!("shadow {}", x);
}

#[inline(never)]
fn sixty() -> i32 {
    60
}

fn formatted() {
    let mut s = Tri { a: 1, b: 2, c: 3 };
    s.c += 1;
    println!("fmt {} {}", s.a, sixty()); // FMT
}

fn main() {
    array_lit();
    call_args();
    shadowed();
    formatted();
}
"""


def steps_line(marker):
    return next(i for i, line in enumerate(STEPS.splitlines(), 1) if marker in line)


def stopped_line(capsys):
    assert main(["session", "inspect", "--json"]) == 0
    return json.loads(capsys.readouterr().out)["frames"][0]["line"]


@pytest.mark.timeout(400)
def test_rust_a_step_back_onto_a_statements_first_line_is_refused(crate, capsys):
    # Review of #105 (round 2): `let arr = [s.a,` / `k,` / `s.b];` from a breakpoint on
    # its first line, `step` twice comes back to that line at the array's
    # construction, after `s.a` was read: `set s.a=50` reported `1 -> 50` and the
    # program printed `arr [1, 7, 2] 50`. So did call arguments over several lines.
    (crate / "src/main.rs").write_text(STEPS)
    for first, total in (("// ARR_1", "arr [40, 7, 2] 40"), ("// CALL_1", "call 4072 40")):
        at = f"src/main.rs:{steps_line(first)}"
        assert main(["session", "start", str(crate), "--at", at]) == 0
        capsys.readouterr()
        # At the breakpoint, the statement's first instruction: the change reaches it.
        code, result = change(capsys, "s.a=40")
        assert code == 0 and result["after"] == "40", result
        lines = []
        for _ in range(2):
            assert main(["session", "step"]) == 0
            capsys.readouterr()
            lines.append(stopped_line(capsys))
            refused(capsys, "s.a=50", "cannot be changed here")
        if lines[-1] == steps_line(first):
            # Back on the first line, part-way through it.
            refused(capsys, "s.a=50", f"part-way through line {lines[-1]}")
        assert main(["session", "continue", "--to-exit"]) == 0
        capsys.readouterr()
        assert main(["session", "report", "--json"]) == 0
        text = json.loads(capsys.readouterr().out)["output"]
        assert main(["session", "close"]) == 0
        capsys.readouterr()
        assert total in text, text


@pytest.mark.timeout(400)
def test_rust_a_shadowed_root_integer_is_changed(crate, capsys):
    # Review of #105 (round 2): `x @ main.rs:N=500` was refused with "only writable
    # integer locals ... has debugger type 'int'".
    (crate / "src/main.rs").write_text(STEPS)
    at = f"src/main.rs:{steps_line('// X_STOP')}"
    assert main(["session", "start", str(crate), "--at", at]) == 0
    capsys.readouterr()
    code, result = change(capsys, f"x @ main.rs:{steps_line('// X_INNER')}=500")
    assert code == 0 and result["after"] == "500", result
    code, result = change(capsys, f"x@main.rs:{steps_line('// X_OUTER')}=20")
    assert code == 0 and result["after"] == "20", result
    assert main(["session", "continue", "--to-exit"]) == 0
    capsys.readouterr()
    assert main(["session", "report", "--json"]) == 0
    text = json.loads(capsys.readouterr().out)["output"]
    assert main(["session", "close"]) == 0
    assert "shadow 501" in text, text


@pytest.mark.timeout(400)
def test_rust_a_formatting_line_gives_pointers_and_allows_a_change(crate, capsys):
    # Review of #105 (round 2): `println!("{} {}", s.a, f())` was refused, though
    # `format_args!` only takes a pointer to `s.a` (it reads the field when printing).
    (crate / "src/main.rs").write_text(STEPS)
    assert (
        main(["session", "start", str(crate), "--at", f"src/main.rs:{steps_line('// FMT')}"]) == 0
    )
    capsys.readouterr()
    code, result = change(capsys, "s.a=33")
    assert code == 0 and result["after"] == "33", result
    assert main(["session", "continue", "--to-exit"]) == 0
    capsys.readouterr()
    assert main(["session", "report", "--json"]) == 0
    text = json.loads(capsys.readouterr().out)["output"]
    assert main(["session", "close"]) == 0
    assert "fmt 33 60" in text, text
