"""The eleventh evaluation's rota: `last: Option<Engineer>`, the variable at the heart of
the bug, read `<unqualified Rust enum layout>`, with no address and nothing to read
instead. An `Option` of a struct the crate defines now reads from memory by its proven
niche layout, with the payload's fields as children; one Peeky does not decode says
why, where it is stored and what to read instead."""

import json
import os
import re

import pytest

from peeky.cli import main

MANIFEST = """[package]
name = "rota"
version = "0.1.0"
edition = "2024"

[dependencies]
"""
LOCK = """# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4

[[package]]
name = "rota"
version = "0.1.0"
"""
ROTA = """use std::env;
use std::ptr;

#[derive(Clone, Debug)]
struct Engineer {
    name: String,
    shifts: u32,
    leave: Vec<u32>,
}

#[derive(Clone, Copy, Debug)]
struct Slot {
    week: u32,
    open: bool,
}

fn parse(arg: &str) -> Engineer {
    let (name, weeks) = arg.split_once(':').unwrap_or((arg, ""));
    let leave = weeks
        .split(',')
        .filter(|w| !w.is_empty())
        .map(|w| w.parse().expect("a week number"))
        .collect();
    Engineer { name: name.to_string(), shifts: 0, leave }
}

fn plan(team: &mut [Engineer], weeks: u32) -> String {
    let mut log = String::new();
    let mut last: Option<Engineer> = None;
    let mut slot: Option<Slot> = None;
    let mut count: Option<u32> = None;
    for week in 1..=weeks {
        let mut pick = usize::MAX;
        for (i, e) in team.iter().enumerate() {
            if e.leave.contains(&week) {
                continue; // LEAVE
            }
            if let Some(l) = &last {
                if ptr::eq(e, l) { // SAME
                    continue;
                }
            }
            if pick == usize::MAX || e.shifts < team[pick].shifts {
                pick = i;
            }
        }
        if !log.is_empty() {
            log.push(',');
        }
        if pick == usize::MAX {
            log.push_str(&format!("{week}=-"));
            last = None;
        } else {
            team[pick].shifts += 1;
            log.push_str(&format!("{week}={}", team[pick].name));
            last = Some(team[pick].clone()); // ASSIGN
        }
        slot = Some(Slot { week, open: pick == usize::MAX });
        count = Some(count.unwrap_or(0) + 1);
    }
    format!("{log} {slot:?} {count:?}")
}

fn main() {
    let args: Vec<String> = env::args().skip(1).collect();
    let weeks: u32 = args[0].parse().expect("WEEKS");
    let mut team: Vec<Engineer> = args[1..].iter().map(|a| parse(a)).collect();
    let log = plan(&mut team, weeks);
    println!("ROTA:{log}");
}
"""
ARGS = ["10", "Ana:5,6", "Björn:1,2,3,4", "Chloé", "Dev:9"]


@pytest.fixture
def crate(tmp_path, monkeypatch):
    names = ("CARGO", "RUSTC", "DAP", "DWARFDUMP", "LINKER")
    if not all(os.environ.get("PEEKY_RUST_" + name) for name in names):
        pytest.skip("set PEEKY_RUST_* tool paths to enable Rust conformance")
    monkeypatch.setenv("PEEKY_STATE_DIR", str(tmp_path / "state"))
    root = tmp_path / "rota"
    (root / "src").mkdir(parents=True)
    (root / "Cargo.toml").write_text(MANIFEST)
    (root / "Cargo.lock").write_text(LOCK)
    (root / "src/main.rs").write_text(ROTA)
    return root


def line_of(marker):
    return next(i for i, line in enumerate(ROTA.splitlines(), 1) if f"// {marker}" in line)


def probe(capsys, crate, line, captures, *argv):
    command = ["probe", str(crate), "--at", f"src/main.rs:{line}", "--capture", captures]
    code = main([*command, *argv, "--json", "--quiet", "--", *ARGS])
    result = json.loads(capsys.readouterr().out)
    assert code in (0, 1), result.get("error")
    return {(row["hit"], row["selector"]): row for row in result["rows"]}


def reads_memory(row):
    return bool(os.environ.get("PEEKY_EXPECT_READ_MEMORY")) or row.get("view") != "opaque"


ADDRESS = re.compile(r"It is stored at (0x[0-9a-f]{16}); ")


@pytest.mark.timeout(400)
def test_an_option_of_a_struct_reads_its_variant_and_fields(crate, capsys):
    captures = "last,last.__0,last.__0.name,last.__0.shifts,last.__0.leave,l,slot,count"
    rows = probe(capsys, crate, line_of("SAME"), captures, "--hit", "13")
    row = {selector: found for (_, selector), found in rows.items()}
    last = row["last"]
    if not reads_memory(last):
        # No readMemory (lldb-dap 18): withheld, with why, its address and what to read.
        assert last["value"] == "<unverified Rust enum value>", last
        assert last["note"].startswith("Peeky reads this `Option` from memory"), last
        assert "read what `if let Some(x) = &last` binds instead." in last["note"], last
        return
    # Week 6: Björn was on call in week 5, and `last` holds a clone of him.
    assert last["value"] == 'Some(Engineer { name: "Björn", shifts: 1, .. })', last
    assert last["view"] == "active-variant" and "note" not in last, last
    assert row["last.__0"]["value"] == 'Engineer { name: "Björn", shifts: 1, .. }', row
    assert row["last.__0"]["type"] == "rota::Engineer", row["last.__0"]
    assert row["last.__0.name"]["value"] == '"Björn"', row["last.__0.name"]
    assert row["last.__0.name"]["view"] == "memory", row["last.__0.name"]
    assert row["last.__0.shifts"]["value"] == "1", row["last.__0.shifts"]
    leave = row["last.__0.leave"]
    assert leave["unavailable"] and "`leave` has type `Vec<u32>`" in leave["error"], leave
    assert "read it through `x` of `if let Some(x) = &last`" in leave["error"], leave
    # `l` borrows from `last`, which `ptr::eq` then compares with a slot of `team`.
    assert row["l"]["value"].startswith("0x"), row["l"]
    # A bool niche, and an Option<u32>, which Peeky does not decode: why, its address
    # (a pointer into it can be compared with) and what to read instead.
    assert row["slot"]["value"] == "Some(Slot { week: 5, open: false })", row["slot"]
    count = row["count"]
    assert count["value"] == "<unqualified Rust enum layout>" and count["view"] == "opaque"
    assert "it does not decode this `Option<u32>`" in count["note"], count
    assert ADDRESS.search(count["note"]), count
    assert count["note"].endswith("read what `if let Some(x) = &count` binds instead."), count


@pytest.mark.timeout(400)
def test_a_none_reads_and_a_line_that_drops_it_is_withheld_with_its_address(crate, capsys):
    rows = probe(capsys, crate, line_of("LEAVE"), "last,slot", "--hits", "1")
    if reads_memory(rows[(1, "last")]):
        assert rows[(1, "last")]["value"] == "None", rows
        assert rows[(1, "slot")]["value"] == "None", rows
    rows = probe(capsys, crate, line_of("ASSIGN"), "last,l", "--hits", "1")
    # The line drops the old value: the MIR does not prove it initialized there.
    last = rows[(1, "last")]
    assert last["value"] == "<unverified Rust enum value>", last
    assert "does not prove `last` initialized at this line" in last["note"], last
    assert ADDRESS.search(last["note"]), last


@pytest.mark.timeout(400)
def test_a_session_lists_the_payload_and_a_borrow_points_at_its_address(crate, capsys):
    start = [
        "session",
        "start",
        str(crate),
        "--name",
        "o",
        "--at",
        f"src/main.rs:{line_of('SAME')}",
    ]
    assert main([*start, "--hit", "13", "--", *ARGS]) == 0
    capsys.readouterr()
    try:
        assert main(["session", "get", "--name", "o", "--json", "last", "l"]) == 0
        last, borrow = json.loads(capsys.readouterr().out)
        if last.get("view") == "opaque":
            # Withheld: the address it gives is where `l`, a borrow of its payload, points.
            assert int(ADDRESS.search(last["note"])[1], 16) == int(borrow["value"], 16), last
            return
        assert [child["selector"] for child in last["children"]] == ["last.__0"], last
        assert main(["session", "get", "--name", "o", "--json", "last.__0"]) == 0
        (payload,) = json.loads(capsys.readouterr().out)
        listed = {child["name"]: child for child in payload["children"]}
        assert listed["name"]["value"] == '"Björn"' and listed["shifts"]["value"] == "1"
        # Its fields are read from memory, never changed through the view.
        assert main(["session", "set", "--name", "o", "last.__0.shifts=3"]) != 0
        assert "inside a value Peeky decodes itself" in capsys.readouterr().err
    finally:
        main(["session", "close", "--name", "o"])
        capsys.readouterr()
