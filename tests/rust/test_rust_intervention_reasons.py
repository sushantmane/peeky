"""Rust interventions with their real reasons and what `describe` says can change
(#183, eighth evaluation's `board`), on real builds."""

import json
import os
import sys

import pytest

from peeky.cli import main

MANIFEST = """[package]
name = "board"
version = "0.1.0"
edition = "2024"

[dependencies]
"""
LOCK = """# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4

[[package]]
name = "board"
version = "0.1.0"
"""
BOARD = """use std::env;

struct Board {
    names: Vec<String>,
    best: Vec<u32>,
    since: Vec<u32>,
    entries: u32,
}

impl Board {
    fn new() -> Board {
        Board { names: Vec::new(), best: Vec::new(), since: Vec::new(), entries: 0 }
    }

    fn record(&mut self, name: &str, score: u32) {
        match self.names.iter().position(|n| n == name) { // RECORD
            Some(i) => {
                if score > self.best[i] {
                    self.best[i] = score;
                }
            }
            None => {
                self.names.push(name.to_string());
                self.best.push(score);
                self.since.push(self.entries);
            }
        }
        self.entries += 1;
    }
}

struct Tri {
    a: i32,
    b: i32,
}

fn array_lit() -> i32 {
    let mut s = Tri { a: 1, b: 2 };
    s.b += 1;
    let k = 7;
    let arr = [s.a, // ARR_1
               k,
               s.b]; // ARR_3
    arr[0] + arr[2]
}

fn main() {
    let mut board = Board::new();
    for entry in env::args().skip(1) {
        let (name, score) = entry.split_once(':').expect("NAME:SCORE"); // ENTRY
        board.record(name, score.parse().expect("a score"));
    }
    let names: Vec<String> = board.names.iter().map(|n| format!("{}={}", n, board.best[0])).collect();
    println!("NAMES:{} ENTRIES:{} ARR:{}", names.join(","), board.entries, array_lit());
}
"""
ARGS = ("--", "alice:50", "bob:60")
# lldb-dap 21 writes memory (macOS here); 18 and 20 cannot, and a String's text is on
# the heap.
WRITES = sys.platform == "darwin"


def line_of(marker):
    return next(i for i, text in enumerate(BOARD.splitlines(), 1) if f"// {marker}" in text)


@pytest.fixture
def crate(tmp_path, monkeypatch):
    names = ("CARGO", "RUSTC", "DAP", "DWARFDUMP", "LINKER")
    if not all(os.environ.get("PEEKY_RUST_" + name) for name in names):
        pytest.skip("set PEEKY_RUST_* tool paths to enable Rust conformance")
    monkeypatch.setenv("PEEKY_STATE_DIR", str(tmp_path / "state"))
    root = tmp_path / "board"
    (root / "src").mkdir(parents=True)
    (root / "Cargo.toml").write_text(MANIFEST)
    (root / "Cargo.lock").write_text(LOCK)
    (root / "src/main.rs").write_text(BOARD)
    return root


def probe(capsys, crate, line, capture, *argv):
    at = ["probe", str(crate), "--at", f"src/main.rs:{line}", "--capture", capture]
    code = main([*at, *argv, "--json", "--quiet", *ARGS])
    return code, json.loads(capsys.readouterr().out)


@pytest.mark.timeout(400)
def test_a_loop_binding_is_changed_at_the_bodys_first_line(crate, capsys):
    # `for entry in args`: at the body's first line, `entry` was refused as "a statement
    # under way at the stop has already read it into a temporary (... at its second
    # line)": the iterator's `next()` result, made before `entry` took its value.
    code, result = probe(capsys, crate, line_of("ENTRY"), "entry", "--set", 'entry="zed:50"')
    if WRITES:
        assert code == 0, result.get("error")
        assert "NAMES:zed=50,bob=50" in result["output"], result["output"]
    else:
        assert code == 1 and "cannot write memory" in result["error"]["message"], result
    assert "statement under way" not in json.dumps(result)


@pytest.mark.timeout(400)
def test_a_statements_later_line_is_refused_before_the_run_naming_where_it_read(crate, capsys):
    # Every stop at `s.b];` is inside `let arr = [s.a, k, s.b];`, which read `s.a` into
    # a temporary at its first line: no stop there can change `s.a` for it.
    first, last = line_of("ARR_1"), line_of("ARR_3")
    code, result = probe(capsys, crate, last, "s.a", "--set", "s.a=50")
    assert code == 2 and result.get("refused_before_launch") is True, result
    message = result["error"]["message"]
    assert f"`s.a` cannot be changed at src/main.rs:{last}, at any stop" in message, message
    assert f"has already read `s` into a temporary (at line {first})" in message, message
    assert "Change it at the first line of that statement" in message, message
    # At its first line, the change reaches it.
    code, result = probe(capsys, crate, first, "s.a", "--set", "s.a=50")
    assert code == 0 and "ARR:53" in result["output"], result


@pytest.mark.timeout(400)
def test_rows_name_rust_types_and_why_a_field_stays_raw(crate, capsys):
    code, result = probe(capsys, crate, line_of("RECORD"), "self.names,self.best,self.entries")
    assert code == 0, result.get("error")
    rows = {row["selector"]: row for row in result["rows"]}
    # As the program spells them, LLDB's own kept alongside.
    assert rows["self.best"]["type"] == "Vec<u32>", rows["self.best"]
    assert (
        rows["self.best"]["debugger_type"] == "alloc::vec::Vec<unsigned int, alloc::alloc::Global>"
    )
    assert rows["self.names"]["type"] == "Vec<String>", rows["self.names"]
    # A Vec<String> field says why it shows LLDB's summary, as a listing of `self` does.
    assert "Peeky does not read the elements of a Vec<String>" in rows["self.names"]["note"]
    at = ["session", "start", str(crate), "--at", f"src/main.rs:{line_of('RECORD')}"]
    assert main([*at, *ARGS]) == 0
    capsys.readouterr()
    try:
        assert main(["session", "get", "self"]) == 0
        listed = capsys.readouterr().out
    finally:
        main(["session", "close"])
        capsys.readouterr()
    assert "self.names: Vec<String> = " in listed, listed
    assert "note: self.names shows LLDB's summary, not contents: Peeky does not read" in listed


@pytest.mark.timeout(400)
def test_describe_lists_the_settable_paths_and_the_edit_for_the_rest(crate, capsys):
    assert main(["describe", str(crate)]) == 0
    out = capsys.readouterr().out
    [mutable] = [line for line in out.splitlines() if line.startswith("mutable:")]
    # `board.entries`, not `board` (whose Vecs' elements are not settable), and not the
    # `&str` parameter `name`, whose length is not the program's to change.
    assert "Such fields and elements (`[*]`: any element): " in mutable, mutable
    assert "board::main: board.entries" in mutable, mutable
    assert "board::Board::record: name" not in mutable, mutable
    assert "String root locals to a text in double quotes" in mutable, mutable
    assert "nor is anything in board::Board::record" in mutable, mutable
    assert mutable.endswith("keeps a local in memory: COOKBOOK 6.6)"), mutable
    assert "board (board::Board, " in out and "names (Vec<String>, " in out, out
