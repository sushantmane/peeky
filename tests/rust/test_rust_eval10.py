"""The tenth agent evaluation's Rust Lows on real builds: `describe` lists the bindings a
`?` desugars to (prep 7), and a refused change through a `for` loop's item said to change
it "before the call that passed it", though no call passed it (prep 9)."""

import json
import os

import pytest

from peeky.cli import main

MANIFEST = """[package]
name = "eval10"
version = "0.1.0"
edition = "2024"

[dependencies]
"""
LOCK = """# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4

[[package]]
name = "eval10"
version = "0.1.0"
"""
MAIN = """use std::num::ParseIntError;

struct Expense {
    payer: *const i64,
    cents: i64,
}

fn parse(text: &str) -> Result<i64, ParseIntError> {
    let cents: i64 = text.trim().parse()?; // TRY
    let val = cents + 1; // OWN_VAL
    let residual = val * 2; // OWN_RESIDUAL
    Ok(residual)
}

fn both(text: &str) -> Result<i64, ParseIntError> {
    let val: i64 = text.parse()?; // SAME_LINE
    Ok(val)
}

fn credit(e: &Expense) -> i64 {
    e.cents + 1 // PARAM
}

fn settle(expenses: &[Expense]) -> i64 {
    let mut total = 0;
    for e in expenses {
        total += credit(e); // ITEM
    }
    total
}

fn main() {
    let one = 1i64;
    let expenses = vec![
        Expense { payer: &one, cents: parse("4").unwrap_or(0) },
        Expense { payer: &one, cents: both("x").unwrap_or(7) },
    ];
    let paid = settle(&expenses);
    println!("{} {}", paid, expenses[0].payer == expenses[1].payer);
}
"""


@pytest.fixture
def crate(tmp_path, monkeypatch):
    names = ("CARGO", "RUSTC", "DAP", "DWARFDUMP", "LINKER")
    if not all(os.environ.get("PEEKY_RUST_" + name) for name in names):
        pytest.skip("set PEEKY_RUST_* tool paths to enable Rust conformance")
    monkeypatch.setenv("PEEKY_STATE_DIR", str(tmp_path / "state"))
    root = tmp_path / "eval10"
    (root / "src").mkdir(parents=True)
    (root / "Cargo.toml").write_text(MANIFEST)
    (root / "Cargo.lock").write_text(LOCK)
    (root / "src/main.rs").write_text(MAIN)
    return root


def line_of(marker):
    return next(i for i, line in enumerate(MAIN.splitlines(), 1) if f"// {marker}" in line)


@pytest.mark.timeout(400)
def test_describe_leaves_out_what_a_question_mark_binds(crate, capsys):
    assert main(["describe", str(crate), "--json"]) == 0
    scopes = {scope["scope"]: scope for scope in json.loads(capsys.readouterr().out)["scopes"]}
    parse = scopes["eval10::parse"]
    # Before: `residual @ main.rs:9`, `residual @ main.rs:11`, `val @ main.rs:9` and
    # `val @ main.rs:10`. The program's own `val` and `residual` stay, each now the one
    # binding of its name.
    assert parse["names"] == ["cents", "residual", "text", "val"], parse
    assert parse["types"]["residual"] == "i64" and parse["types"]["val"] == "i64", parse
    # A `val` of the program's on a line with a `?`: the line's two `val`s, which Peeky
    # can't tell apart by line, are both listed (shown when unsure); its `residual` is not.
    same = scopes["eval10::both"]
    assert "residual" not in json.dumps(same["names"]), same
    assert any(name.startswith("val") for name in same["names"]), same


def _refused(capsys, crate, marker, assignment):
    at = f"src/main.rs:{line_of(marker)}"
    code = main(["probe", str(crate), "--at", at, "--capture", "e", "--set", assignment, "--json"])
    result = json.loads(capsys.readouterr().out)
    assert code == 2 and result.get("refused_before_launch") is True, result
    return result["error"]


@pytest.mark.timeout(400)
def test_a_loop_items_field_gives_no_call_advice(crate, capsys):
    # kitty: `--set e.payer=0` in `settle` said "change the value where it is owned,
    # before the call that passed it: `--at <call line> …`"; `e` is a `for` item.
    error = _refused(capsys, crate, "ITEM", "e.cents=0")
    assert error["code"] == "MUTATION_REJECTED", error
    message = error["message"]
    assert "`e` is a local here, not a parameter, so no call passed it" in message, message
    assert "before the call that passed it" not in message, message
    assert "call" not in error["hint"], error["hint"]
    # A reference parameter keeps the advice: a call passed it.
    error = _refused(capsys, crate, "PARAM", "e.cents=0")
    assert "before the call that passed it" in error["message"], error
    assert "not a parameter" not in error["message"], error


@pytest.mark.timeout(400)
def test_a_sessions_set_through_a_loop_item_gives_no_call_advice(crate, capsys):
    assert main(["session", "start", str(crate), "--at", f"src/main.rs:{line_of('ITEM')}"]) == 0
    capsys.readouterr()
    try:
        assert main(["session", "set", "e.cents=0", "--json"]) == 2
        error = json.loads(capsys.readouterr().out)["error"]
        assert error["code"] == "MUTATION_REJECTED", error
        assert "not a parameter, so no call passed it" in error["message"], error
        assert "before the call that passed it" not in error["message"], error
    finally:
        main(["session", "close"])
        capsys.readouterr()
