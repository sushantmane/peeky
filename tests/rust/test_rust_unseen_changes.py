"""#330 (found preparing the twelfth evaluation): after the program copied a local (into a
binding, or into a Vec by `push`), a change to it was `[settable]` where the program then
replaced or ended the local before it used the copy. `--set y=100` after `u.push(y);`, at
`let t = n;` before `y = t;`, was reported, and `u` printed the old value. Now such a change
is refused, and so is one where no path reads the value again: it is overwritten, or it goes
out of scope, first. A change still works before the copy, and where the program reads the
local again before replacing it."""

import json
import os

import pytest

from peeky.cli import main

MANIFEST = """[package]
name = "{name}"
version = "0.1.0"
edition = "2024"

[dependencies]
"""
LOCK = """# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4

[[package]]
name = "{name}"
version = "0.1.0"
"""
UNSEEN = """use std::env;

#[derive(Clone, Copy, Debug)]
struct Lap {
    number: u32,
    start: u32,
    end: u32,
}

#[inline(never)]
fn other() -> u32 {
    1
}

fn pushed(n: u32) -> String {
    let mut y = n + 7;
    let mut u: Vec<u32> = Vec::new();
    u.push(y); // PUSH
    let t = n; // PUSHED
    y = t; // REPLACED
    format!("{y} {u:?}")
}

fn plain(n: u32) -> String {
    let mut x = n + 9;
    let z = x; // COPY
    let k = n; // PLAIN
    x = k;
    format!("{x} {z}")
}

fn laps(reads: &[u32]) -> String {
    let mut laps: Vec<Lap> = Vec::new();
    let mut start = 0;
    for &at in reads {
        let mut lap = Lap { number: laps.len() as u32 + 1, start, end: at };
        laps.push(lap); // LAPPED
        let finish = lap.end; // FINISH
        lap.start = finish; // FIELD
        start = lap.start;
    }
    let times: Vec<String> = laps.iter().map(|l| format!("{}:{}", l.number, l.end - l.start)).collect();
    times.join("/")
}

fn summed(n: u32) -> String {
    let mut x = n + 5;
    let mut w: Vec<u32> = Vec::new();
    w.push(x);
    let s: u32 = w.iter().sum(); // SUMMED
    x = s;
    format!("{x} {w:?}")
}

fn read_later(n: u32) -> String {
    let mut x = n + 5;
    let mut w: Vec<u32> = Vec::new();
    w.push(x);
    let k = other(); // READ_LATER
    let s = x + k;
    x = s;
    format!("{x} {w:?}")
}

fn overwritten(n: u32) -> u32 {
    let mut total = n + 1;
    let k = other(); // BEFORE_TOTAL
    total = k + n; // TOTAL
    let r = total * 2; // AFTER_TOTAL
    r
}

fn scoped(n: u32) -> u32 {
    let mut b = 0;
    if n > 0 {
        let mut a = n + 1;
        a *= 3;
        std::hint::black_box(a); // SCOPE_READ
        b = other(); // SCOPE_DEAD
    }
    b
}

fn param(mut x: u32) -> u32 {
    std::hint::black_box(&mut x);
    let z = x; // PARAM_COPY
    let k = other(); // PARAM
    z + k
}

fn main() {
    let n: u32 = env::args().nth(1).unwrap().parse().unwrap();
    let reads: Vec<u32> = env::args().skip(2).map(|a| a.parse().unwrap()).collect();
    println!("PUSHED {}", pushed(n));
    println!("PLAIN {}", plain(n));
    println!("LAPS {}", laps(&reads));
    println!("SUMMED {}", summed(n));
    println!("LATER {}", read_later(n));
    println!("TOTAL {}", overwritten(n));
    println!("SCOPED {}", scoped(n));
    println!("PARAM {}", param(n));
}
"""

# Review of PR #334: a type's own `Drop` reads what it drops; a panic, `process::exit` or a
# coroutine's exit ends the frame's locals; a refusal names where a value ends only where
# every path ends there. Each run takes what to do first.
FRAMES = """use std::env;
use std::hint::black_box;
use std::pin::pin;
use std::task::{Context, Waker};

struct D(u32, u32);

impl Drop for D {
    fn drop(&mut self) {
        println!("DROP {}", self.0);
    }
}

#[inline(never)]
fn other() -> u32 {
    1
}

fn scoped(n: u32) -> u32 {
    let d = D(n + 1, n);
    let z = d.0;
    let k = other(); // DROP_SCOPED
    z + k
}

fn taken(d: D) -> u32 {
    let z = d.0;
    let k = other(); // DROP_TAKEN
    z + k
}

struct S {
    name: String,
    n: u32,
}

fn named(n: u32) -> u32 {
    let s = S { name: n.to_string(), n: n + 1 };
    let z = s.n; // NAMED_COPY
    let k = other(); // NAMED
    z + k
}

async fn exited(n: u32) {
    let mut x = n + 1;
    black_box(&mut x);
    let z = x; // ASYNC_COPY
    let k = other(); // ASYNC
    println!("ASYNC {}", z + k);
    std::process::exit(0);
}

fn pointed(n: u32) -> ! {
    let x = n + 1;
    let r = &x;
    let z = x; // POINTER_COPY
    let k = other(); // POINTER
    println!("POINTER {}", z + k);
    black_box(r);
    std::process::exit(0);
}

fn branch(n: u32) -> u32 {
    let mut total = n + 1;
    let k = other(); // BRANCH
    if n > 100 {
        panic!("too many");
    }
    total = k + n; // BRANCH_WRITE
    total
}

fn spin(n: u32) -> u32 {
    let mut total = n + 1;
    let k = other(); // SPIN
    if n > 100 {
        loop {
            black_box(k);
        }
    }
    total = k + n; // SPIN_WRITE
    total
}

fn main() {
    let args: Vec<String> = env::args().collect();
    let n: u32 = args[2].parse().unwrap();
    match args[1].as_str() {
        "drop" => println!(
            "SCOPED {} TAKEN {} NAMED {}",
            scoped(n),
            taken(D(n + 5, n)),
            named(n)
        ),
        "async" => {
            let mut fut = pin!(exited(n));
            let _ = fut.as_mut().poll(&mut Context::from_waker(Waker::noop()));
        }
        "pointer" => pointed(n),
        _ => println!("BRANCH {} SPIN {}", branch(n), spin(n)),
    }
}
"""
# The same exits in a crate with unsafe code of its own, where the never-read rule is off.
EXITS = """use std::env;
use std::hint::black_box;

#[inline(never)]
fn other() -> u32 {
    1
}

fn argument(mut x: u32) -> ! {
    black_box(&mut x);
    let z = x; // ARG_COPY
    let k = other(); // ARG
    println!("ARG {}", z + k);
    std::process::exit(0);
}

fn local(n: u32) -> ! {
    let mut x = n + 1;
    black_box(&mut x);
    let z = x; // LOCAL_COPY
    let k = other(); // LOCAL
    println!("LOCAL {}", z + k);
    std::process::exit(0);
}

fn main() {
    let args: Vec<String> = env::args().collect();
    let n: u32 = args[2].parse().unwrap();
    let read = [n];
    // Unsafe code of its own, unrelated to `x`.
    let first = unsafe { *read.as_ptr() };
    if args[1] == "arg" { argument(first) } else { local(first) }
}
"""
TEXTS = {"unseen": UNSEEN, "frames": FRAMES, "exits": EXITS}


def line_of(marker, text=UNSEEN):
    lines = enumerate(text.splitlines(), 1)
    return next(i for i, line in lines if line.endswith(f"// {marker}"))


RUN = ("--", "1", "100", "250")


@pytest.fixture
def crate(tmp_path, monkeypatch):
    names = ("CARGO", "RUSTC", "DAP", "DWARFDUMP", "LINKER")
    if not all(os.environ.get("PEEKY_RUST_" + name) for name in names):
        pytest.skip("set PEEKY_RUST_* tool paths to enable Rust conformance")
    monkeypatch.setenv("PEEKY_STATE_DIR", str(tmp_path / "state"))
    for name, text in TEXTS.items():
        root = tmp_path / name
        (root / "src").mkdir(parents=True)
        (root / "Cargo.toml").write_text(MANIFEST.format(name=name))
        (root / "Cargo.lock").write_text(LOCK.format(name=name))
        (root / "src/main.rs").write_text(text)
    return tmp_path / "unseen"


def probe(capsys, root, marker, *argv, run=RUN):
    line = line_of(marker, TEXTS[root.name])
    at = ["probe", str(root), "--at", f"src/main.rs:{line}", "--json", "--quiet"]
    code = main([*at, *argv, *run])
    return code, json.loads(capsys.readouterr().out)


def changed(capsys, root, marker, *argv, run=RUN):
    """The output's lines of a probe whose `--set` is made."""
    code, result = probe(capsys, root, marker, *argv, run=run)
    assert code == 0, result.get("error")
    assert result.get("set_outcomes") or result["output"], result
    return result["output"].splitlines()


def refused(capsys, root, marker, *argv, run=RUN):
    """The message of a refusal made before the program runs."""
    code, result = probe(capsys, root, marker, *argv, run=run)
    error = result.get("error") or {}
    assert code == 2 and error.get("code") == "MUTATION_REJECTED", result
    assert result.get("refused_before_launch") is True and not result["rows"], result
    return error["message"]


def row(capsys, root, marker, selector):
    code, result = probe(capsys, root, marker, "--capture", selector)
    assert code == 0, result.get("error")
    (found,) = [each for each in result["rows"] if each["selector"] == selector]
    return found


@pytest.mark.timeout(400)
def test_a_copy_used_after_the_local_is_replaced_refuses_the_change(crate, capsys):
    # The issue: `u.push(y);`, `let t = n;`, `y = t;`, then `u` printed. On the main branch,
    # `--set y=100` at `let t = n;` was reported, and the output was `PUSHED 1 [8]`.
    for marker in ("PUSHED", "REPLACED"):
        message = refused(capsys, crate, marker, "--set", "y=100")
        assert "the program's own `u` (at lines " in message, message
        assert "may hold a copy of `y` that it goes on with" in message, message
    # Before the push, the change reaches `u`.
    assert "PUSHED 1 [100]" in changed(capsys, crate, "PUSH", "--set", "y=100")
    # A plain copy: `let z = x;`, `let k = n;`, `x = k;`, then `z` printed.
    message = refused(capsys, crate, "PLAIN", "--set", "x=100")
    assert (
        f"the program has already copied `x` into `z` (at line {line_of('COPY')}) and goes on "
        "with that copy"
    ) in message, message
    assert "PLAIN 1 100" in changed(capsys, crate, "COPY", "--set", "x=100")
    # An argument copied, then never read again before the function returns.
    message = refused(capsys, crate, "PARAM", "--set", "x=100")
    assert (
        f"the program has already copied `x` into `z` (at line {line_of('PARAM_COPY')})"
    ) in message, message
    assert "PARAM 101" in changed(capsys, crate, "PARAM_COPY", "--set", "x=100")


@pytest.mark.timeout(400)
def test_a_struct_pushed_then_written_refuses_a_change_to_the_field(crate, capsys):
    # `laps.push(lap);`, `let finish = lap.end;`, `lap.start = finish;`: `lap.start` is
    # never read again, and `lap` ends before `laps` is used.
    assert row(capsys, crate, "FINISH", "lap.start").get("settable") is not True
    for marker in ("FINISH", "FIELD"):
        message = refused(capsys, crate, marker, "--set", "lap.start=40")
        assert "the program's own `laps` (at lines " in message, message
        assert "may hold a copy of `lap` that it goes on with" in message, message
    # At the push, the change reaches the Vec: the first lap is 100 - 40.
    assert "LAPS 1:60/2:150" in changed(capsys, crate, "LAPPED", "--set", "lap.start=40")


@pytest.mark.timeout(400)
def test_a_value_never_read_again_is_refused_saying_where(crate, capsys):
    total, scope = line_of("TOTAL"), line_of("SCOPE_DEAD") + 1
    for marker in ("BEFORE_TOTAL", "TOTAL"):
        message = refused(capsys, crate, marker, "--set", "total=100")
        assert (
            f"the program does not read `total` after any stop of line {line_of(marker)}, so a "
            f"change there would never be seen: it is overwritten at line {total} first"
        ) in message, message
        assert (
            "Change it on a later line, after the program overwrites it, or on an earlier line, "
            "before the program's last read of it (`--set-at` there)"
        ) in message, message
    assert row(capsys, crate, "TOTAL", "total")["not_settable"] == (
        f"not read after the stop (overwritten at line {total})"
    )
    message = refused(capsys, crate, "SCOPE_DEAD", "--set", "a=100")
    assert (
        f"the program does not read `a` after any stop of line {scope - 1}, so a change there "
        f"would never be seen: it goes out of scope at line {scope} first"
    ) in message, message
    assert "Change it on an earlier line, before the program's last read of it" in message
    # Where the program reads it next, a change works.
    assert "TOTAL 200" in changed(capsys, crate, "AFTER_TOTAL", "--set", "total=100")
    code, result = probe(capsys, crate, "SCOPE_READ", "--set", "a=100")
    assert code == 0, result.get("error")


@pytest.mark.timeout(400)
def test_a_local_read_again_before_it_is_replaced_stays_settable(crate, capsys):
    # `w.push(x);`, then `let s = x + k;` reads `x` before `x = s;`: the change is seen.
    assert row(capsys, crate, "READ_LATER", "x").get("settable") is True
    assert "LATER 101 [6]" in changed(capsys, crate, "READ_LATER", "--set", "x=100")
