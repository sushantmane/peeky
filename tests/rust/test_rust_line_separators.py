r"""A U+2028 in a source file's name. rustc's MIR and Cargo's messages print it as it is,
dwarfdump in octal (`x\342\200\250y.rs`) or as it is (`DW_AT_decl_file`), LLVM IR in hex
(`x\E2\80\A8y.rs`). Split at the U+2028, or with the escapes read as other characters, a
module so named could not be debugged, nor its MIR proofs read."""

import json
import os

import pytest

from peeky.cli import main

MANIFEST = """[package]
name = "{name}"
version = "0.1.0"
edition = "2024"

[dependencies]
"""
LOCK = """# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4

[[package]]
name = "{name}"
version = "0.1.0"
"""
MODULE = "x\u2028y.rs"
MAIN = f"""#[path = "{MODULE}"]
mod odd;

fn main() {{
    let n = std::hint::black_box(20);
    let r = odd::f(n);
    println!("{{r}}");
}}
"""
ODD = """pub fn f(n: i64) -> i64 {
    let doubled = n * 2;
    let total = doubled + 1;
    let parts = vec![n, doubled, total];
    println!("{total} {}", parts.len()); // STOP
    total
}
"""


@pytest.fixture
def crate(tmp_path, monkeypatch):
    names = ("CARGO", "RUSTC", "DAP", "DWARFDUMP", "LINKER")
    if not all(os.environ.get("PEEKY_RUST_" + name) for name in names):
        pytest.skip("set PEEKY_RUST_* tool paths to enable Rust conformance")
    monkeypatch.setenv("PEEKY_STATE_DIR", str(tmp_path / "state"))
    root = tmp_path / "odd"
    (root / "src").mkdir(parents=True)
    (root / "Cargo.toml").write_text(MANIFEST.format(name="odd"))
    (root / "Cargo.lock").write_text(LOCK.format(name="odd"))
    (root / "src/main.rs").write_text(MAIN)
    (root / "src" / MODULE).write_text(ODD)
    return root


@pytest.mark.timeout(400)
def test_a_module_named_with_a_line_separator_is_debugged(crate, capsys):
    line = ODD.split("\n").index(next(x for x in ODD.split("\n") if "// STOP" in x)) + 1
    at = f"src/{MODULE}:{line}"
    code = main(["probe", str(crate), "--at", at, "--capture", "n,doubled,total,parts", "--json"])
    result = json.loads(capsys.readouterr().out)
    assert code == 0, result.get("error")
    rows = {row["selector"]: row for row in result["rows"]}
    assert [rows[name]["value"] for name in ("n", "doubled", "total")] == ["20", "40", "41"]
    parts = rows["parts"]
    if os.environ.get("PEEKY_EXPECT_READ_MEMORY") or parts.get("view") == "memory":
        # Read under the MIR's proof, which matches the IR's (hex-escaped) file name.
        assert parts["value"] == "[20, 40, 41]" and parts["view"] == "memory", parts
    else:
        assert "the debugger gives no memory address for it" in parts.get("note", ""), parts
    assert "41 3" in result["output"]
