"""#156: a Vec, String, &str or Box<str> field reads its contents where what holds it
cannot change or be freed while the frame stands: through a reference parameter the
IR proves live (`&mut` only in the innermost frame), or inside a local the MIR proves
initialized at the stop. Anything else stays raw, with the reason on its row."""

import json
import os

import pytest

from peeky.cli import main

MANIFEST = """[package]
name = "{name}"
version = "0.1.0"
edition = "2024"

[dependencies]
"""
LOCK = """# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4

[[package]]
name = "{name}"
version = "0.1.0"
"""
# The seventh evaluation's `movavg`, as the agent saw it.
MOVAVG = """use std::env;

/// Rolling mean over the last `k` values, printed with one decimal after each value.
struct Window {
    k: usize,
    values: Vec<i64>,
    sum: i64,
}

impl Window {
    fn push(&mut self, v: i64) -> f64 {
        self.values.push(v);
        self.sum += v; // PUSHED
        if self.values.len() >= self.k {
            let old = self.values.remove(0);
            self.sum -= old;
        }
        self.sum as f64 / self.values.len() as f64
    }
}

fn main() {
    let args: Vec<String> = env::args().collect();
    let k: usize = args[1].parse().unwrap();
    let mut w = Window { k, values: Vec::new(), sum: 0 };
    let mut out = Vec::new();
    for v in args[2].split(',') {
        let mean = w.push(v.parse().unwrap());
        out.push(format!("{:.1}", mean)); // MEAN
    }
    println!("MEANS:{}", out.join(","));
}
"""
FIELDS = """use std::cell::RefCell;

#[derive(Debug, Clone, Copy)]
struct Point {
    x: i32,
    y: i32,
}

struct Inner {
    items: Vec<u16>,
}

struct Bag {
    values: Vec<i64>,
    name: String,
    boxed: Box<str>,
    points: Vec<Point>,
    inner: Inner,
    pair: (u8, Vec<i32>),
    cell: RefCell<Vec<i64>>,
}

struct Named<'a> {
    label: &'a str,
    count: u32,
}

struct Wrap<T> {
    items: Vec<T>,
}

struct Tagged {
    tag: &'static str,
    counts: Vec<i64>,
}

impl Bag {
    fn total(&self) -> i64 {
        self.values.iter().sum::<i64>() + self.inner.items.len() as i64 // TOTAL
    }

    fn report(&self) -> i64 {
        let t = self.total(); // REPORT
        t + self.cell.borrow().len() as i64
    }

    fn grow(&mut self, v: i64) -> i64 {
        self.values.push(v); // GROW
        self.name.push('!');
        self.report()
    }
}

fn show(n: &Named) -> usize {
    n.label.len() + n.count as usize // SHOW
}

fn peek<T: Copy>(w: &Wrap<T>) -> usize {
    w.items.len() // PEEK
}

fn main() {
    let args: Vec<String> = std::env::args().collect();
    let text = format!("t{}", args.len());
    let mut bag = Bag {
        values: vec![3, 6],
        name: String::from("bag"),
        boxed: "boxed".into(),
        points: vec![Point { x: 1, y: 2 }],
        inner: Inner { items: vec![7, 8, 9] },
        pair: (1, vec![4, 5]),
        cell: RefCell::new(vec![2]),
    };
    let held = Box::new(Inner { items: vec![5] });
    let named = Named { label: &text, count: 2 };
    let tagged = Tagged { tag: "static", counts: vec![1] };
    let shown = show(&named) + held.items.len() + tagged.counts.len(); // NAMED
    let g = bag.grow(9); // MAIN
    let peeked = peek(&Wrap { items: vec![1u8, 2] }) + peek(&Wrap { items: vec!['a'] });
    let moved = bag; // MOVE
    println!("{} {} {} {}", g, peeked, moved.values.len(), shown); // AFTER
    let taken = moved.name;
    println!("{} {}", taken, moved.values.len()); // PARTIAL
}
"""

BORROWS = """fn tally(n: usize) -> usize {
    n * 2
}

fn main() {
    let args: Vec<String> = std::env::args().collect();
    let mut owned = format!("a{},b", args.len());
    let mut total = 0;
    for v in args[1].split('/') {
        total += tally(v.len());
        total += 1; // FROZEN
    }
    let w: &str = owned.split(',').next().unwrap();
    total += tally(w.len());
    owned.push_str(" and more text, to grow it past its capacity");
    total += owned.len(); // THAWED
    println!("TOTAL {}", total);
}
"""


def crate_at(tmp_path, name, text):
    root = tmp_path / name
    (root / "src").mkdir(parents=True)
    (root / "Cargo.toml").write_text(MANIFEST.format(name=name))
    (root / "Cargo.lock").write_text(LOCK.format(name=name))
    (root / "src/main.rs").write_text(text)
    return root


@pytest.fixture
def state(tmp_path, monkeypatch):
    names = ("CARGO", "RUSTC", "DAP", "DWARFDUMP", "LINKER")
    if not all(os.environ.get("PEEKY_RUST_" + name) for name in names):
        pytest.skip("set PEEKY_RUST_* tool paths to enable Rust conformance")
    monkeypatch.setenv("PEEKY_STATE_DIR", str(tmp_path / "state"))
    return tmp_path / "state"


def line_of(text, marker):
    return next(i for i, line in enumerate(text.splitlines(), 1) if marker in line)


def probe(capsys, crate, text, marker, selectors, *argv):
    at = f"src/main.rs:{line_of(text, marker)}"
    code = main(["probe", str(crate), "--at", at, "--capture", selectors, *argv, "--json"])
    result = json.loads(capsys.readouterr().out)
    assert code == 0, result.get("error")
    return result


def reads(row):
    """Whether this debugger reads memory (lldb-dap from LLVM 20); lldb-dap 18 does not."""
    return bool(os.environ.get("PEEKY_EXPECT_READ_MEMORY")) or row.get("view") == "memory"


def raw(row, *why):
    """A row left as LLDB shows it, whose note gives the reason."""
    assert row.get("view") is None and "@ 0x" in row["value"], row
    note = row.get("note") or ""
    assert "shows LLDB's summary (its type and address), not its contents" in note, row
    assert "(#53)" not in note and "may be moved, dropped or not yet assigned around" not in note
    for each in why:
        assert each in note, (each, note)


NO_MEMORY = "the debugger gives no memory address for it"


@pytest.mark.timeout(400)
def test_the_movavg_window_reads_its_values_through_self(tmp_path, state, capsys):
    # Seventh evaluation: `self.values` (a Vec<i64> behind `&mut self`) showed only LLDB's
    # summary with a warning about an owned local that may be moved (#53), and
    # `self.values[0]` was "not found ... Capture values.len".
    crate = crate_at(tmp_path, "movavg", MOVAVG)
    selectors = "self.values,self.values[0],self.values[-1],self.values.len,self.sum"
    result = probe(
        capsys,
        crate,
        MOVAVG,
        "// PUSHED",
        selectors,
        "--arg",
        "3",
        "--arg",
        "3,6,9,12",
        "--hits",
        "2",
    )
    rows = [{row["selector"]: row for row in result["rows"] if row["hit"] == h} for h in (1, 2)]
    if reads(rows[0]["self.values"]):
        assert [row["self.values"]["value"] for row in rows] == ["[3]", "[3, 6]"], rows
        assert rows[1]["self.values[0]"]["value"] == "3", rows
        assert rows[1]["self.values[-1]"]["value"] == "6", rows
        assert rows[1]["self.values.len"]["value"] == "2", rows
        assert not any("#53" in warning for warning in result["warnings"]), result["warnings"]
    else:
        raw(rows[0]["self.values"], NO_MEMORY, "Capture self.values.len for the length")
        error = rows[0]["self.values[0]"]["error"]
        assert NO_MEMORY in error and "Capture self.values.len" in error, error
    # main's `w`, which the MIR proves initialized (`w.sum` is [settable]), reads too.
    result = probe(capsys, crate, MOVAVG, "// MEAN", "w.values,w.sum", "--arg", "3", "--arg", "3,6")
    rows = {row["selector"]: row for row in result["rows"] if row["hit"] == 1}
    assert rows["w.sum"]["settable"] is True, rows
    if reads(rows["w.values"]):
        assert rows["w.values"]["value"] == "[3]", rows
    else:
        raw(rows["w.values"], NO_MEMORY)


@pytest.mark.timeout(400)
def test_fields_read_through_a_reference_and_in_a_proven_local(tmp_path, state, capsys):
    crate = crate_at(tmp_path, "fields", FIELDS)
    selectors = [
        "self.values",
        "self.name",
        "self.boxed",
        "self.points",
        "self.inner.items",
        "self.inner.items[-1]",
        "self.pair.__1",
        "self.cell.value.value",
    ]
    result = probe(capsys, crate, FIELDS, "// GROW", ",".join(selectors))
    rows = {row["selector"]: row for row in result["rows"]}
    if reads(rows["self.values"]):
        assert {name: rows[name]["value"] for name in selectors[:-1]} == {
            "self.values": "[3, 6]",
            "self.name": '"bag"',
            "self.boxed": '"boxed"',
            "self.points": "[Point { x: 1, y: 2 }]",
            "self.inner.items": "[7, 8, 9]",
            "self.inner.items[-1]": "9",
            "self.pair.__1": "[4, 5]",
        }, rows
    else:
        raw(rows["self.values"], NO_MEMORY)
    # A RefCell's contents change behind `&self`: never read.
    raw(rows["self.cell.value.value"], "`self.cell` is a standard-library type (RefCell<")
    # In main: the proven local, a Box's contents, and a generic's instances (#130).
    names = "bag.values,bag.inner.items,held.items,named.label"
    rows = {row["selector"]: row for row in probe(capsys, crate, FIELDS, "// NAMED", names)["rows"]}
    if reads(rows["bag.values"]):
        assert [rows[name]["value"] for name in names.split(",")] == [
            "[3, 6]",
            "[7, 8, 9]",
            "[5]",
            '"t1"',
        ], rows
    # `named.label` borrows `text`: past `named`'s last use and a call, #110 cannot show
    # what it borrows still stands, so nothing in `named` is read (it reads where it is
    # used). A struct with no lifetime holds only `&'static str`: `tagged.tag` reads.
    names = "named.label,tagged.tag,tagged.counts"
    rows = {row["selector"]: row for row in probe(capsys, crate, FIELDS, "// AFTER", names)["rows"]}
    error = rows["named.label"]["error"]
    assert "cannot expand 'named'" in error and "#110" in error, error
    if reads(rows["tagged.tag"]):
        assert (rows["tagged.tag"]["value"], rows["tagged.counts"]["value"]) == ('"static"', "[1]")
    result = probe(capsys, crate, FIELDS, "// PEEK", "w.items", "--hits", "2")
    if reads(result["rows"][0]):
        assert [row["value"] for row in result["rows"]] == ["[1, 2]", "['a']"], result["rows"]


@pytest.mark.timeout(400)
def test_a_moved_or_partly_moved_struct_keeps_its_fields_raw(tmp_path, state, capsys):
    crate = crate_at(tmp_path, "moved", FIELDS)
    rows = {
        row["selector"]: row
        for row in probe(capsys, crate, FIELDS, "// AFTER", "bag.values,moved.values")["rows"]
    }
    # `bag` was moved into `moved`: its bytes are a moved-from copy (#108), which its
    # note says (not that an owned local may be moved, #53).
    assert rows["bag.values"].get("view") is None and rows["bag.values"].get("stale"), rows
    assert rows["bag.values"]["note"].startswith("This is (or is inside) a Rust local"), rows
    if reads(rows["moved.values"]):
        assert rows["moved.values"]["value"] == "[3, 6, 9]", rows
    else:
        raw(rows["moved.values"], NO_MEMORY)
    # `moved.name` was moved out: the struct is partly moved, and nothing in it reads.
    rows = {
        row["selector"]: row
        for row in probe(capsys, crate, FIELDS, "// PARTIAL", "moved.values,moved.name")["rows"]
    }
    for name in ("moved.values", "moved.name"):
        assert rows[name].get("view") is None and rows[name].get("stale"), rows


@pytest.mark.timeout(400)
def test_caller_frames_read_only_through_a_shared_reference(tmp_path, state, capsys):
    crate = crate_at(tmp_path, "frames", FIELDS)
    at = f"src/main.rs:{line_of(FIELDS, '// TOTAL')}"
    assert main(["session", "start", str(crate), "--at", at]) == 0
    capsys.readouterr()
    rows = {}
    try:
        for frame, selector in ((1, "self.values"), (2, "self.values"), (3, "bag.values")):
            assert main(["session", "get", selector, "--frame", str(frame), "--json"]) == 0
            [rows[frame]] = json.loads(capsys.readouterr().out)
        assert main(["session", "get", "self", "--frame", "2"]) == 0
        listing = capsys.readouterr().out
    finally:
        main(["session", "close"])
        capsys.readouterr()
    # `report(&self)`: a shared reference's target cannot change during the call.
    if reads(rows[1]):
        assert rows[1]["value"] == "[3, 6, 9]", rows[1]
    else:
        raw(rows[1], NO_MEMORY)
    # `grow(&mut self)`, and main's `bag`: the call under way may be changing them.
    raw(rows[2], "`self` is a `&mut` parameter of a caller frame")
    raw(rows[3], "`bag` is a local of a caller frame")
    assert "self.values, self.name, self.boxed" in listing, listing
    assert "show LLDB's summary, not contents: `self` is a `&mut` parameter" in listing


@pytest.mark.timeout(400)
def test_a_borrow_of_a_local_nothing_changes_reads_past_its_last_use(tmp_path, state, capsys):
    # Seventh evaluation (Low): `v` of `for v in args[2].split(',')`, past its last use
    # and a call, showed `<not shown: may point at freed memory>`, though it points into
    # `args`, which nothing borrows `&mut`, moves or drops before the end of `main`.
    crate = crate_at(tmp_path, "borrows", BORROWS)
    result = probe(capsys, crate, BORROWS, "// FROZEN", "v", "--arg", "ab/cd", "--hits", "2")
    rows = result["rows"]
    assert [row.get("view") != "unproven" for row in rows] == [True, True], rows
    if reads(rows[0]):
        assert [row["value"] for row in rows] == ['"ab"', '"cd"'], rows
    # `w` points into `owned`, changed (`push_str`, a `&mut` borrow) since its last
    # use: what it pointed at may have been reallocated, so it is never read (#110).
    result = probe(capsys, crate, BORROWS, "// THAWED", "w", "--arg", "ab/cd")
    assert result["rows"][0]["view"] == "unproven", result["rows"]
