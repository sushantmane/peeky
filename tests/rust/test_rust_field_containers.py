# Unsafe code that frees what a value owns behind the MIR's back, soundly (the value is
# never used while it dangles), in every place the stopped function cannot see it: in
# the function, a closure, an `unsafe fn` it calls, through a pointer stored for later,
# after a move, in a caller.
UNSAFE = """use std::hint::black_box;
use std::mem;
use std::ptr::{self, addr_of};

struct W {
    values: Vec<i64>,
    k: usize,
}

struct Outer {
    w: W,
    k: usize,
}

fn mk() -> W {
    W { values: vec![1, 2, 3], k: 2 }
}

impl W {
    #[inline(never)]
    fn rebuild(&mut self) -> usize {
        unsafe { ptr::drop_in_place(&mut self.values) };
        let n = black_box(self.k); // DROPPED_IN_PLACE
        unsafe { ptr::write(&mut self.values, vec![1]) };
        n
    }
}

#[inline(never)]
fn closure_free() -> usize {
    let mut w = mk();
    let mut kill = || unsafe { ptr::drop_in_place(&mut w.values) };
    kill();
    let n = black_box(w.k); // CLOSURE_FREE
    mem::forget(w);
    n
}

/// Safety: the caller must forget `w` or restore `w.values`.
unsafe fn take_values(w: &mut W) {
    drop(unsafe { ptr::read(&w.values) });
}

#[inline(never)]
fn callee() -> usize {
    let mut w = mk();
    unsafe { take_values(&mut w) };
    let n = black_box(w.k); // CALLEE
    mem::forget(w);
    n
}

fn stash(slot: &mut *mut Vec<i64>, v: &mut Vec<i64>) {
    *slot = v;
}

#[inline(never)]
fn out_param() -> usize {
    let mut w = mk();
    let mut p: *mut Vec<i64> = ptr::null_mut();
    stash(&mut p, &mut w.values);
    unsafe { ptr::drop_in_place(p) };
    let n = black_box(w.k); // OUT_PARAM
    mem::forget(w);
    n
}

#[inline(never)]
fn slot() -> usize {
    let mut w = mk();
    let mut slot: Option<&mut Vec<i64>> = None;
    slot.replace(&mut w.values);
    let p: *mut Vec<i64> = slot.take().unwrap();
    unsafe { ptr::drop_in_place(p) };
    let n = black_box(w.k); // SLOT
    mem::forget(w);
    n
}

#[inline(never)]
fn moved_in() -> usize {
    let mut w = mk();
    let p = w.values.as_mut_ptr();
    let h = Outer { w, k: 1 };
    unsafe { drop(Vec::from_raw_parts(p, 3, 3)) };
    let n = black_box(h.k); // MOVED_IN
    mem::forget(h);
    n
}

#[inline(never)]
fn rebound() -> usize {
    let mut w = mk();
    let p = w.values.as_mut_ptr();
    let w = w;
    unsafe { drop(Vec::from_raw_parts(p, 3, 3)) };
    let n = black_box(w.k); // REBOUND
    mem::forget(w);
    n
}

#[inline(never)]
fn look(w: &W) -> usize {
    black_box(w.k) // LOOK
}

#[inline(never)]
fn caller_frees() -> usize {
    let w = mk();
    unsafe { drop(ptr::read(addr_of!(w.values))) };
    let n = look(&w);
    mem::forget(w);
    n
}

#[derive(Debug, Clone, Copy)]
struct Span {
    start: u64,
    end: u64,
}

// Each reads only what the caller left valid: a Vec's length, a struct's fields.
#[inline(never)]
fn look_vec(v: &Vec<i64>) -> usize {
    black_box(v.capacity()) // LOOK_VEC
}

#[inline(never)]
fn look_text(t: &str) -> usize {
    black_box(t.len()) // LOOK_TEXT
}

#[inline(never)]
fn look_span(s: &Span) -> u64 {
    black_box(s.start) // LOOK_SPAN
}

#[inline(never)]
fn lent_freed() -> usize {
    let w = mk();
    unsafe { drop(ptr::read(addr_of!(w.values))) };
    let n = look_vec(&w.values);
    mem::forget(w);
    let s = String::from("some text");
    let m = look_text(s.as_str()) + look_span(&Span { start: 1, end: 2 }) as usize;
    n + m
}

#[derive(Debug)]
struct Pt {
    x: i64,
    y: i64,
}

#[inline(never)]
fn boxed() -> i64 {
    let mut b = Box::new(Pt { x: 1, y: 2 });
    let p: *mut Pt = &mut *b;
    unsafe { drop(Box::from_raw(p)) };
    let n = black_box(3); // BOXED
    mem::forget(b);
    n
}

#[inline(never)]
fn owned_local() -> usize {
    let mut v = vec![1i64, 2, 3];
    let mut kill = || unsafe { ptr::drop_in_place(&mut v) };
    kill();
    let n = black_box(1); // OWNED_LOCAL
    mem::forget(v);
    n
}

#[inline(never)]
fn mutated() -> usize {
    let s = String::from("short");
    let v: &str = s.as_str();
    let n = v.len();
    // Undefined behaviour, which the program never relies on: through a pointer cast
    // from `&s`, the String it borrows grows (and moves) under `v`.
    let p = &s as *const String as *mut String;
    unsafe { (*p).push_str(" and now much longer than before, to move its buffer") };
    black_box(n) // MUTATED
}

fn main() {
    let mut w = W { values: vec![1, 2, 3], k: 4 };
    let total = w.rebuild() + closure_free() + callee() + out_param() + slot() + moved_in()
        + rebound() + caller_frees() + owned_local() + mutated() + lent_freed()
        + boxed() as usize;
    println!("{total}");
}
"""
# A `Vec` a macro declares, with a buffer `unsafe` code regrows
# behind a shared reference.
SHADOWED = """use std::cell::UnsafeCell;
use std::hint::black_box;

macro_rules! decl {
    ($name:ident < $t:ident >) => {
        pub struct $name<$t> {
            inner: UnsafeCell<std::vec::Vec<$t>>,
        }
        impl<$t> $name<$t> {
            pub fn new(v: std::vec::Vec<$t>) -> Self {
                $name { inner: UnsafeCell::new(v) }
            }
            pub fn as_slice(&self) -> &[$t] {
                unsafe { (*self.inner.get()).as_slice() }
            }
            /// Safety: no slice `as_slice` returned may be used afterwards.
            pub unsafe fn regrow(&self, x: $t) {
                let v = unsafe { &mut *self.inner.get() };
                v.shrink_to_fit();
                v.push(x);
            }
        }
    };
}

decl!(Vec<T>);

#[inline(never)]
fn reader(v: &Vec<i64>) -> usize {
    let s: &[i64] = v.as_slice();
    let n = s.len();
    unsafe { v.regrow(99) };
    black_box(n) // SHADOWED
}

fn main() {
    let v = Vec::new(std::vec![1i64, 2, 3]);
    println!("{}", reader(&v));
}
"""


def crate_at(tmp_path, name, text):
    root = tmp_path / name
    (root / "src").mkdir(parents=True)
    (root / "Cargo.toml").write_text(MANIFEST.format(name=name))
    (root / "Cargo.lock").write_text(LOCK.format(name=name))
    (root / "src/main.rs").write_text(text)
    return root


@pytest.fixture
def state(tmp_path, monkeypatch):
    names = ("CARGO", "RUSTC", "DAP", "DWARFDUMP", "LINKER")
    if not all(os.environ.get("PEEKY_RUST_" + name) for name in names):
        pytest.skip("set PEEKY_RUST_* tool paths to enable Rust conformance")
    monkeypatch.setenv("PEEKY_STATE_DIR", str(tmp_path / "state"))
    return tmp_path / "state"


def line_of(text, marker):
    return next(i for i, line in enumerate(text.splitlines(), 1) if marker in line)


def probe(capsys, crate, text, marker, selectors, *argv):
    at = f"src/main.rs:{line_of(text, marker)}"
    code = main(["probe", str(crate), "--at", at, "--capture", selectors, *argv, "--json"])
    result = json.loads(capsys.readouterr().out)
    assert code == 0, result.get("error")
    return result


def reads(row):
    """Whether this debugger reads memory (lldb-dap from LLVM 20); lldb-dap 18 does not."""
    return bool(os.environ.get("PEEKY_EXPECT_READ_MEMORY")) or row.get("view") == "memory"


def raw(row, *why):
    """A row left as LLDB shows it, whose note gives the reason."""
    assert row.get("view") is None and "@ 0x" in row["value"], row
    note = row.get("note") or ""
    assert "shows LLDB's summary (its type and address), not its contents" in note, row
    assert "(#53)" not in note and "may be moved, dropped or not yet assigned around" not in note
    for each in why:
        assert each in note, (each, note)


NO_MEMORY = "the debugger gives no memory address for it"


@pytest.mark.timeout(400)
def test_the_movavg_window_reads_its_values_through_self(tmp_path, state, capsys):
    # `self.values` (a Vec<i64> behind `&mut self`) reads, not only as LLDB's summary with
    # a warning about an owned local that may be moved, and `self.values[0]` is found.
    crate = crate_at(tmp_path, "movavg", MOVAVG)
    selectors = "self.values,self.values[0],self.values[-1],self.values.len,self.sum"
    result = probe(
        capsys,
        crate,
        MOVAVG,
        "// PUSHED",
        selectors,
        "--arg",
        "3",
        "--arg",
        "3,6,9,12",
        "--hits",
        "2",
    )
    rows = [{row["selector"]: row for row in result["rows"] if row["hit"] == h} for h in (1, 2)]
    if reads(rows[0]["self.values"]):
        assert [row["self.values"]["value"] for row in rows] == ["[3]", "[3, 6]"], rows
        assert rows[1]["self.values[0]"]["value"] == "3", rows
        assert rows[1]["self.values[-1]"]["value"] == "6", rows
        assert rows[1]["self.values.len"]["value"] == "2", rows
        assert not any("#53" in warning for warning in result["warnings"]), result["warnings"]
    else:
        raw(rows[0]["self.values"], NO_MEMORY, "Capture self.values.len for the length")
        error = rows[0]["self.values[0]"]["error"]
        assert NO_MEMORY in error and "Capture self.values.len" in error, error
    # main's `w`, which the MIR proves initialized, reads too. `w.sum` is not [settable] at
    # `out.push(format!(…, mean))`: `mean = w.push(…)` may hold a value computed from
    # it, which the program goes on with. On the last pass nothing reads `w.sum` again.
    result = probe(capsys, crate, MOVAVG, "// MEAN", "w.values,w.sum", "--arg", "3", "--arg", "3,6")
    rows = {row["selector"]: row for row in result["rows"] if row["hit"] == 1}
    assert rows["w.sum"]["settable"] is False, rows
    if reads(rows["w.values"]):
        assert rows["w.values"]["value"] == "[3]", rows
    else:
        raw(rows["w.values"], NO_MEMORY)
    at = line_of(MOVAVG, "// MEAN")
    command = ["probe", str(crate), "--at", f"src/main.rs:{at}", "--set", "w.sum=100"]
    code = main([*command, "--arg", "3", "--arg", "3,6", "--json", "--quiet"])
    error = json.loads(capsys.readouterr().out).get("error") or {}
    assert code == 2 and error.get("code") == "MUTATION_REJECTED", error
    holders = f"the program's own `mean` and `out` (at lines {at - 3}, {at - 1} and {at})"
    assert holders in error["message"], error
    assert "may hold a copy of `w` that it goes on with" in error["message"], error


