"""A refused change through a Rust reference or pointer gets the call advice ("before the
call that passed it") only where it is proven a parameter at the stop: not a `for` loop's
item, a local shadowing a parameter, a reborrow, or a parameter pointed elsewhere, by
assignment, through `&mut` or by inline assembly. Real builds."""

import json
import os
import platform

import pytest

from peeky.cli import main

MANIFEST = """[package]
name = "ledger"
version = "0.1.0"
edition = "2024"

[dependencies]
"""
LOCK = """# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4

[[package]]
name = "ledger"
version = "0.1.0"
"""
MAIN = """use std::num::ParseIntError;

struct Expense {
    payer: *const i64,
    cents: i64,
}

fn parse(text: &str) -> Result<i64, ParseIntError> {
    let cents: i64 = text.trim().parse()?; // TRY
    let val = cents + 1; // OWN_VAL
    let residual = val * 2; // OWN_RESIDUAL
    Ok(residual)
}

fn both(text: &str) -> Result<i64, ParseIntError> {
    let val: i64 = text.parse()?; // SAME_LINE
    Ok(val)
}

fn credit(e: &Expense) -> i64 {
    e.cents + 1 // PARAM
}

struct Pair {
    x: i64,
    y: i64,
}

fn shadow(p: &mut Pair) -> i64 { // SIGNATURE
    p.y += 1; // PARAM_USE
    let q = &*p;
    let seen = q.x; // COPY
    let mut own = Pair { x: seen, y: 0 };
    let p = &mut own; // INNER
    p.y += 2; // SHADOWED
    p.x + p.y
}

static GLOBAL: Pair = Pair { x: 7, y: 8 };

fn redirect(mut p: &Pair) -> i64 {
    let first = p.x;
    p = &GLOBAL;
    first + p.y // REDIRECTED
}

fn aimed(mut p: &Pair) -> i64 {
    let first = p.x;
    let slot = &mut p;
    *slot = &GLOBAL;
    first + p.y // AIMED
}

fn settle(expenses: &[Expense]) -> i64 {
    let mut total = 0;
    for e in expenses {
        total += credit(e); // ITEM
    }
    total
}

fn main() {
    let one = 1i64;
    let expenses = vec![
        Expense { payer: &one, cents: parse("4").unwrap_or(0) },
        Expense { payer: &one, cents: both("x").unwrap_or(7) },
    ];
    let paid = settle(&expenses);
    let mut pair = Pair { x: 3, y: 4 };
    let shadowed = shadow(&mut pair) + redirect(&pair) + aimed(&pair);
    println!("{} {} {} {}", paid, expenses[0].payer == expenses[1].payer, shadowed, pair.y);
}
"""


@pytest.fixture
def crate(tmp_path, monkeypatch):
    names = ("CARGO", "RUSTC", "DAP", "DWARFDUMP", "LINKER")
    if not all(os.environ.get("PEEKY_RUST_" + name) for name in names):
        pytest.skip("set PEEKY_RUST_* tool paths to enable Rust conformance")
    monkeypatch.setenv("PEEKY_STATE_DIR", str(tmp_path / "state"))
    root = tmp_path / "ledger"
    (root / "src").mkdir(parents=True)
    (root / "Cargo.toml").write_text(MANIFEST)
    (root / "Cargo.lock").write_text(LOCK)
    (root / "src/main.rs").write_text(MAIN)
    return root


def line_of(marker):
    return next(i for i, line in enumerate(MAIN.splitlines(), 1) if line.endswith(f"// {marker}"))


def _refused(capsys, crate, marker, assignment):
    at = f"src/main.rs:{line_of(marker)}"
    code = main(["probe", str(crate), "--at", at, "--capture", "e", "--set", assignment, "--json"])
    result = json.loads(capsys.readouterr().out)
    assert code == 2 and result.get("refused_before_launch") is True, result
    return result["error"]


@pytest.mark.timeout(400)
def test_a_loop_items_field_gives_no_call_advice(crate, capsys):
    # `e` in `settle` is a `for` item over a slice, whose elements Peeky never changes: no
    # "change the value where it is owned, before the call that passed it".
    error = _refused(capsys, crate, "ITEM", "e.cents=0")
    assert error["code"] == "MUTATION_REJECTED", error
    message = error["message"]
    assert (
        "`e` is a local here, not a parameter, so no call passed it: it points at an element "
        "of a slice or Vec, which Peeky never changes, so edit the source with `--old`/`--new`"
    ) in message, message
    assert "before the call that passed it" not in message, message
    assert error["hint"].startswith("Edit the source with `--old`/`--new`"), error["hint"]
    # A reference parameter keeps the advice: a call passed it.
    error = _refused(capsys, crate, "PARAM", "e.cents=0")
    assert "before the call that passed it" in error["message"], error
    assert "not a parameter" not in error["message"], error


NO_CALL = "if what it points at is also a root local in some frame, change it there"


@pytest.mark.timeout(400)
def test_a_local_shadowing_a_parameter_is_not_taken_for_it(crate, capsys):
    # `let p = &mut own;` shadows the parameter `p`; the MIR binds `p` twice, and the inner
    # one is no parameter.
    error = _refused(capsys, crate, "SHADOWED", "p.y=0")
    message = error["message"]
    assert f"`p` is a local here, not a parameter, so no call passed it: {NO_CALL}" in message
    assert "before the call" not in message and "call" not in error["hint"], error
    # The parameter, above the `let`, and named by its declaration below it.
    assert (
        "before the call that passed it" in _refused(capsys, crate, "PARAM_USE", "p.y=0")["message"]
    )
    named = f"p @ main.rs:{line_of('SIGNATURE')}.y=0"
    assert "before the call that passed it" in _refused(capsys, crate, "SHADOWED", named)["message"]
    # A reborrow of the parameter is a local, but what it points at was passed: no claim
    # either way.
    error = _refused(capsys, crate, "COPY", "q.x=0")
    assert (
        f"`q` isn't proven a parameter here, so Peeky names no call: {NO_CALL}" in error["message"]
    ), error
    assert "before the call" not in error["message"], error


@pytest.mark.timeout(400)
@pytest.mark.parametrize("marker", ["REDIRECTED", "AIMED"])
def test_a_parameter_pointed_elsewhere_gets_no_call_claim(crate, capsys, marker):
    # `p = &GLOBAL;` (or a write through `&mut p`) before the stop: `p` is no longer what
    # the caller passed.
    error = _refused(capsys, crate, marker, "p.y=0")
    message = error["message"]
    assert f"`p` isn't proven a parameter here, so Peeky names no call: {NO_CALL}" in message
    assert "before the call" not in message and "call" not in error["hint"], error


# A crate's own `trait Iterator`, implemented for the standard
# slice iterator, is dumped `<std::slice::Iter<'_, Pair> as Iterator>::next` too, and
# its `next` may return any reference.
OWN_ITERATOR = """struct Pair {
    x: i64,
    y: i64,
}

static GLOBAL: Pair = Pair { x: 7, y: 8 };

trait Iterator {
    type Item;
    fn next(&mut self) -> Option<Self::Item>;
}

impl<'a> Iterator for std::slice::Iter<'a, Pair> {
    type Item = &'a Pair;
    fn next(&mut self) -> Option<&'a Pair> {
        Some(&GLOBAL)
    }
}

fn fake(items: &[Pair]) -> i64 {
    let mut total = 0;
    let mut it = items.iter();
    while let Some(e) = Iterator::next(&mut it) {
        total += e.x; // FAKE
        if total > 20 {
            break;
        }
    }
    total
}

fn main() {
    let items = [Pair { x: 1, y: 2 }];
    println!("{} {}", fake(&items), items[0].y);
}
"""


@pytest.mark.timeout(400)
def test_an_item_of_a_crates_own_iterator_trait_is_no_slice_element(crate, capsys):
    (crate / "src/main.rs").write_text(OWN_ITERATOR)
    line = next(i for i, text in enumerate(OWN_ITERATOR.splitlines(), 1) if "// FAKE" in text)
    code = main(
        ["probe", str(crate), "--at", f"src/main.rs:{line}", "--capture", "e"]
        + ["--set", "e.x=0", "--json"]
    )
    result = json.loads(capsys.readouterr().out)
    assert code == 2 and result.get("refused_before_launch") is True, result
    message = result["error"]["message"]
    assert f"`e` is a local here, not a parameter, so no call passed it: {NO_CALL}" in message
    assert "slice or Vec" not in message, message


# `asm!` with `inout(reg) p` writes the parameter, and the MIR
# shows it only as an operand (`inout(reg) copy _1 => _1`): no assignment, no `&mut`.
# `mov {0}, {0}` is the same text on x86-64 and AArch64.
ASM = """use std::arch::asm;

struct Pair {
    x: i64,
    y: i64,
}

fn hidden(mut p: *const Pair) -> i64 {
    unsafe {
        asm!("mov {0}, {0}", inout(reg) p);
        (*p).x + (*p).y // ASM_USE
    }
}

fn plain(p: *const Pair) -> i64 {
    unsafe { (*p).x + (*p).y } // RAW_USE
}

fn main() {
    let pair = Pair { x: 1, y: 2 };
    println!("{} {}", hidden(&pair), plain(&pair));
}
"""


@pytest.mark.timeout(400)
def test_inline_assembly_leaves_a_pointer_parameter_unproven(crate, capsys):
    if platform.machine().lower() not in ("x86_64", "amd64", "arm64", "aarch64"):
        pytest.skip("the test's `mov {0}, {0}` is x86-64 or AArch64 assembly")
    (crate / "src/main.rs").write_text(ASM)

    def refused(marker):
        line = next(i for i, text in enumerate(ASM.splitlines(), 1) if f"// {marker}" in text)
        at = f"src/main.rs:{line}"
        code = main(["probe", str(crate), "--at", at, "--capture", "p", "--set", "p.x=0", "--json"])
        result = json.loads(capsys.readouterr().out)
        assert code == 2 and result.get("refused_before_launch") is True, result
        return result["error"]["message"]

    message = refused("ASM_USE")
    assert f"`p` isn't proven a parameter here, so Peeky names no call: {NO_CALL}" in message
    assert "before the call" not in message, message
    # The same raw pointer parameter with no `asm!` in its function keeps the advice.
    assert "before the call that passed it" in refused("RAW_USE")


@pytest.mark.timeout(400)
@pytest.mark.parametrize(
    ("marker", "assignment", "said"),
    [
        ("ITEM", "e.cents=0", "an element of a slice or Vec, which Peeky never changes"),
        # LLDB names each `p` by its declaration where both are in scope.
        ("SHADOWED", "INNER", "is a local here, not a parameter, so no call passed it"),
        ("SHADOWED", "SIGNATURE", "before the call that passed it"),
        ("PARAM_USE", "p.y=0", "before the call that passed it"),
    ],
)
def test_a_sessions_set_through_a_pointer_says_what_the_binding_is(
    crate, capsys, marker, assignment, said
):
    assert main(["session", "start", str(crate), "--at", f"src/main.rs:{line_of(marker)}"]) == 0
    capsys.readouterr()
    if assignment in ("INNER", "SIGNATURE"):
        assignment = f"p @ main.rs:{line_of(assignment)}.y=0"
    try:
        assert main(["session", "set", assignment, "--json"]) == 2
        error = json.loads(capsys.readouterr().out)["error"]
        assert error["code"] == "MUTATION_REJECTED", error
        assert said in error["message"], error
        if "before the call" not in said:
            assert "before the call" not in error["message"], error
    finally:
        main(["session", "close"])
        capsys.readouterr()
