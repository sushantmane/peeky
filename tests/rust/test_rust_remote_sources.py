"""#249: a module file that differs on the worker host is refused before Cargo runs."""

import json
import os
import threading

import pytest

from peeky.cli import WORKER_TOKEN_ENV, main

TOKEN = "rust-remote-sources-token-1234-0123456789abcdef"
MANIFEST = """[package]
name = "remote-sources"
version = "0.1.0"
edition = "2021"
build = false
autolib = false
autobins = false
autotests = false
autoexamples = false
autobenches = false

[[bin]]
name = "remote-sources"
path = "src/main.rs"
"""
LOCK = """# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4

[[package]]
name = "remote-sources"
version = "0.1.0"
"""
MAIN = """mod page;

fn main() {
    let start = page::start(1, 3);
    println!("START:{start}"); // OBSERVE
}
"""
PAGE = "pub fn start(page: i32, size: i32) -> i32 {\n    page * size\n}\n"


@pytest.fixture
def remote(tmp_path, monkeypatch):
    names = ("CARGO", "RUSTC", "DAP", "DWARFDUMP", "LINKER")
    if not all(os.environ.get("PEEKY_RUST_" + name) for name in names):
        pytest.skip("set PEEKY_RUST_* tool paths to enable Rust worker conformance")
    from peeky.rust import RustTarget
    from peeky.worker import make_server

    monkeypatch.setenv("PEEKY_STATE_DIR", str(tmp_path / "state"))
    monkeypatch.setenv(WORKER_TOKEN_ENV, TOKEN)
    host, local = tmp_path / "host", tmp_path / "local"
    for root in (host, local):
        (root / "src").mkdir(parents=True)
        for name, text in (
            ("Cargo.toml", MANIFEST),
            ("Cargo.lock", LOCK),
            ("src/main.rs", MAIN),
            ("src/page.rs", PAGE),
        ):
            (root / name).write_text(text)
    target = RustTarget(
        sources=("src/main.rs", "src/page.rs"),
        tests=(),
        cargo=os.environ["PEEKY_RUST_CARGO"],
        rustc=os.environ["PEEKY_RUST_RUSTC"],
        adapter=os.environ["PEEKY_RUST_DAP"],
        dwarfdump=os.environ["PEEKY_RUST_DWARFDUMP"],
        linker=os.environ["PEEKY_RUST_LINKER"],
        dsymutil=os.environ.get("PEEKY_RUST_DSYMUTIL"),
        sysroot=os.environ.get("PEEKY_RUST_SYSROOT"),
    )
    server = make_server(host, TOKEN, 0, adapter=target)
    thread = threading.Thread(target=server.serve_forever, daemon=True)
    thread.start()
    try:
        yield host, local, f"http://127.0.0.1:{server.server_port}"
    finally:
        server.worker.close()
        server.shutdown()
        server.server_close()
        thread.join(timeout=5)


def probe(capsys, local, url):
    argv = ["probe", str(local), "--at", "src/main.rs:5", "--capture", "start", "--worker", url]
    code = main([*argv, "--json", "--quiet", "--no-save"])
    return code, json.loads(capsys.readouterr().out)


@pytest.mark.timeout(180)
def test_a_module_file_that_differs_on_the_worker_host_is_refused_by_name(remote, capsys):
    host, local, url = remote
    code, result = probe(capsys, local, url)
    # The same crate: the worker confirms it compared every file, and read what we hold.
    assert code == 0, result.get("error")
    assert [row["value"] for row in result["rows"]] == ["3"] and "START:3" in result["output"]
    (host / "src/page.rs").write_text(PAGE.replace("page * size", "page * size + 1"))
    code, result = probe(capsys, local, url)
    assert code == 2 and result["error"]["code"] == "PROVENANCE_CHANGED", result
    assert (
        "for src/page.rs (the copy on the worker host differs from your checkout)"
        in (result["error"]["message"])
    )
    assert result["refused_before_launch"] is True and result["rows"] == []
