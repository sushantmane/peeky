"""A function whose signature spans several lines, as rustfmt writes a long one, is matched to
its MIR by the lines its signature spans (#466). Its `fn` line has no span in the MIR, only its
parameters' and return place's, so it went unmatched: every change in it was refused, saying
Peeky couldn't tell, and its rows lost their MIR types."""

import json
import os

import pytest

from peeky.cli import main

MANIFEST = """[package]
name = "signatures"
version = "0.1.0"
edition = "2024"

[dependencies]
"""
LOCK = """# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4

[[package]]
name = "signatures"
version = "0.1.0"
"""
MAIN = """pub struct Span {
    pub start: usize,
    pub end: usize,
}

fn trimmed(
    slice: &[u8],
    range: Span,
) -> usize {
    let count = slice[range.start..range.end].iter().take_while(|&&b| b == b' ').count();
    let mut kept = count;
    std::hint::black_box(&mut kept); // KEPT
    range.start + kept
}

fn noted(
    label: &str,
    times: u32,
) {
    let mut shown = times * 2;
    std::hint::black_box(&mut shown); // SHOWN
    println!("{} {}", label, shown);
}

mod scaling {
    pub(in crate::scaling) fn scaled(
        x: u32,
        factor: u32,
    ) -> u32 {
        let mut scaled = x * factor;
        std::hint::black_box(&mut scaled); // SCALED
        scaled
    }

    pub fn call(x: u32) -> u32 {
        scaled(x, 3)
    }
}

unsafe extern "C-unwind" fn unwound(
    x: u32,
    y: u32,
) -> u32 {
    let mut sum = x + y;
    std::hint::black_box(&mut sum); // SUMMED
    sum
}

pub /* visible */ fn commented(
    x: u32,
    y: u32,
) -> u32 {
    let mut product = x * y;
    std::hint::black_box(&mut product); // PRODUCT
    product
}

fn main() {
    println!("KEPT {}", trimmed(b"    abc", Span { start: 0, end: 7 }));
    noted("SHOWN", 4);
    println!("SCALED {}", scaling::call(5));
    println!("SUMMED {}", unsafe { unwound(2, 3) });
    println!("PRODUCT {}", commented(4, 6));
}
"""


@pytest.fixture
def crate(tmp_path, monkeypatch):
    names = ("CARGO", "RUSTC", "DAP", "DWARFDUMP", "LINKER")
    if not all(os.environ.get("PEEKY_RUST_" + name) for name in names):
        pytest.skip("set PEEKY_RUST_* tool paths to enable Rust conformance")
    monkeypatch.setenv("PEEKY_STATE_DIR", str(tmp_path / "state"))
    root = tmp_path / "signatures"
    (root / "src").mkdir(parents=True)
    (root / "Cargo.toml").write_text(MANIFEST)
    (root / "Cargo.lock").write_text(LOCK)
    (root / "src/main.rs").write_text(MAIN)
    return root


def probe(capsys, root, marker, *argv):
    line = next(i for i, text in enumerate(MAIN.splitlines(), 1) if text.endswith(f"// {marker}"))
    at = ["probe", str(root), "--at", f"src/main.rs:{line}", "--json", "--quiet", "--no-save"]
    code = main([*at, *argv])
    result = json.loads(capsys.readouterr().out)
    assert code == 0, result.get("error")
    return {row["selector"]: row for row in result["rows"] if row["phase"] == "after-set"}, result


@pytest.mark.timeout(400)
def test_a_change_in_a_function_with_a_signature_over_several_lines_is_made(crate, capsys):
    rows, result = probe(capsys, crate, "KEPT", "--capture", "kept", "--set", "kept=6")
    assert rows["kept"]["value"] == "6"
    assert rows["kept"]["type"] == "usize"
    # `range.start + kept`, with the change.
    assert "KEPT 6" in result["output"]
    # A function returning nothing: its `{` line is its parameters' last.
    rows, result = probe(capsys, crate, "SHOWN", "--capture", "shown", "--set", "shown=11")
    assert rows["shown"]["value"] == "11"
    assert "SHOWN 11" in result["output"]


@pytest.mark.timeout(400)
def test_a_split_signature_with_a_path_visibility_an_abi_or_a_comment_is_matched(crate, capsys):
    # `pub(in crate::scaling)`, `unsafe extern "C-unwind"` and `pub /* visible */` before `fn`
    # left these unmatched, and every change in them refused (#474).
    for marker, variable, value, printed in (
        ("SCALED", "scaled", "40", "SCALED 40"),
        ("SUMMED", "sum", "50", "SUMMED 50"),
        ("PRODUCT", "product", "60", "PRODUCT 60"),
    ):
        rows, result = probe(
            capsys, crate, marker, "--capture", variable, "--set", f"{variable}={value}"
        )
        assert rows[variable]["value"] == value, (marker, rows)
        assert rows[variable]["type"] == "u32", (marker, rows)
        assert printed in result["output"], (marker, result["output"])
