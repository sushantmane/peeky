"""Inline assembly that reads a file is refused before building (#180), on a real Rust
build: `global_asm!`'s `.incbin` read a file rustc's dependency file does not list, so
the program ran on bytes no provenance check covered (`blob=SECRET`). A `.incbin`
string outside inline assembly builds as before."""

import json
import os

import pytest

from peeky.assembler import ASSEMBLER_REFUSAL
from peeky.cli import main

MANIFEST = """[package]
name = "blob"
version = "0.1.0"
edition = "2021"

[dependencies]
"""
LOCK = """# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4

[[package]]
name = "blob"
version = "0.1.0"
"""
INCBIN = """use std::arch::global_asm;
#[cfg(target_os = "macos")]
global_asm!(".data", ".globl _blob", "_blob:", ".incbin \\"DATA\\"", ".byte 0", ".text");
#[cfg(not(target_os = "macos"))]
global_asm!(".data", ".globl blob", "blob:", ".incbin \\"DATA\\"", ".byte 0", ".text");
extern "C" {
    static blob: [u8; 7];
}
fn main() {
    let s = unsafe { std::str::from_utf8(&blob[..6]).unwrap() };
    println!("blob={}", s); // OBSERVE
}
"""
PLAIN = """fn main() {
    let s = ".incbin \\"DATA\\"";
    println!("text={}", s); // OBSERVE
}
"""


@pytest.fixture
def crate(tmp_path, monkeypatch):
    names = ("CARGO", "RUSTC", "DAP", "DWARFDUMP", "LINKER")
    if not all(os.environ.get("PEEKY_RUST_" + name) for name in names):
        pytest.skip("set PEEKY_RUST_* tool paths to enable Rust conformance")
    monkeypatch.setenv("PEEKY_STATE_DIR", str(tmp_path / "state"))
    # Outside the crate, as an absolute path: nothing declares it.
    data = tmp_path / "out" / "data.bin"
    data.parent.mkdir()
    data.write_bytes(b"SECRET")
    root = tmp_path / "blob"
    (root / "src").mkdir(parents=True)
    (root / "Cargo.toml").write_text(MANIFEST)
    (root / "Cargo.lock").write_text(LOCK)

    def probe(capsys, text, save=False):
        (root / "src/main.rs").write_text(text.replace("DATA", str(data)))
        line = next(i for i, row in enumerate(text.splitlines(), 1) if "// OBSERVE" in row)
        command = ["probe", str(root), "--at", f"src/main.rs:{line}", "--capture", "s"]
        code = main([*command, "--json", "--quiet", *([] if save else ["--no-save"])])
        return code, json.loads(capsys.readouterr().out)

    return probe, tmp_path


@pytest.mark.timeout(300)
def test_global_asm_that_reads_a_file_is_refused_before_building(crate, capsys):
    probe, tmp_path = crate
    code, result = probe(capsys, INCBIN, save=True)
    error = result.get("error") or {}
    assert code == 2 and error.get("code") == "UNSUPPORTED", result
    assert error["message"].startswith(
        f"{ASSEMBLER_REFUSAL}: the global_asm! at src/main.rs:3 uses `.incbin`, which reads a file"
    ), error
    assert "declared source or header" in error["hint"]
    # Nothing ran, so no run is kept as evidence.
    assert result.get("refused_before_launch") is True and "output" not in result, result
    assert not (tmp_path / "state" / "evidence" / "evidence.db").exists()


@pytest.mark.timeout(300)
def test_an_incbin_string_outside_inline_assembly_builds(crate, capsys):
    probe, _ = crate
    code, result = probe(capsys, PLAIN)
    assert code == 0 and result["status"] == "completed", result.get("error")
    # Its value is read where the debugger reads memory (lldb-dap from LLVM 20).
    assert result["rows"][0]["selector"] == "s" and "text=.incbin" in result["output"]
