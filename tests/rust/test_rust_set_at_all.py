"""`--set-at LINE@all` on a real Rust build (#265): a change at every stop of the line
reached only in the case to test, in the frame that owns the value, each made and read
back as one `--set-at LINE@N` is; through a `&mut` it is refused before the run."""

import json
import os

import pytest

from peeky.cli import main

MANIFEST = """[package]
name = "debounce"
version = "0.1.0"
edition = "2024"

[dependencies]
"""
LOCK = """# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4

[[package]]
name = "debounce"
version = "0.1.0"
"""
MAIN = """struct Debounce {
    stable: i32,
    candidate: i32,
    count: i32,
    threshold: i32,
}

fn settle(db: &mut Debounce, level: i32) -> bool {
    if level == db.stable {
        return false; // CALLEE
    }
    if level != db.candidate {
        db.candidate = level;
        db.count = 0;
    }
    db.count += 1;
    if db.count < db.threshold {
        return false;
    }
    db.stable = level;
    db.count = 0;
    true
}

fn main() {
    let signal: Vec<i32> = std::env::args()
        .nth(1)
        .unwrap_or_default()
        .bytes()
        .map(|b| i32::from(b - b'0'))
        .collect();
    let mut db = Debounce { stable: 0, candidate: 0, count: 0, threshold: 3 };
    let mut quiet = 0;
    let mut events = String::new();
    for (ms, &level) in signal.iter().enumerate() {
        if level == db.stable {
            quiet += 1; // AGREES
            continue;
        }
        if level != db.candidate {
            db.candidate = level;
            db.count = 0;
        }
        db.count += 1;
        if db.count >= db.threshold {
            db.stable = level;
            db.count = 0;
            events.push_str(&format!("{}@{},", if level == 1 { 'P' } else { 'R' }, ms));
        }
    }
    let mut other = Debounce { stable: 0, candidate: 0, count: 0, threshold: 3 };
    let pressed = signal.iter().filter(|&&level| settle(&mut other, level)).count();
    println!("DEBOUNCE:{events} quiet {quiet} settled {pressed}");
}
"""
SIGNAL = "00101101111110100100001101100000"


@pytest.fixture
def crate(tmp_path, monkeypatch):
    names = ("CARGO", "RUSTC", "DAP", "DWARFDUMP", "LINKER")
    if not all(os.environ.get("PEEKY_RUST_" + name) for name in names):
        pytest.skip("set PEEKY_RUST_* tool paths to enable Rust conformance")
    monkeypatch.setenv("PEEKY_STATE_DIR", str(tmp_path / "state"))
    root = tmp_path / "debounce"
    (root / "src").mkdir(parents=True)
    (root / "Cargo.toml").write_text(MANIFEST)
    (root / "Cargo.lock").write_text(LOCK)
    (root / "src/main.rs").write_text(MAIN)
    return root


def line_of(marker):
    return next(i for i, line in enumerate(MAIN.splitlines(), 1) if f"// {marker}" in line)


def probe(capsys, root, *argv):
    code = main(["probe", str(root), *argv, "--json", "--quiet", "--no-save", f"--arg={SIGNAL}"])
    return code, json.loads(capsys.readouterr().out)


@pytest.mark.timeout(600)
def test_an_all_resets_a_rust_count_wherever_the_input_agrees(crate, capsys):
    agrees = line_of("AGREES")
    at = f"src/main.rs:{agrees}"
    code, plain = probe(capsys, crate, "--at", at)
    assert code == 0, plain
    assert plain["output"].strip() == "DEBOUNCE:P@5,R@15,P@23,R@28, quiet 20 settled 4"
    code, result = probe(
        capsys, crate, "--at", at, "--capture", "ms,db.count", "--hits", "all",
        "--set-at", f"{agrees}@all", "db.count=0",
    )  # fmt: skip
    assert code == 0, result
    assert result["output"].strip() == "DEBOUNCE:P@9,R@20, quiet 16 settled 4", result
    changes = result["interventions"]
    assert [change["hit"] for change in changes] == list(range(1, result["hits"] + 1))
    assert all(change.get("all") and change["after"] == "0" for change in changes), changes
    assert any(change["before"] != "0" for change in changes), changes
    assert "unapplied" not in result
    # In `settle`, `db` is a `&mut`: refused before the run, as one change would be.
    callee = line_of("CALLEE")
    code, refused = probe(
        capsys, crate, "--at", f"src/main.rs:{callee}", "--set-at", f"{callee}@all", "db.count=0"
    )
    assert code == 2 and refused["refused_before_launch"], refused
    assert "`db` is a pointer" in refused["error"]["message"], refused["error"]
