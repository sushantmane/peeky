"""Setting a Rust `String` to a text (#137 part 2), on real builds: the bytes and `len`,
within its capacity, only where the MIR proves the local holds a String at the stop;
never a `&str` (borrowed, possibly read-only text)."""

import json
import os
import sys

import pytest

from peeky.cli import main

MANIFEST = """[package]
name = "texts"
version = "0.1.0"
edition = "2024"

[dependencies]
"""
LOCK = """# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4

[[package]]
name = "texts"
version = "0.1.0"
"""
TEXTS = """fn main() {
    let mut name = String::with_capacity(16);
    name.push_str("apple ");
    let lit: &str = "lit";
    let moved = String::from("gone");
    let keep = moved;
    let n = name.len();
    println!("NAME:[{}] LIT:{} KEEP:{} N:{}", name, lit, keep, n); // OBSERVE
    name.push('!');
    println!("AFTER:[{}]", name);
}
"""
OBSERVE = next(i for i, text in enumerate(TEXTS.splitlines(), 1) if "// OBSERVE" in text)
# lldb-dap 21 writes memory (macOS here); 18 and 20 cannot, and a String's text is on
# the heap.
WRITES = sys.platform == "darwin"


@pytest.fixture
def crate(tmp_path, monkeypatch):
    names = ("CARGO", "RUSTC", "DAP", "DWARFDUMP", "LINKER")
    if not all(os.environ.get("PEEKY_RUST_" + name) for name in names):
        pytest.skip("set PEEKY_RUST_* tool paths to enable Rust conformance")
    monkeypatch.setenv("PEEKY_STATE_DIR", str(tmp_path / "state"))
    root = tmp_path / "texts"
    (root / "src").mkdir(parents=True)
    (root / "Cargo.toml").write_text(MANIFEST)
    (root / "Cargo.lock").write_text(LOCK)
    (root / "src/main.rs").write_text(TEXTS)
    return root


def probe(capsys, crate, *argv):
    at = ["probe", str(crate), "--at", f"src/main.rs:{OBSERVE}", "--capture", "name,keep"]
    code = main([*at, *argv, "--json", "--quiet"])
    return code, json.loads(capsys.readouterr().out)


def refusal(code, result, *texts):
    assert code == 1 and result["error"]["code"] == "MUTATION_REJECTED", result
    for text in texts:
        assert text in result["error"]["message"], result["error"]
    return result


@pytest.mark.timeout(400)
def test_a_string_takes_a_text_within_its_capacity(crate, capsys):
    # #137 part 2: `--set name="pear"` was refused before the run ("`name` is a
    # std::string::String; only integer locals ... can be changed").
    code, result = probe(capsys, crate, "--set", 'name="pear"', "--set", 'keep="gon"')
    if not WRITES:
        refusal(code, result, "a String's text is on the heap, and this debugger cannot write")
        return
    assert code == 0, result.get("error")
    assert "NAME:[pear] LIT:lit KEEP:gon N:6" in result["output"], result["output"]
    # The String grows from the new length, in the buffer it had.
    assert "AFTER:[pear!]" in result["output"], result["output"]
    assert [(c["name"], c["before"], c["after"]) for c in result["interventions"]] == [
        ("name", '"apple "', '"pear"'),
        ("keep", '"gone"', '"gon"'),
    ]
    rows = {row["selector"]: row for row in result["rows"] if row["phase"] == "observed"}
    assert rows["name"]["settable"] is True and rows["name"]["view"] == "memory", rows
    # Exactly its capacity, 16 bytes; one more is refused, nothing changed.
    code, result = probe(capsys, crate, "--set", 'name="sixteen bytes ok"')
    assert code == 0 and "NAME:[sixteen bytes ok]" in result["output"], result
    code, result = probe(capsys, crate, "--set", 'name="seventeen bytes!!"')
    refusal(code, result, "`name`'s buffer holds 16 bytes, and the text is 17 bytes")
    assert "NAME:" not in (result.get("output") or ""), result


@pytest.mark.timeout(400)
def test_borrowed_moved_or_other_values_take_no_text(crate, capsys):
    # A &str's text may be read-only (a literal): refused before the program runs.
    code, result = probe(capsys, crate, "--set", 'lit="x"')
    refusal(code, result, "`lit` is a &str, text it borrows, which may be read-only")
    assert result.get("refused_before_launch") is True, result
    code, result = probe(capsys, crate, "--set", 'n="5"')
    refusal(code, result, "`n` is a usize; a text changes a String")
    code, result = probe(capsys, crate, "--set", "name=5")
    refusal(code, result, "and a String to a text in double quotes (--set 'name=\"apple\"')")
    # A moved String's buffer belongs to another binding, or is freed: never written.
    code, result = probe(capsys, crate, "--set", 'moved="x"')
    refusal(code, result, "the build's MIR does not prove it initialized here")
    assert "NAME:" not in (result.get("output") or ""), result


BORROWS = """use std::cell::RefCell;
#[inline(never)]
fn keep<'a>(out: &mut Vec<&'a str>, s: &'a str) { out.push(s); }
#[inline(never)]
fn check(tag: &str, t: &str) { println!("{}=[{}] utf8={}", tag, t, std::str::from_utf8(t.as_bytes()).is_ok()); }
fn main() {
    let mut s = String::with_capacity(16);
    s.push_str("abcdefghij");
    let head: &str = &s[..2];
    let tail: &str = &s[2..];
    check("head", head); // HEAD
    check("tail", tail);
    check("s", &s); // AFTER
    let mut a = String::with_capacity(16);
    a.push_str("alpha");
    let mut b = String::with_capacity(16);
    b.push_str("bravo");
    let mut c = String::with_capacity(16);
    c.push_str("charlie");
    let mut d = String::with_capacity(16);
    d.push_str("delta");
    let mut e = String::with_capacity(16);
    e.push_str("echo");
    let mut chars = a.chars();
    let first = chars.next();
    let mut v: Vec<&str> = Vec::new();
    keep(&mut v, &b);
    let cell: RefCell<Vec<&str>> = RefCell::new(Vec::new());
    cell.borrow_mut().push(c.as_str());
    let shout = || d.len();
    let n = e.len();
    let copy = e.clone();
    println!("{:?} {:?}", first, v); // MANY
    println!("{:?} {:?} {} {} {} {}", chars.next(), cell.borrow(), shout(), n, copy, e);
}
"""


@pytest.mark.timeout(400)
def test_a_string_a_live_borrow_reads_is_never_changed(crate, capsys):
    # #164 review: with `head = &s[..2]` and `tail = &s[2..]` still to be used, a change
    # to `s` left both reading new bytes at old lengths (`[61, c3]`, `[a9, ...]`: not
    # UTF-8, undefined behavior), and `t = &s` read `byelo world`. Refused wherever the
    # MIR shows a borrow of the String used after the stop; made after its last use.
    (crate / "src/main.rs").write_text(BORROWS)

    def line(marker):
        return next(i for i, text in enumerate(BORROWS.splitlines(), 1) if marker in text)

    def change(marker, name):
        at = ["probe", str(crate), "--at", f"src/main.rs:{line(marker)}"]
        code = main([*at, "--set", f'{name}="xé"', "--json", "--quiet"])
        return code, json.loads(capsys.readouterr().out)

    refused = "a borrow of it (a `&str` of its text, a reference, an iterator over it) is "
    # `head` and `tail`; an iterator; a `&str` pushed into a Vec, or into a RefCell's;
    # a closure that borrows it.
    for marker, name in (("// HEAD", "s"), *(("// MANY", each) for each in "abcd")):
        code, result = change(marker, name)
        refusal(code, result, f"`{name}` cannot be changed to a text at this stop: {refused}")
        assert "utf8=false" not in (result.get("output") or ""), result
    # After their last use; a `len()` and a clone keep no borrow.
    for marker, name in (("// AFTER", "s"), ("// MANY", "e")):
        code, result = change(marker, name)
        if not WRITES:
            refusal(code, result, "cannot write memory")
            continue
        assert code == 0, result.get("error")
        assert "utf8=false" not in result["output"], result["output"]
    if WRITES:
        assert "s=[xé] utf8=true" in main_output(crate, capsys, line("// AFTER"), "s")


def main_output(crate, capsys, at, name):
    code = main(
        ["probe", str(crate), "--at", f"src/main.rs:{at}", "--set", f'{name}="xé"', "--json"]
    )
    result = json.loads(capsys.readouterr().out)
    assert code == 0, result.get("error")
    return result["output"]
