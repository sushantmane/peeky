r"""#177: rustc's dependency file lists every file a build read, and the provenance check
needs each (declared, inside the crate). It escapes only a space (`\ `): a `$$` is two
dollars, and a U+2028 is part of a name, not a line break."""

import json
import os
from pathlib import Path

import pytest

from peeky.cli import main

MANIFEST = """[package]
name = "{name}"
version = "0.1.0"
edition = "2024"

[dependencies]
"""
LOCK = """# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4

[[package]]
name = "{name}"
version = "0.1.0"
"""
MAIN = """fn main() {
    let n = std::hint::black_box(MODULES);
    println!("{n}"); // STOP
}
"""


@pytest.fixture
def state(tmp_path, monkeypatch):
    names = ("CARGO", "RUSTC", "DAP", "DWARFDUMP", "LINKER")
    if not all(os.environ.get("PEEKY_RUST_" + name) for name in names):
        pytest.skip("set PEEKY_RUST_* tool paths to enable Rust conformance")
    monkeypatch.setenv("PEEKY_STATE_DIR", str(tmp_path / "state"))
    return tmp_path / "state"


def crate_with(tmp_path, name, modules):
    """A crate whose `main` sums one function of each module, by its file's name (or
    absolute path)."""
    root = tmp_path / name
    (root / "src").mkdir(parents=True)
    (root / "Cargo.toml").write_text(MANIFEST.format(name=name))
    (root / "Cargo.lock").write_text(LOCK.format(name=name))
    declared, total = [], []
    for index, file in enumerate(modules):
        path = Path(file) if os.path.isabs(file) else root / "src" / file
        path.write_text(f"pub fn f() -> i64 {{ {index + 1} }}\n")
        literal = str(file).replace("\\", "\\\\")
        declared.append(f'#[path = "{literal}"]\nmod m{index};')
        total.append(f"m{index}::f()")
    text = "\n".join(declared) + "\n" + MAIN.replace("MODULES", " + ".join(total))
    (root / "src/main.rs").write_text(text)
    # rustc counts lines by `\n` alone.
    return root, text[: text.index("// STOP")].count("\n") + 1


def probe(capsys, root, line):
    code = main(["probe", str(root), "--at", f"src/main.rs:{line}", "--capture", "n", "--json"])
    return code, json.loads(capsys.readouterr().out)


@pytest.mark.timeout(400)
def test_dollars_and_spaces_in_module_names_are_read_as_rustc_wrote_them(tmp_path, state, capsys):
    # Main read `c$$d.rs` as make would (`c$d.rs`), then refused the build for reading
    # an undeclared file. (Spaces, which rustc escapes as `\ `, it read right.)
    modules = ["c$$d.rs", "e$f.rs", "a b.rs", "two  sp.rs", "$$.rs"]
    root, line = crate_with(tmp_path, "names", modules)
    code, result = probe(capsys, root, line)
    assert code == 0, result.get("error")
    assert [row["value"] for row in result["rows"]] == ["15"], result["rows"]


@pytest.mark.timeout(400)
def test_a_file_read_after_a_line_separator_in_a_name_is_still_checked(tmp_path, state, capsys):
    # Main split the dependency file's lines at U+2028 too, dropping the rest of the
    # rule: the module outside the crate after it escaped the provenance check.
    outside = tmp_path / "outside.rs"
    root, line = crate_with(tmp_path, "separator", ["x.rs\u2028y.rs", str(outside)])
    # Declared, never compiled: what main read the name before the U+2028 as.
    (root / "src/x.rs").write_text("")
    code, result = probe(capsys, root, line)
    assert code == 2 and result["status"] == "failed", result
    assert result["refused_before_launch"] is True
    assert (
        f"The Rust build read {outside}, which is not a declared source"
        in (result["error"]["message"])
    ), result["error"]
