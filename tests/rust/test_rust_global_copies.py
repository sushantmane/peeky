# A trait of the crate's own whose `impl` stores in a static. Only the crate's code can call it,
# by its name: formatting and the standard library's `Vec::push` run none of it.
TRAITS = """use std::sync::atomic::{AtomicU32, Ordering};

static A: AtomicU32 = AtomicU32::new(0);

trait Sink {
    fn put(&self, v: u32);
}

struct Global;

struct Item(u32);

impl Sink for Global {
    fn put(&self, v: u32) {
        A.store(v, Ordering::Relaxed);
    }
}

fn other() -> u32 {
    std::hint::black_box(1)
}

fn printed(arg: u32) -> u32 {
    let x = std::convert::identity(arg);
    println!("{}", x);
    let k = other(); // PRINTED
    std::hint::black_box(&x);
    A.load(Ordering::Relaxed) + k
}

fn pushed(arg: u32) -> u32 {
    let x = std::convert::identity(arg);
    let mut items = Vec::new();
    items.push(Item(x));
    drop(items);
    let k = other(); // PUSHED
    std::hint::black_box(&x);
    A.load(Ordering::Relaxed) + k
}

fn dynamic(arg: u32) -> u32 {
    let x = std::convert::identity(arg);
    let s: &dyn Sink = &Global;
    s.put(x);
    let k = other(); // DYNAMIC
    std::hint::black_box(&x);
    A.load(Ordering::Relaxed) + k
}

fn main() {
    let n: u32 = std::env::args().nth(1).unwrap().parse().unwrap();
    println!("{}", printed(n) + pushed(n) + dynamic(n));
}
"""


# Two modules with a function and a method of one name, where only `dirty`'s store in `A`;
# pointers a call returns, into a static (`slot()`) or a leaked `Box` (`fresh()`); and a
# global read after the stop (`FLAG`) that isn't the one the copy went to (`S`).
PATHS = """use std::sync::Mutex;
use std::sync::atomic::{AtomicU32, Ordering};

static A: AtomicU32 = AtomicU32::new(0);
static FLAG: AtomicU32 = AtomicU32::new(0);
static S: Mutex<u32> = Mutex::new(0);

mod dirty {
    pub fn note(v: u32) {
        super::A.store(v, std::sync::atomic::Ordering::Relaxed);
    }

    pub struct Wrap(pub u32);

    impl Wrap {
        pub fn keep(&self) {
            super::A.store(self.0, std::sync::atomic::Ordering::Relaxed);
        }
    }
}

mod clean {
    pub fn note(v: u32) {
        std::hint::black_box(v);
    }

    pub struct Wrap(pub u32);

    impl Wrap {
        pub fn keep(&self) {
            std::hint::black_box(self.0);
        }
    }
}

#[inline(never)]
fn other() -> u32 {
    std::hint::black_box(FLAG.load(Ordering::Relaxed))
}

#[inline(never)]
fn fresh() -> &'static Mutex<u32> {
    Box::leak(Box::new(Mutex::new(0)))
}

#[inline(never)]
fn slot() -> &'static Mutex<u32> {
    &S
}

#[inline(never)]
fn lock_set(m: &Mutex<u32>, v: u32) {
    *m.lock().unwrap() = v;
}

static KEPT_PTRS: Mutex<Vec<&'static Mutex<u32>>> = Mutex::new(Vec::new());

#[inline(never)]
fn fresh_kept() -> &'static Mutex<u32> {
    let m: &'static Mutex<u32> = Box::leak(Box::new(Mutex::new(0)));
    KEPT_PTRS.lock().unwrap().push(m);
    m
}

fn named_fresh(arg: u32) -> u32 {
    let x = std::convert::identity(arg);
    let r = fresh();
    lock_set(r, x);
    let k = other(); // NAMED_FRESH
    std::hint::black_box(&x);
    A.load(Ordering::Relaxed) + k
}

fn kept_fresh(arg: u32) -> u32 {
    let x = std::convert::identity(arg);
    lock_set(fresh_kept(), x);
    let k = other(); // KEPT_FRESH
    std::hint::black_box(&x);
    *KEPT_PTRS.lock().unwrap()[0].lock().unwrap() + k
}

fn unrelated(arg: u32) -> u32 {
    let x = std::convert::identity(arg);
    lock_set(&S, x);
    let k = other(); // UNRELATED
    std::hint::black_box(&x);
    let y = x + k;
    std::hint::black_box(&y);
    *S.lock().unwrap() + y
}

fn freshly(arg: u32) -> u32 {
    let x = std::convert::identity(arg);
    lock_set(fresh(), x);
    let k = other(); // FRESH
    std::hint::black_box(&x);
    A.load(Ordering::Relaxed) + k
}

fn slotted(arg: u32) -> u32 {
    let x = std::convert::identity(arg);
    lock_set(slot(), x);
    let k = other(); // SLOTTED
    std::hint::black_box(&x);
    *S.lock().unwrap() + k
}

fn cleaned(arg: u32) -> u32 {
    let x = std::convert::identity(arg);
    clean::note(x);
    clean::Wrap(x).keep();
    let k = other(); // CLEAN
    std::hint::black_box(&x);
    A.load(Ordering::Relaxed) + k
}

fn dirtied(arg: u32) -> u32 {
    let x = std::convert::identity(arg);
    dirty::note(x);
    let k = other(); // DIRTY
    std::hint::black_box(&x);
    A.load(Ordering::Relaxed) + k
}

fn kept(arg: u32) -> u32 {
    let x = std::convert::identity(arg);
    dirty::Wrap(x).keep();
    let k = other(); // KEPT
    std::hint::black_box(&x);
    A.load(Ordering::Relaxed) + k
}

fn main() {
    let n: u32 = std::env::args().nth(1).unwrap().parse().unwrap();
    println!("FRESH {}", freshly(n));
    println!("SLOTTED {}", slotted(n));
    println!("CLEAN {}", cleaned(n));
    println!("DIRTY {}", dirtied(n));
    println!("KEPT {}", kept(n));
    println!("NAMED_FRESH {}", named_fresh(n));
    println!("KEPT_FRESH {}", kept_fresh(n));
    println!("UNRELATED {}", unrelated(n));
}
"""


# A pointer `fresh()` returned, a leaked `Box` into which `lock_set(r, x)` stores `x`, handed
# to a thread the frame spawns and detaches, or to `later(r)`, which spawns one; and compared
# by the standard library's `ptr::eq`, which keeps nothing.
KEEPS = """use std::sync::Mutex;
use std::time::Duration;

#[inline(never)]
fn other() -> u32 {
    std::hint::black_box(1)
}

#[inline(never)]
fn fresh() -> &'static Mutex<u32> {
    Box::leak(Box::new(Mutex::new(0)))
}

#[inline(never)]
fn lock_set(m: &Mutex<u32>, v: u32) {
    *m.lock().unwrap() = v;
}

#[inline(never)]
fn later(m: &'static Mutex<u32>) {
    std::thread::spawn(move || {
        std::thread::sleep(Duration::from_millis(300));
        println!("LATER {}", *m.lock().unwrap());
    });
}

fn spawned(arg: u32) -> u32 {
    let x = std::convert::identity(arg);
    let r = fresh();
    lock_set(r, x); // SPAWNED_CALL
    std::thread::spawn(move || {
        std::thread::sleep(Duration::from_millis(300));
        println!("THREAD {}", *r.lock().unwrap());
    });
    let k = other(); // SPAWNED
    std::hint::black_box(&x);
    k
}

fn handed(arg: u32) -> u32 {
    let x = std::convert::identity(arg);
    let r = fresh();
    lock_set(r, x);
    later(r);
    let k = other(); // HANDED
    std::hint::black_box(&x);
    k
}

fn compared(arg: u32) -> u32 {
    let x = std::convert::identity(arg);
    let r = fresh();
    let q = fresh();
    lock_set(r, x);
    std::hint::black_box(std::ptr::eq(r, q));
    let k = other(); // COMPARED
    std::hint::black_box(&x);
    k
}

fn main() {
    let n: u32 = std::env::args().nth(1).unwrap().parse().unwrap();
    println!("SPAWNED {}", spawned(n));
    println!("HANDED {}", handed(n));
    println!("COMPARED {}", compared(n));
    std::thread::sleep(Duration::from_millis(600));
}
"""


