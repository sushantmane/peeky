def probe(capsys, root, marker, *argv, text=SOURCE):
    at = ["probe", str(root), "--at", f"src/main.rs:{line_of(marker, text)}", "--json"]
    code = main([*at, "--quiet", *argv, "--", "5"])
    return code, json.loads(capsys.readouterr().out)


def refused(code, result, marker):
    """The message and hint of a refusal made before the program runs."""
    error = result.get("error") or {}
    assert code == 2 and error.get("code") == "MUTATION_REJECTED", (marker, result)
    assert result.get("refused_before_launch") is True, (marker, result)
    return error["message"], error["hint"]


@pytest.mark.timeout(900)
def test_a_copy_a_call_stores_in_a_static_or_thread_local_withholds_the_local(crate, capsys):
    for marker, call, _ in COPIES:
        message, hint = refused(*probe(capsys, crate, marker, "--set", "x=100"), marker)
        assert (
            f"a static or thread-local may hold a copy of `x` (from line {line_of(call)}) "
            "that the program may go on with, so a change there may never be seen"
        ) in message, (marker, message)
        # No copy to change instead: Peeky changes no static.
        assert "change the copy" not in message + hint, (marker, message, hint)
        assert hint == (
            "Change it before the program copies it (a stop on an earlier line, or `--set-at` "
            "there)."
        ), (marker, hint)
    # `widen` stores `u64::from(v) * 2` in a `static` `AtomicU64`: what was computed from `x`.
    message, hint = refused(*probe(capsys, crate, "WIDENED", "--set", "x=100"), "WIDENED")
