"""#324: at a line breakpoint on `let y = x.clone();` in an unoptimized build, `x` was
`[settable]`; `--set x=100` reported the change, but the program printed the old value. LLVM
inlines `clone` even at opt-level 0: its load of `x` carries `core/src/clone.rs`'s line, and
comes before the line's first row of its own, where LLDB puts the line's breakpoint. So the
stop was past the read, not before the line's code. Now Peeky reads the inlined call's site
and addresses from the DWARF and withholds what the call was given; a step onto the line,
which stops before the inlined code, still allows the change."""

import json
import os
import sys

import pytest

from peeky.cli import main

MANIFEST = """[package]
name = "inlined"
version = "0.1.0"
edition = "2024"

[dependencies]
"""
LOCK = """# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4

[[package]]
name = "inlined"
version = "0.1.0"
"""
# tests/unit/test_rust_inlined_reads.py holds this crate's MIR.
SOURCE = """use std::env;

struct P {
    a: u32,
    b: u32,
}

#[inline(always)]
fn twice(v: &u32) -> u32 {
    *v * 2
}

#[inline(always)]
fn size(s: &String) -> usize {
    s.len()
}

fn cloned(x: u32) -> u32 {
    let k = std::convert::identity(1u32); // BEFORE
    let y = x.clone(); // CLONE
    y + k
}

fn through(x: u32) -> u32 {
    let r = &x;
    let y = (*r).clone(); // THROUGH
    y
}

fn field(arg: u32) -> u32 {
    let p = P { a: arg, b: 2 };
    let y = p.a.clone(); // FIELD
    y + p.b
}

fn doubled(x: u32) -> u32 {
    let y = twice(&x); // TWICE
    y
}

fn sized(s: String) -> usize {
    let n = size(&s); // SIZE
    n + s.len()
}

fn mixed(x: u32, z: u32) -> u32 {
    let y = z.clone() + x; // MIXED
    std::hint::black_box(&x);
    y
}

fn listed(x: u32) -> u32 {
    let v = vec![x, 2, 3]; // VEC
    std::hint::black_box(&x);
    v[0]
}

fn main() {
    let x: u32 = env::args().nth(1).unwrap().parse().unwrap();
    let s = env::args().nth(2).unwrap();
    println!("CLONE {}", cloned(x));
    println!("THROUGH {}", through(x));
    println!("FIELD {}", field(x));
    println!("TWICE {}", doubled(x));
    println!("SIZE {}", sized(s));
    println!("MIXED {}", mixed(x, 10));
    println!("VEC {}", listed(x));
}
"""
# lldb-dap 21 writes memory (macOS here); 18 and 20 cannot, and a String's text is on the heap.
WRITES = sys.platform == "darwin"
RUN = ("--", "5", "hello")


def line_of(marker):
    return next(i for i, line in enumerate(SOURCE.splitlines(), 1) if f"// {marker}" in line)


@pytest.fixture
def crate(tmp_path, monkeypatch):
    names = ("CARGO", "RUSTC", "DAP", "DWARFDUMP", "LINKER")
    if not all(os.environ.get("PEEKY_RUST_" + name) for name in names):
        pytest.skip("set PEEKY_RUST_* tool paths to enable Rust conformance")
    monkeypatch.setenv("PEEKY_STATE_DIR", str(tmp_path / "state"))
    root = tmp_path / "inlined"
    (root / "src").mkdir(parents=True)
    (root / "Cargo.toml").write_text(MANIFEST)
    (root / "Cargo.lock").write_text(LOCK)
    (root / "src/main.rs").write_text(SOURCE)
    return root


def probe(capsys, root, marker, *argv):
    at = ["probe", str(root), "--at", f"src/main.rs:{line_of(marker)}", "--json", "--quiet"]
    code = main([*at, *argv, *RUN])
    return code, json.loads(capsys.readouterr().out)


def rows(result, selector):
    """The rows of ``selector`` as the stop showed it, before any change."""
    return [
        row
        for row in result["rows"]
        if row["selector"] == selector and row.get("phase") == "observed"
    ]


def refused(code, result):
    """The message of a refusal at the stop."""
    error = result.get("error") or {}
    assert code != 0 and error.get("code") == "MUTATION_REJECTED", result
    return error["message"]


def printed(result, label):
    return [line for line in result["output"].splitlines() if line.startswith(f"{label} ")]


@pytest.mark.timeout(600)
def test_a_line_breakpoint_past_an_inlined_read_withholds_what_the_call_was_given(crate, capsys):
    for marker, local, call in (
        ("CLONE", "x", "clone"),
        ("THROUGH", "x", "clone"),
        ("TWICE", "x", "twice"),
    ):
        line = line_of(marker)
        code, result = probe(capsys, crate, marker, "--capture", local)
        assert code == 0, result.get("error")
        (row,) = rows(result, local)
        assert row.get("settable") is False, row
        assert row.get("not_settable") == f"line {line}'s inlined `{call}` may have read it", row
        code, result = probe(capsys, crate, marker, "--set", f"{local}=100")
        message = refused(code, result)
        assert result["error"]["hint"].endswith(
            "or `session step` onto the line from the one before it."
        )
        assert (
            f"line {line}'s code may already have read `{local}` before this stop: the build "
            f"inlined `{call}` there, which is given `{local}` or what may point into it, and "
            "that code runs before the line's first instruction of its own, where a line "
            "breakpoint stops"
        ) in message, message
        assert f"reach line {line} with `session step` from the line before it" in message
    # A field: the call is given a pointer to `p.a`.
    message = refused(*probe(capsys, crate, "FIELD", "--set", "p.a=100"))
    assert f"line {line_of('FIELD')}'s code may already have read `p`" in message, message
    # A String's text, where lldb-dap writes memory.
    if WRITES:
        message = refused(*probe(capsys, crate, "SIZE", "--set", 's="zz"'))
        assert f"line {line_of('SIZE')}'s code may already have read `s`" in message, message
    # A line earlier, before the inlined code runs, the change reaches `y`: 100 + 1.
    code, result = probe(capsys, crate, "BEFORE", "--set", "x=100")
    assert code == 0, result.get("error")
    assert printed(result, "CLONE") == ["CLONE 101"], result["output"]


@pytest.mark.timeout(600)
def test_the_inlined_call_withholds_only_what_it_is_given(crate, capsys):
    # `let y = z.clone() + x;`: the inlined `clone` read `z`; the line reads `x` after the
    # stop, so `x` stays settable and the change reaches `y`: 10 + 100.
    code, result = probe(capsys, crate, "MIXED", "--capture", "x,z", "--set", "x=100")
    assert code == 0, result.get("error")
    # `z` is withheld: the statement's temporary may hold its copy.
    (z,) = rows(result, "z")
    assert z.get("settable") is False and z.get("not_settable"), z
    assert printed(result, "MIXED") == ["MIXED 110"], result["output"]
    # `vec!`'s inlined allocation is given nothing of the program's: `x` is stored after it.
    code, result = probe(capsys, crate, "VEC", "--set", "x=100")
    assert code == 0, result.get("error")
    assert printed(result, "VEC") == ["VEC 100"], result["output"]


@pytest.mark.timeout(600)
def test_a_step_onto_the_line_stops_before_its_inlined_code(crate, capsys):
    # A step from the line before stops at the inlined call's first instruction (LLDB shows
    # the caller there): nothing of the line has run, so the change reaches `y`.
    at = f"src/main.rs:{line_of('BEFORE')}"
    assert main(["session", "start", str(crate), "--at", at, *RUN]) == 0
    capsys.readouterr()
    assert main(["session", "step"]) == 0
    capsys.readouterr()
    assert main(["session", "inspect", "--json"]) == 0
    snapshot = json.loads(capsys.readouterr().out)
    assert snapshot["frames"][0]["line"] == line_of("CLONE"), snapshot["frames"][0]
    (row,) = [v for s in snapshot["scopes"] for v in s["variables"] if v["name"] == "x"]
    assert row.get("settable") is True, row
    assert main(["session", "set", "x=100", "--json"]) == 0
    assert json.loads(capsys.readouterr().out)["after"] == "100"
    assert main(["session", "continue", "--to-exit"]) == 0
    capsys.readouterr()
    assert main(["session", "report", "--json"]) == 0
    text = json.loads(capsys.readouterr().out)["output"]
    assert main(["session", "close"]) == 0
    assert "CLONE 101" in text, text
