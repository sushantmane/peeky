"""A Rust line that stops several times per pass says so: in `movavg`,
`out.push(format!("{:.1}", mean));` stops at each of `format!`'s blocks, so `--hits all`
gives 12 hits for 4 values, and `--hits`/`--set-hit` count stops, not passes."""

import json
import os
import platform
import signal
import threading

import pytest

from peeky.cli import main

MANIFEST = """[package]
name = "movavg"
version = "0.1.0"
edition = "2024"

[dependencies]
"""
LOCK = """# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4

[[package]]
name = "movavg"
version = "0.1.0"
"""
MAIN = """use std::env;

/// Rolling mean over the last `k` values, printed with one decimal after each value.
struct Window {
    k: usize,
    values: Vec<i64>,
    sum: i64,
}

impl Window {
    fn push(&mut self, v: i64) -> f64 {
        self.values.push(v);
        self.sum += v;
        if self.values.len() >= self.k {
            let old = self.values.remove(0);
            self.sum -= old;
        }
        self.sum as f64 / self.values.len() as f64
    }
}

fn main() {
    let args: Vec<String> = env::args().collect();
    let k: usize = args[1].parse().unwrap();
    let mut w = Window { k, values: Vec::new(), sum: 0 };
    let mut out = Vec::new();
    for v in args[2].split(',') { // FOR
        let mean = w.push(v.parse().unwrap()); // PUSH
        out.push(format!("{:.1}", mean)); // FORMAT
    }
    println!("MEANS:{}", out.join(","));
}
"""


@pytest.fixture
def movavg(tmp_path, monkeypatch):
    names = ("CARGO", "RUSTC", "DAP", "DWARFDUMP", "LINKER")
    if not all(os.environ.get("PEEKY_RUST_" + name) for name in names):
        pytest.skip("set PEEKY_RUST_* tool paths to enable Rust conformance")
    monkeypatch.setenv("PEEKY_STATE_DIR", str(tmp_path / "state"))
    root = tmp_path / "movavg"
    (root / "src").mkdir(parents=True)
    (root / "Cargo.toml").write_text(MANIFEST)
    (root / "Cargo.lock").write_text(LOCK)
    (root / "src/main.rs").write_text(MAIN)
    return root


def at(marker):
    return "src/main.rs:" + str(
        next(i for i, line in enumerate(MAIN.splitlines(), 1) if f"// {marker}" in line)
    )


def probe(root, capsys, where, *extra):
    command = ["probe", str(root), "--at", where, "--capture", "mean", *extra]
    assert main([*command, "--json", "--quiet", "--", "3", "3,6,9,12"]) == 0
    result = json.loads(capsys.readouterr().out)
    assert result["status"] == "completed", result
    assert result["output"].strip() == "MEANS:3.0,4.5,7.5,10.5"
    return result


def per_pass(result):
    return [w for w in result["warnings"] if "times per pass" in w]


def for_header(result):
    """`for v in …`'s two stops (into_iter, then the iterator's `next`) and what the probe
    says of them. On arm64 both run before the loop: the loop note. On x86-64 the loop jumps
    back to line 0's code (the `leaq` of `next`'s argument) just before the second, which
    stops at each of the 5 checks for 4 values: the per-pass warning, and each stop."""
    loop = [w for w in result["warnings"] if "is a loop header: it stops twice" in w]
    stops = [(row["stop"], row["stops"]) for row in result["rows"]]
    if platform.machine().lower() in ("x86_64", "amd64"):
        assert result["hits"] == 6 and per_pass(result) and not loop, result["warnings"]
        assert stops == [(1, 2)] + [(2, 2)] * 5, stops
    else:
        assert result["hits"] == 2 and not per_pass(result) and loop, result["warnings"]
        assert stops == [(1, 2), (2, 2)], stops


@pytest.mark.timeout(600)
def test_formats_line_says_it_stops_three_times_per_pass(movavg, capsys):
    where = at("FORMAT")
    result = probe(movavg, capsys, where, "--hits", "all")
    assert result["hits"] == 12
    (warning,) = per_pass(result)
    line = where.split(":")[1]
    assert warning.startswith(
        f"Line {line} stops up to 3 times per pass in movavg::main (3 breakpoint locations): "
        "--hits, --set-hit and --set-at's @HIT count stops, not passes"
    ), warning
    rows = [(row["stop"], row["stops"], row["value"]) for row in result["rows"]]
    assert rows == [(stop, 3, mean) for mean in ("3.0", "4.5", "7.5", "10.5") for stop in (1, 2, 3)]
    # --hits counts stops: the 4th is the second pass's first.
    result = probe(movavg, capsys, where, "--hits", "4")
    assert result["hits"] == 4 and per_pass(result)
    assert (result["rows"][-1]["stop"], result["rows"][-1]["value"]) == (1, "4.5")


@pytest.mark.timeout(600)
def test_a_for_header_has_two_locations_both_before_the_loop(movavg, capsys):
    # `for v in xs` has two blocks' first code on its line, `into_iter` and the iterator's
    # binding: two stops, both before the first pass, and none at later passes. Its loop
    # note says so, in place of the per-pass warning.
    result = probe(movavg, capsys, at("FOR"), "--hits", "all")
    for_header(result)
    # A plain line stops once per pass: no warning, no stop.
    result = probe(movavg, capsys, at("PUSH"), "--hits", "all")
    assert result["hits"] == 4 and not per_pass(result)
    assert not any("stop" in row for row in result["rows"])


def stall(monkeypatch, when, seconds):
    """Freeze lldb-dap (SIGSTOP) for ``seconds``, once: as the launch asks `breakpoint list`
    (``when`` "launch"), or at the first stop ("stop"), as a loaded machine may stall it.
    Returns the timers that resume it, to join."""
    from peeky.dap import DAP

    timers = []

    def resume(pid):
        try:
            os.kill(pid, signal.SIGCONT)
        except ProcessLookupError:
            pass

    def freeze(dap):
        os.kill(dap.process.pid, signal.SIGSTOP)
        timers.append(threading.Timer(seconds, resume, (dap.process.pid,)))
        timers[-1].start()

    accept, send = DAP._accept, DAP.send

    def accepted(self, body):
        if when == "stop" and not timers and isinstance(body, dict):
            if body.get("type") == "event" and body.get("event") == "stopped":
                freeze(self)
        return accept(self, body)

    def sent(self, command, arguments=None, *args, **kwargs):
        text = (arguments or {}).get("expression", "") if command == "evaluate" else ""
        if when == "launch" and not timers and text.startswith("`breakpoint list"):
            freeze(self)
        return send(self, command, arguments, *args, **kwargs)

    monkeypatch.setattr(DAP, "_accept", accepted)
    monkeypatch.setattr(DAP, "send", sent)
    return timers


@pytest.mark.timeout(600)
@pytest.mark.parametrize(("when", "seconds"), [("launch", 5.5), ("stop", 2.5)])
def test_a_debugger_stalled_for_seconds_still_gives_the_loop_note_and_each_stop(
    movavg, capsys, monkeypatch, when, seconds
):
    # A loaded machine can stall the debugger for seconds: given too little time to say
    # where the breakpoint's locations are at launch, or for the stop's frame, the probe
    # would leave out the loop note, or each hit's stop, without a word. Here lldb-dap is
    # frozen past waits of 5 s and 2 s: everything still has time.
    timers = stall(monkeypatch, when, seconds)
    try:
        result = probe(movavg, capsys, at("FOR"), "--hits", "all")
    finally:
        for timer in timers:
            timer.join()
    assert len(timers) == 1
    for_header(result)


@pytest.mark.timeout(600)
def test_a_debugger_stalled_past_a_stops_read_fails_the_probe_with_no_stop_shown(
    movavg, capsys, monkeypatch
):
    # Frozen past the 15 s a stop's frame is read with, the probe fails with TIMEOUT, and
    # shows no row for the stop, rather than one with no `stop` (and no line or function),
    # as if it were all there was.
    timers = stall(monkeypatch, "stop", 15.5)
    command = ["probe", str(movavg), "--at", at("FOR"), "--capture", "mean", "--hits", "all"]
    try:
        code = main([*command, "--json", "--quiet", "--", "3", "3,6,9,12"])
    finally:
        for timer in timers:
            timer.join()
    result = json.loads(capsys.readouterr().out)
    assert code != 0 and result["status"] == "failed", result
    assert result["error"]["code"] == "TIMEOUT" and result["error"]["session_closed"] is True
    assert result["rows"] == [] and len(timers) == 1


SHAPES = """#[inline(never)]
fn gener<T: std::fmt::Display + Copy>(xs: &[T]) -> Vec<String> {
    let mut out = Vec::new();
    for x in xs {
        out.push(format!("<{}>", x)); // GEN
    }
    out
}

#[inline(always)]
fn fmt_inl(v: i32) -> String {
    format!("[{}]", v) // INL
}

#[inline(never)]
fn uses_inl(a: i32) -> String {
    fmt_inl(a) + &fmt_inl(a + 1)
}

fn main() {
    let a = gener(&[1, 2]);
    let b = gener(&["x", "y"]);
    println!("{:?} {:?} {}", a, b, uses_inl(5));
}
"""


@pytest.mark.timeout(600)
def test_inlined_copies_and_generic_instances_are_told_apart(movavg, capsys):
    # `format!` in an `#[inline(always)]` function called twice stops 6 times for 2 calls,
    # and the warning says so: its locations are not taken for inlined copies of their own.
    # Two instances of a generic each get a warning named with their type arguments.
    (movavg / "src/main.rs").write_text(SHAPES)
    (movavg / "Cargo.toml").write_text(MANIFEST.replace("movavg", "shapes"))
    (movavg / "Cargo.lock").write_text(LOCK.replace("movavg", "shapes"))

    def run(marker):
        line = next(i for i, text in enumerate(SHAPES.splitlines(), 1) if f"// {marker}" in text)
        command = ["probe", str(movavg), "--at", f"src/main.rs:{line}", "--capture", "x"]
        assert main([*command, "--hits", "all", "--json", "--quiet"]) == 0
        result = json.loads(capsys.readouterr().out)
        assert result["status"] == "completed" and "[5][6]" in result["output"], result
        return line, result

    line, result = run("INL")
    assert result["hits"] == 6
    (warning,) = per_pass(result)
    assert warning.startswith(
        f"Line {line} stops up to 3 times per pass in shapes::fmt_inl (3 breakpoint locations)"
    ), warning
    assert [row["stop"] for row in result["rows"]] == [1, 2, 3, 1, 2, 3]
    line, result = run("GEN")
    assert result["hits"] == 12
    # One per instance, in the order of their code.
    assert sorted(w.split(" (")[0] for w in per_pass(result)) == [
        f"Line {line} stops up to 3 times per pass in shapes::gener<&str>",
        f"Line {line} stops up to 3 times per pass in shapes::gener<i32>",
    ], result["warnings"]
    assert any(w.startswith(f"Line {line} stopped in 2 functions") for w in result["warnings"])


SET_AT = """use std::hint::black_box;

fn main() {
    let mut out = Vec::new();
    let mut x: i64 = 0;
    black_box(&mut x);
    for i in 0..3i64 {
        x += i;
        out.push(format!("{}-{}", x, i)); // MULTI
        println!("after {} {}", i, x);
    }
    println!("{:?}", out);
}
"""


@pytest.mark.timeout(600)
def test_a_set_at_says_which_stop_its_hit_was(movavg, capsys):
    # `--set-at 9@2 x=100` on a `format!` line changes x at the line's 2nd stop, its first
    # pass's 2nd location: the change, the JSON, the evidence and `queries wide` say which
    # stop, not only `9@2`, as if it were the 2nd pass.
    (movavg / "src/main.rs").write_text(SET_AT)
    (movavg / "Cargo.toml").write_text(MANIFEST.replace("movavg", "s1"))
    (movavg / "Cargo.lock").write_text(LOCK.replace("movavg", "s1"))
    line = next(i for i, text in enumerate(SET_AT.splitlines(), 1) if "// MULTI" in text)
    command = ["probe", str(movavg), "--at", f"src/main.rs:{line}", "--capture", "x"]
    command += ["--hits", "4", "--set-at", f"{line}@2", "x=100"]
    assert main([*command, "--json", "--quiet"]) == 0
    result = json.loads(capsys.readouterr().out)
    assert "after 0 100" in result["output"], result
    (change,) = result["interventions"]
    assert (change["at"], change["stop"], change["stops"]) == (f"{line}@2", 2, 3), change
    assert main(["sql", "SELECT hit, stop FROM interventions", "--json"]) == 0
    assert json.loads(capsys.readouterr().out)["rows"] == [{"hit": 2, "stop": 2}]
    assert main(["queries", "wide", "--json"]) == 0
    wide = json.loads(capsys.readouterr().out)["rows"]
    assert [row["sets"] for row in wide if row["sets"]] == [
        f'["x: 0 -> 100 (line {line}, hit 2, stop 2, in s1::main)"]'
    ]
    assert main(["queries", "set_effect", "--json"]) == 0
    assert {row["stop"] for row in json.loads(capsys.readouterr().out)["rows"]} == {2}
    # The table's change line says it too.
    assert main(command) == 0
    shown = capsys.readouterr().out
    assert f"set x: 0 -> 100  (--set-at line {line}@2, stop 2 of 3, in s1::main)" in shown
