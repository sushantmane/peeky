"""A Rust line that stops several times per pass (#157): the seventh evaluation's
`movavg`, where `out.push(format!("{:.1}", mean));` stops at each of `format!`'s blocks,
so `--hits all` gave 12 hits for 4 values with no word that the line stops 3 times per
pass, and `--hits`/`--set-hit` counted stops where the agent counted passes."""

import json
import os

import pytest

from peeky.cli import main

MANIFEST = """[package]
name = "movavg"
version = "0.1.0"
edition = "2024"

[dependencies]
"""
LOCK = """# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4

[[package]]
name = "movavg"
version = "0.1.0"
"""
MAIN = """use std::env;

/// Rolling mean over the last `k` values, printed with one decimal after each value.
struct Window {
    k: usize,
    values: Vec<i64>,
    sum: i64,
}

impl Window {
    fn push(&mut self, v: i64) -> f64 {
        self.values.push(v);
        self.sum += v;
        if self.values.len() >= self.k {
            let old = self.values.remove(0);
            self.sum -= old;
        }
        self.sum as f64 / self.values.len() as f64
    }
}

fn main() {
    let args: Vec<String> = env::args().collect();
    let k: usize = args[1].parse().unwrap();
    let mut w = Window { k, values: Vec::new(), sum: 0 };
    let mut out = Vec::new();
    for v in args[2].split(',') { // FOR
        let mean = w.push(v.parse().unwrap()); // PUSH
        out.push(format!("{:.1}", mean)); // FORMAT
    }
    println!("MEANS:{}", out.join(","));
}
"""


@pytest.fixture
def movavg(tmp_path, monkeypatch):
    names = ("CARGO", "RUSTC", "DAP", "DWARFDUMP", "LINKER")
    if not all(os.environ.get("PEEKY_RUST_" + name) for name in names):
        pytest.skip("set PEEKY_RUST_* tool paths to enable Rust conformance")
    monkeypatch.setenv("PEEKY_STATE_DIR", str(tmp_path / "state"))
    root = tmp_path / "movavg"
    (root / "src").mkdir(parents=True)
    (root / "Cargo.toml").write_text(MANIFEST)
    (root / "Cargo.lock").write_text(LOCK)
    (root / "src/main.rs").write_text(MAIN)
    return root


def at(marker):
    return "src/main.rs:" + str(
        next(i for i, line in enumerate(MAIN.splitlines(), 1) if f"// {marker}" in line)
    )


def probe(root, capsys, where, *extra):
    command = ["probe", str(root), "--at", where, "--capture", "mean", *extra]
    assert main([*command, "--json", "--quiet", "--", "3", "3,6,9,12"]) == 0
    result = json.loads(capsys.readouterr().out)
    assert result["status"] == "completed", result
    assert result["output"].strip() == "MEANS:3.0,4.5,7.5,10.5"
    return result


def per_pass(result):
    return [w for w in result["warnings"] if "times per pass" in w]


@pytest.mark.timeout(600)
def test_formats_line_says_it_stops_three_times_per_pass(movavg, capsys):
    where = at("FORMAT")
    result = probe(movavg, capsys, where, "--hits", "all")
    assert result["hits"] == 12
    (warning,) = per_pass(result)
    line = where.split(":")[1]
    assert warning.startswith(
        f"Line {line} stops up to 3 times per pass in movavg::main (3 breakpoint locations): "
        "--hits and --set-hit count stops, not passes"
    ), warning
    rows = [(row["stop"], row["stops"], row["value"]) for row in result["rows"]]
    assert rows == [(stop, 3, mean) for mean in ("3.0", "4.5", "7.5", "10.5") for stop in (1, 2, 3)]
    # --hits counts stops: the 4th is the second pass's first.
    result = probe(movavg, capsys, where, "--hits", "4")
    assert result["hits"] == 4 and per_pass(result)
    assert (result["rows"][-1]["stop"], result["rows"][-1]["value"]) == (1, "4.5")


@pytest.mark.timeout(600)
def test_a_for_header_has_two_locations_both_before_the_loop(movavg, capsys):
    # `for v in xs` has two blocks' first code on its line, `into_iter` and the iterator's
    # binding: two stops, both before the first pass, and none at later passes.
    result = probe(movavg, capsys, at("FOR"), "--hits", "all")
    assert result["hits"] == 2 and len(per_pass(result)) == 1
    assert [(row["stop"], row["stops"]) for row in result["rows"]] == [(1, 2), (2, 2)]
    # A plain line stops once per pass: no warning, no stop.
    result = probe(movavg, capsys, at("PUSH"), "--hits", "all")
    assert result["hits"] == 4 and not per_pass(result)
    assert not any("stop" in row for row in result["rows"])
