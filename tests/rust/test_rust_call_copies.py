"""A value a call returns, given a pointer into the local or to what holds a copy of it,
may be a copy (#320). After `let y = x.clone();`, `s.push_str(&x.to_string());` or `let y =
unsafe { std::ptr::read(&x) };`, `x` was `[settable]` where the program goes on with the
copy: `--set x=100` was reported, and the output kept the old value. Now `x` is refused
there, naming the copy, and a change before the copy still reaches the program. The
standard library's measures and comparisons (`len`, `contains`, `eq`, `cmp`) return no
copy, but a crate's own `String::len` may. After `mem::take(&mut a)`, the refusal names
its result `b`, not `a`."""

import json
import os

import pytest

from peeky.cli import main

MANIFEST = """[package]
name = "{name}"
version = "0.1.0"
edition = "2024"

[dependencies]
"""
LOCK = """# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4

[[package]]
name = "{name}"
version = "0.1.0"
"""
CALLS = """use std::env;

#[inline(never)]
fn other() -> u32 {
    1
}

fn cloned(arg: u32) -> u32 {
    let x = std::convert::identity(arg);
    let j = other(); // BEFORE
    let y = x.clone(); // CLONE
    let k = other(); // CLONED
    let t = y + j + k;
    std::hint::black_box(&x);
    t
}

fn texted(arg: u32) -> String {
    let x = std::convert::identity(arg);
    let mut s = String::new();
    s.push_str(&x.to_string()); // TEXT
    let k = other(); // TEXTED
    let t = format!("{}+{}", s, k);
    std::hint::black_box(&x);
    t
}

fn read(arg: u32) -> u32 {
    let x = std::convert::identity(arg);
    let y = unsafe { std::ptr::read(&x) }; // READ
    let k = other(); // READS
    let t = y + k;
    std::hint::black_box(&x);
    t
}

fn taken(arg: u32) -> u32 {
    let x = std::convert::identity(arg);
    let mut a = x; // MOVE
    let b = std::mem::take(&mut a); // TAKE
    let k = other(); // TAKEN
    let t = a + b + k;
    std::hint::black_box(&x);
    t
}

fn formatted(arg: u32) -> String {
    let x = std::convert::identity(arg);
    let s = format!("<{}>", x); // FORMAT
    let k = other(); // FORMATTED
    let t = format!("{}{}", s, k);
    std::hint::black_box(&x);
    t
}

fn extended(arg: u32) -> u32 {
    let x = std::convert::identity(arg);
    let mut v = Vec::new();
    v.extend_from_slice(std::slice::from_ref(&x)); // EXTEND
    let k = other(); // EXTENDED
    let t = v[0] + k;
    std::hint::black_box(&x);
    t
}

fn measured(arg: u32) -> u32 {
    let x = std::convert::identity(arg);
    let a = [x, 2];
    let n = a.len() + a.contains(&5) as usize;
    let e = x.eq(&5);
    let c = x.cmp(&5);
    let p = x.partial_cmp(&5);
    let k = other(); // MEASURED
    let t = n as u32 + e as u32 + c as u32 + p.is_some() as u32 + k;
    std::hint::black_box(&x);
    t
}

#[inline(never)]
fn hybrid(x: &u32) -> (u32, &'static ()) {
    (*x, &())
}

struct Hybrid<'a> {
    v: u32,
    r: &'a u32,
}

#[inline(never)]
fn hybrid_struct(x: &u32) -> Hybrid<'_> {
    Hybrid { v: *x, r: x }
}

fn paired(arg: u32) -> u32 {
    let x = std::convert::identity(arg);
    let h = hybrid(&x); // PAIR
    let k = other(); // PAIRED
    let t = h.0 + k;
    std::hint::black_box(&x);
    t
}

fn held(arg: u32) -> u32 {
    let x = std::convert::identity(arg);
    let h = hybrid_struct(&x); // HOLD
    let k = other(); // HELD
    let t = h.v + k;
    std::hint::black_box(h.r);
    t
}

fn main() {
    let x: u32 = env::args().nth(1).unwrap().parse().unwrap();
    println!("CLONED {}", cloned(x));
    println!("TEXTED {}", texted(x));
    println!("READS {}", read(x));
    println!("TAKEN {}", taken(x));
    println!("FORMATTED {}", formatted(x));
    println!("EXTENDED {}", extended(x));
    println!("MEASURED {}", measured(x));
    println!("PAIRED {}", paired(x));
    println!("HELD {}", held(x));
}
"""
# #320 review: types of the crate's own named as the standard library's `String` and `Vec`,
# whose `len` the dump names `String::len` and `Vec::len`, as it would the standard one.
OWNED = """use std::env;

// Types of the crate's own, named as the standard library's, with a `len` that returns
// what it reads.
struct String;

impl String {
    #[inline(never)]
    fn len(s: &std::string::String) -> usize {
        s.parse().unwrap()
    }
}

struct Vec;

impl Vec {
    #[inline(never)]
    fn len(v: &std::vec::Vec<u32>) -> usize {
        v[0] as usize
    }
}

#[inline(never)]
fn other() -> u32 {
    1
}

fn texts(arg: u32) -> usize {
    let x = std::convert::identity(arg);
    let n = String::len(&x.to_string()); // TEXT
    let k = other(); // TEXTS
    let t = n + k as usize;
    std::hint::black_box(&x);
    t
}

fn items(arg: u32) -> usize {
    let x = std::convert::identity(arg);
    let n = Vec::len(&vec![x, 2]); // ITEM
    let k = other(); // ITEMS
    let t = n + k as usize;
    std::hint::black_box(&x);
    t
}

fn main() {
    let x: u32 = env::args().nth(1).unwrap().parse().unwrap();
    println!("TEXTS {}", texts(x));
    println!("ITEMS {}", items(x));
}
"""

# #320 review round 2: a crate `mod alloc` whose `str::Chars` holds a value beside a
# reference, and the standard library's iterator adapters.
ADAPTERS = """use std::env;

// A module of the crate's own named like the standard library's `alloc`, whose `Chars`
// holds a value beside a reference.
mod alloc {
    pub mod str {
        pub struct Chars<'a> {
            pub v: u32,
            pub r: &'a (),
        }
    }
}

#[inline(never)]
fn other() -> u32 {
    1
}

#[inline(never)]
fn mark() {}

#[inline(never)]
fn shadow(x: &u32) -> alloc::str::Chars<'static> {
    alloc::str::Chars { v: *x, r: &() }
}

#[inline(never)]
fn rev_of(s: &str) -> std::iter::Rev<std::str::Chars<'_>> {
    s.chars().rev()
}

fn shadowed(arg: u32) -> u32 {
    let x = std::convert::identity(arg);
    let c = shadow(&x); // SHADOW
    let k = other(); // SHADOWED
    let t = c.v + k;
    std::hint::black_box((&x, c.r));
    t
}

fn reversed() -> usize {
    let mut s = String::with_capacity(16);
    s.push_str("abc");
    let it = s.chars().rev(); // REV
    mark(); // REVERSED
    let n = it.count();
    let made = rev_of(&s); // MADE
    mark(); // REMADE
    let m = made.count();
    s.push('!');
    n + m
}

fn mapped(arg: u32) -> u32 {
    let x = std::convert::identity(arg);
    let a = [1u32, 2];
    let it = a.iter().map(move |e| e + x); // MAP
    let k = other(); // MAPPED
    let t = it.sum::<u32>() + k;
    std::hint::black_box(&x);
    t
}

fn lent(arg: u32) -> u32 {
    let x = std::convert::identity(arg);
    let a = [1u32, 2];
    let it = a.iter().map(|e| e + x); // LEND
    let k = other(); // LENT
    let t = it.sum::<u32>() + k;
    std::hint::black_box(&x);
    t
}

fn main() {
    let x: u32 = env::args().nth(1).unwrap().parse().unwrap();
    println!("SHADOWED {}", shadowed(x));
    println!("REVERSED {}", reversed());
    println!("MAPPED {}", mapped(x));
    println!("LENT {}", lent(x));
}
"""


def line_of(text, marker):
    return next(i for i, line in enumerate(text.splitlines(), 1) if f"// {marker}" in line)


@pytest.fixture
def crate(tmp_path, monkeypatch):
    names = ("CARGO", "RUSTC", "DAP", "DWARFDUMP", "LINKER")
    if not all(os.environ.get("PEEKY_RUST_" + name) for name in names):
        pytest.skip("set PEEKY_RUST_* tool paths to enable Rust conformance")
    monkeypatch.setenv("PEEKY_STATE_DIR", str(tmp_path / "state"))

    def make(name, text):
        root = tmp_path / name
        (root / "src").mkdir(parents=True)
        (root / "Cargo.toml").write_text(MANIFEST.format(name=name))
        (root / "Cargo.lock").write_text(LOCK.format(name=name))
        (root / "src/main.rs").write_text(text)
        return root

    return make


def probe(capsys, root, marker, *argv, text=CALLS):
    at = ["probe", str(root), "--at", f"src/main.rs:{line_of(text, marker)}", "--json", "--quiet"]
    code = main([*at, *argv, "--", "5"])
    return code, json.loads(capsys.readouterr().out)


def refused(code, result, marker):
    """The message of a refusal made before the program runs."""
    error = result.get("error") or {}
    assert code == 2 and error.get("code") == "MUTATION_REJECTED", (marker, result)
    assert result.get("refused_before_launch") is True, (marker, result)
    return error["message"]


@pytest.mark.timeout(400)
def test_a_copy_a_call_returns_withholds_the_local_where_the_program_goes_on_with_it(crate, capsys):
    root = crate("calls", CALLS)
    # Each line after the copy: `x` is never read again (`black_box(&x)` only lends it).
    for marker, holder, made in (
        ("CLONED", "y", "CLONE"),
        ("TEXTED", "s", "TEXT"),
        ("READS", "y", "READ"),
        ("TAKEN", "b", "TAKE"),
        ("FORMATTED", "s", None),
        ("EXTENDED", "v", "EXTEND"),
        # #320 review: a value beside a reference, `(u32, &'static ())` and `Hybrid<'_>`.
        ("PAIRED", "h", "PAIR"),
        ("HELD", "h", "HOLD"),
    ):
        message = refused(*probe(capsys, root, marker, "--set", "x=100"), marker)
        assert f"the program's own `{holder}` (at " in message, (marker, message)
        if made is not None:
            assert f"{line_of(CALLS, made)})" in message, (marker, message)
        assert "may hold a copy of `x` that it goes on with" in message, (marker, message)
    # `a` holds its default after `mem::take`; `b` holds the copy.
    code, result = probe(capsys, root, "TAKEN", "--set", "x=100")
    assert "`a`" not in result["error"]["message"].split("Refused")[0], result["error"]
    # The row says so too, without a `--set`.
    code, result = probe(capsys, root, "CLONED", "--capture", "x")
    assert code == 0, result.get("error")
    (row,) = [row for row in result["rows"] if row["selector"] == "x"]
    assert row["value"] == "5" and row.get("settable") is False, row
    clone = line_of(CALLS, "CLONE")
    assert row.get("not_settable") == f"the program may hold a copy (line {clone})", row


@pytest.mark.timeout(400)
def test_a_change_before_the_copy_still_reaches_the_program(crate, capsys):
    root = crate("calls", CALLS)
    for marker, printed in (
        ("BEFORE", "CLONED 102"),
        ("TEXT", "TEXTED 100+1"),
        ("READ", "READS 101"),
        ("MOVE", "TAKEN 101"),
        ("FORMAT", "FORMATTED <100>1"),
        ("EXTEND", "EXTENDED 101"),
        ("PAIR", "PAIRED 101"),
        ("HOLD", "HELD 101"),
    ):
        code, result = probe(capsys, root, marker, "--set", "x=100")
        assert code == 0, (marker, result.get("error"))
        assert printed in result["output"].splitlines(), (marker, result["output"])


@pytest.mark.timeout(400)
def test_the_standard_librarys_measures_and_comparisons_leave_the_local_settable(crate, capsys):
    # `a.len()`, `a.contains(&5)`, `x.eq(&5)`, `x.cmp(&5)`, `x.partial_cmp(&5)`: what each
    # returns can't hold a `u32`. `a = [x, 2]` holds a copy, but isn't used after the stop.
    root = crate("calls", CALLS)
    code, result = probe(capsys, root, "MEASURED", "--capture", "x", "--set", "x=100")
    assert code == 0, result.get("error")
    assert result["interventions"][0]["after"] == "100", result["interventions"]
    assert "MEASURED 6" in result["output"].splitlines(), result["output"]


@pytest.mark.timeout(400)
def test_a_crate_type_named_like_a_standard_one_measures_nothing(crate, capsys):
    # #320 review: `String::len(&x.to_string())` and `Vec::len(&vec![x, 2])` call the
    # crate's own `len`, which returns what it reads. Taken for the standard library's,
    # `x` was settable after them, and the program printed the old `n`.
    root = crate("owned", OWNED)
    for marker, made in (("TEXTS", "TEXT"), ("ITEMS", "ITEM")):
        message = refused(*probe(capsys, root, marker, "--set", "x=100", text=OWNED), marker)
        held = f"the program's own `n` (at line {line_of(OWNED, made)}) may hold a copy of `x`"
        assert held in message, (marker, message)
    # Before the call, the change reaches it.
    for marker, printed in (("TEXT", "TEXTS 101"), ("ITEM", "ITEMS 101")):
        code, result = probe(capsys, root, marker, "--set", "x=100", text=OWNED)
        assert code == 0, (marker, result.get("error"))
        assert printed in result["output"].splitlines(), (marker, result["output"])


@pytest.mark.timeout(400)
def test_a_shadowed_view_or_an_adapter_is_said_to_hold_what_it_holds(crate, capsys):
    root = crate("adapters", ADAPTERS)

    def at(marker, *argv):
        return probe(capsys, root, marker, *argv, text=ADAPTERS)

    # The crate's `alloc::str::Chars` is not the standard library's view: `c` may hold a
    # copy of `x`, or only point into it, and there may be no copy to change.
    code, result = at("SHADOWED", "--set", "x=100")
    message = refused(code, result, "SHADOWED")
    assert (
        f"the program's own `c` (at line {line_of(ADAPTERS, 'SHADOW')}) may hold a copy of `x` "
        "that it goes on with, unless `c` only points into it"
    ) in message, message
    assert "copies or borrows it" in result["error"]["hint"], result["error"]
    code, result = at("SHADOW", "--set", "x=100")
    assert code == 0 and "SHADOWED 101" in result["output"].splitlines(), result
    # `s.chars().rev()` only borrows `s`: refused for that borrow, not for a copy.
    code, result = at("REVERSED", "--set", 's="xy"')
    message = (result.get("error") or {}).get("message", "")
    assert code != 0 and "`s` cannot be changed to a text at this stop: change it before a" in (
        message
    ), result
    assert "the program's own" not in message, message
    # `map` with a `move` closure holding `x`'s copy holds a copy; with one borrowing `x`, the
    # change reaches the sum.
    message = refused(*at("MAPPED", "--set", "x=100"), "MAPPED")
    assert (
        f"the program's own `it` (at line {line_of(ADAPTERS, 'MAP')}) may hold a copy of `x` "
        "that it goes on with, so"
    ) in message, message
    for marker, printed in (("MAP", "MAPPED 204"), ("LENT", "LENT 204")):
        code, result = at(marker, "--set", "x=100")
        assert code == 0, (marker, result.get("error"))
        assert printed in result["output"].splitlines(), (marker, result["output"])
