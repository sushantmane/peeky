"""#222: `let label: String;` then `label = format!(…);`, stopped at the next line's first
stop. `format!`'s last call (`must_use`, spanned in std's `alloc/src/macros.rs`, its code
on line 4 or inlined from there) returns into the MIR block of line 5's `println!`, and
was taken for line 5's code: the stop was placed before `label`'s store, so `label` was
withheld (`no value yet`) and `sum` refused, citing "line 113" of another file as if it
were the program's."""

import json
import os
import re

import pytest

from peeky.cli import main

MANIFEST = """[package]
name = "{name}"
version = "0.1.0"
edition = "2024"

[dependencies]
"""
LOCK = """# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4

[[package]]
name = "{name}"
version = "0.1.0"
"""
REPRO = """fn main() {
    let sum = 6;
    let label: String;
    label = format!("sum {sum}");
    println!("{label}");
}
"""
# A statement spanning two lines, whose `format!` has read `sum` when line 4 stops.
SPANNING = """fn main() {
    let sum = 6;
    let label = format!("sum {sum}")
        + &sum.to_string();
    println!("{label}");
}
"""


@pytest.fixture
def state(tmp_path, monkeypatch):
    names = ("CARGO", "RUSTC", "DAP", "DWARFDUMP", "LINKER")
    if not all(os.environ.get("PEEKY_RUST_" + name) for name in names):
        pytest.skip("set PEEKY_RUST_* tool paths to enable Rust conformance")
    monkeypatch.setenv("PEEKY_STATE_DIR", str(tmp_path / "state"))
    return tmp_path / "state"


def crate_at(tmp_path, name, text):
    root = tmp_path / name
    (root / "src").mkdir(parents=True)
    (root / "Cargo.toml").write_text(MANIFEST.format(name=name))
    (root / "Cargo.lock").write_text(LOCK.format(name=name))
    (root / "src/main.rs").write_text(text)
    return root


def probe(capsys, crate, line, *argv):
    code = main(["probe", str(crate), "--at", f"src/main.rs:{line}", *argv, "--json", "--quiet"])
    return code, json.loads(capsys.readouterr().out)


@pytest.mark.timeout(400)
def test_a_deferred_macro_assignment_reads_at_the_next_lines_first_stop(tmp_path, state, capsys):
    crate = crate_at(tmp_path, "repro", REPRO)
    code, result = probe(capsys, crate, 5, "--capture", "sum,label", "--hits", "3")
    assert code == 0, result.get("error")
    rows = {(row["hit"], row["selector"]): row for row in result["rows"]}
    first = rows[(1, "label")]
    # Line 4's store into `label` has run at every stop of line 5, the first included.
    assert "error" not in first and not first.get("withheld"), first
    if os.environ.get("PEEKY_EXPECT_READ_MEMORY") or first.get("view") == "memory":
        assert [rows[(hit, "label")]["value"] for hit in (1, 2, 3)] == ['"sum 6"'] * 3, rows
    assert rows[(1, "sum")].get("settable") is True, rows[(1, "sum")]
    # So `sum` changes at the default stop, where nothing under way has read it.
    code, result = probe(capsys, crate, 5, "--capture", "sum", "--set", "sum=7")
    assert code == 0, result.get("error")
    (change,) = result["interventions"]
    assert (change["name"], change["after"], change["stop"]) == ("sum", "7", 1), change


@pytest.mark.timeout(400)
def test_a_refusal_names_another_files_line_and_a_stop_that_works(tmp_path, state, capsys):
    crate = crate_at(tmp_path, "spanning", SPANNING)
    code, result = probe(capsys, crate, 4, "--capture", "sum", "--set", "sum=7")
    error = result["error"]
    message = error["message"]
    assert error["code"] == "MUTATION_REJECTED", error
    # `format!`'s code is in std's file, named as such, never as the program's line.
    assert re.search(r"\(at alloc/src/macros\.rs:[0-9]+\)", message), message
    assert not re.search(r"\(at lines? [0-9]", message), message
    # The stop is line 4's first: the advice is a stop before the statement starts.
    assert "Change it before that statement starts: at a stop on an earlier line" in message
    assert "a breakpoint on the statement's first line" not in message, message
    assert "earlier line" in error["hint"], error
