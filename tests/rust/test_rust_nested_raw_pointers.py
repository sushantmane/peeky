"""A raw pointer inside a live value (a field, a tuple or array element, a NonNull's, a fat raw
pointer's address) is never followed, though a struct or tuple the MIR proves initialized reads
everything else: `h.p`'s pointee is something safe code can free (`let p = &*b as *const i64;
drop(b);`). It shows only its address, with a note saying Peeky never follows a raw pointer, as
a raw pointer local does; references inside the same values still read. An array of raw pointers
expands to its elements."""

import json
import os
import re

import pytest

from peeky.cli import main

MANIFEST = """[package]
name = "rawptrs"
version = "0.1.0"
edition = "2024"

[dependencies]
"""
LOCK = """# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4

[[package]]
name = "rawptrs"
version = "0.1.0"
"""
# No `unsafe` anywhere: making a raw pointer, and letting it dangle, is safe.
MAIN = """use std::ptr::NonNull;

pub struct Holder {
    n: i64,
    p: *const i64,
}

pub struct MutHolder {
    n: i64,
    p: *mut i64,
}

pub struct Many {
    ps: [*const i64; 2],
    n: i64,
}

pub struct Outer {
    inner: Holder,
    q: NonNull<i64>,
    text: *const str,
    slot: Slot,
}

pub enum Slot {
    Empty,
    At(*const i64),
}

pub struct Lent<'a> {
    r: &'a i64,
    rr: &'a &'a i64,
    bx: Box<i64>,
    pair: (i64, &'a i64),
}

#[inline(never)]
fn churn() -> i64 {
    let mut total = 0;
    for _ in 0..32 {
        total += *Box::leak(Box::new(777i64));
    }
    total
}

fn dangling() -> i64 {
    let kept = 41i64;
    let b = Box::new(5i64);
    let h = Holder { n: 1, p: &*b as *const i64 };
    let mut c = Box::new(6i64);
    let m = MutHolder { n: 2, p: &mut *c as *mut i64 };
    let d = Box::new(7i64);
    let t: (i64, *const i64) = (3, &*d as *const i64);
    let e = Box::new(8i64);
    let f = Box::new(9i64);
    let a = Many { ps: [&*e as *const i64, &*f as *const i64], n: 4 };
    let arr: [*const i64; 2] = [&*e as *const i64, &*f as *const i64];
    let lone: *const i64 = &*b;
    let g = Box::new(10i64);
    let label = String::from("a label");
    let inner = Holder { n: 5, p: &*g as *const i64 };
    let slot = Slot::At(&*g as *const i64);
    let o = Outer { inner, q: NonNull::from(&*g), text: label.as_str() as *const str, slot };
    let kr = &kept;
    let l = Lent { r: &kept, rr: &kr, bx: Box::new(12), pair: (13, &kept) };
    drop(b);
    drop(c);
    drop(d);
    drop(e);
    drop(f);
    drop(g);
    drop(label);
    let z = churn();
    let held = h.p as i64 + m.p as i64 + t.1 as i64 + a.ps[0] as i64 + o.q.as_ptr() as i64;
    let held = held + arr[0] as i64 + arr[1] as i64 + lone as i64;
    let alive = matches!(o.slot, Slot::At(_)) as i64 + o.text as *const u8 as i64 + held;
    z + h.n + m.n + t.0 + a.n + o.inner.n + *l.r + **l.rr + *l.bx + *l.pair.1 + alive * 0 // OBSERVE
}

fn main() {
    println!("{}", dangling());
}
"""
# Each raw pointer, and the value it is in: the field, element or address of a live,
# proven local in the innermost frame of an unoptimized build.
RAW = {
    "h.p": ("h", "p"),
    "m.p": ("m", "p"),
    "t.__1": ("t", "__1"),
    "a.ps[0]": ("a.ps", "[0]"),
    "a.ps[1]": ("a.ps", "[1]"),
    "o.inner.p": ("o.inner", "p"),
    "o.q.pointer": ("o.q", "pointer"),
    "o.text.data_ptr": ("o.text", "data_ptr"),
    # An array of raw pointers local expands to its elements.
    "arr[0]": ("arr", "[0]"),
    "arr[1]": ("arr", "[1]"),
}
# The note of a raw pointer (probe._RAW_RUST), and of what holds one (_RAW_HELD_RUST):
# no reference's words, nor moved, dropped or unproven claims.
NOTE = (
    "This Rust raw pointer shows only its address: Peeky never follows a raw pointer, "
    "because nothing proves that what it points at still stands."
)
HELD = (
    "Its Rust raw pointers show only their address: Peeky never follows a raw pointer, "
    "because nothing proves that what one points at still stands."
)


@pytest.fixture
def crate(tmp_path, monkeypatch):
    names = ("CARGO", "RUSTC", "DAP", "DWARFDUMP", "LINKER")
    if not all(os.environ.get("PEEKY_RUST_" + name) for name in names):
        pytest.skip("set PEEKY_RUST_* tool paths to enable Rust conformance")
    monkeypatch.setenv("PEEKY_STATE_DIR", str(tmp_path / "state"))
    root = tmp_path / "rawptrs"
    (root / "src").mkdir(parents=True)
    (root / "Cargo.toml").write_text(MANIFEST)
    (root / "Cargo.lock").write_text(LOCK)
    (root / "src/main.rs").write_text(MAIN)
    return root


def line_of(text, marker):
    return next(i for i, line in enumerate(text.splitlines(), 1) if marker in line)


def get(capsys, *selectors):
    code = main(["session", "get", *selectors, "--json"])
    rows = json.loads(capsys.readouterr().out)
    assert code == 0, [f"{row['selector']}: {row['error']}" for row in rows if "error" in row]
    return {row["selector"]: row for row in rows}


def brief(row):
    """What a row shows, for a failure's message."""
    keys = ("value", "view", "children", "unavailable")
    return f"{row.get('selector')}: " + str({key: row[key] for key in keys if key in row})


def address_only(row):
    """Only the pointer: its address, no pointee listed or offered, and the raw pointer's
    note, which claims nothing of a reference's or of a moved or dropped value."""
    assert not row.get("children") and "777" not in str(row), brief(row)
    assert row.get("view") == "unproven", brief(row)
    assert re.fullmatch(r"0x[0-9a-fA-F]+", row.get("value") or ""), brief(row)
    # The row itself says it is a raw pointer, as a listing's child does.
    assert row.get("unproven_pointer") == "raw", brief(row)
    assert row.get("note") == NOTE, row.get("note")
    for claim in ("reference", "moved", "dropped", "MIR", "may be"):
        assert claim not in row["note"], claim


@pytest.mark.timeout(400)
def test_a_raw_pointer_inside_a_live_value_shows_only_its_address(crate, capsys):
    at = f"src/main.rs:{line_of(MAIN, '// OBSERVE')}"
    assert main(["session", "start", str(crate), "--at", at]) == 0
    capsys.readouterr()
    try:
        rows = get(capsys, *RAW, "lone")
        holders = get(capsys, *{holder for holder, _ in RAW.values()})
        enum = get(capsys, "o.slot")["o.slot"]
        lent = get(capsys, "l.r", "l.rr", "l.bx", "l.pair.__1")
        values = get(capsys, "h.n", "m.n", "t.__0", "a.n", "o.inner.n", "o.text.length")
    finally:
        main(["session", "close"])
        capsys.readouterr()
    for selector, (holder, name) in RAW.items():
        address_only(rows[selector])
        # Listed in the value that holds it: never expandable, and why is said there.
        children = {child["name"]: child for child in holders[holder]["children"]}
        assert children[name].get("view") == "unproven", (selector, children[name])
        assert children[name].get("unproven_pointer") == "raw", (selector, children[name])
        assert not children[name].get("expandable"), (selector, children[name])
        assert holders[holder].get("note") == HELD, (selector, holders[holder])
        assert holders[holder].get("view") is None, (selector, holders[holder])
    # A raw pointer local: the same, not a reference's note.
    address_only(rows["lone"])
    # The values that hold them are live and proven: everything else in them reads.
    expected = {"h.n": "1", "m.n": "2", "t.__0": "3", "a.n": "4", "o.inner.n": "5"}
    assert {name: values[name].get("value") for name in expected} == expected, values
    assert values["o.text.length"]["value"] == "7", values
    assert not any(row.get("stale") or row.get("view") for row in values.values()), values
    # An enum's payload, a raw pointer here, was never read: the enum is opaque.
    assert enum.get("view") == "opaque" and not enum.get("children"), enum
    # References and a Box inside a live value still read through, as before.
    for selector, value in (("l.r", "41"), ("l.bx", "12"), ("l.pair.__1", "41")):
        (child,) = lent[selector]["children"]
        assert lent[selector].get("view") is None and child["value"] == value, lent[selector]
    (inner,) = lent["l.rr"]["children"]
    assert inner["name"] == "*rr" and inner.get("expandable"), lent["l.rr"]


@pytest.mark.timeout(400)
def test_a_probe_captures_a_nested_raw_pointer_as_its_address(crate, capsys):
    at = f"src/main.rs:{line_of(MAIN, '// OBSERVE')}"
    capture = ",".join([*RAW, "lone", "l.pair.__1"])
    code = main(["probe", str(crate), "--at", at, "--capture", capture, "--quiet", "--json"])
    result = json.loads(capsys.readouterr().out)
    assert code == 0, result.get("error")
    rows = {row["selector"]: row for row in result["rows"]}
    for selector in ["lone", *RAW]:
        address_only(rows[selector])
    # A reference in a tuple is no raw pointer: it reads as before, with no note.
    assert "view" not in rows["l.pair.__1"] and "note" not in rows["l.pair.__1"], rows


OPTIMIZED = """#[derive(Debug)]
pub struct Pt {
    x: i64,
    y: i64,
}

#[inline(never)]
fn churn() -> i64 {
    let mut total = 0;
    for _ in 0..32 {
        total += Box::leak(Box::new(Pt { x: 777, y: 888 })).x;
    }
    total
}

#[inline(never)]
fn work() -> i64 {
    let b = Box::new(Pt { x: 1, y: 2 });
    let c = Box::new(Pt { x: 3, y: 4 });
    let p: *const Pt = std::hint::black_box(&*b);
    let arr: [*const Pt; 2] = std::hint::black_box([&*b as *const Pt, &*c as *const Pt]);
    drop(b);
    drop(c);
    let k = churn();
    let far = ((arr[0] as i64) >> 62) + ((arr[1] as i64) >> 62);
    std::hint::black_box(k + ((p as i64) >> 62) + far) // OPTIMIZED
}

fn main() {
    println!("{}", work());
}
"""


@pytest.mark.timeout(300)
def test_a_raw_pointer_local_of_an_optimized_build_shows_only_its_address(crate):
    # Where the borrow check cannot judge a raw pointer local (an optimized build proves
    # nothing), what it points at is not read: `p.x` would show the freed Box's 777.
    from peeky.probe import Probe, run_probe
    from peeky.rust import RustTarget

    (crate / "src/main.rs").write_text(OPTIMIZED)
    target = RustTarget(
        sources=("src/main.rs",),
        tests=(),
        cargo=os.environ["PEEKY_RUST_CARGO"],
        rustc=os.environ["PEEKY_RUST_RUSTC"],
        adapter=os.environ["PEEKY_RUST_DAP"],
        dwarfdump=os.environ["PEEKY_RUST_DWARFDUMP"],
        linker=os.environ["PEEKY_RUST_LINKER"],
        dsymutil=os.environ.get("PEEKY_RUST_DSYMUTIL"),
        sysroot=os.environ.get("PEEKY_RUST_SYSROOT"),
        opt_level="1",
    )
    line = line_of(OPTIMIZED, "// OPTIMIZED")
    selectors = ("p", "p.x", "arr", "arr[0]", "arr[1]", "arr[0].x")
    result = run_probe(crate, Probe("src/main.rs", line, selectors), adapter=target)
    assert result["status"] == "completed", result.get("error")
    rows = {row["selector"]: row for row in result["rows"]}
    assert "value" not in rows["p.x"] and "777" not in str(rows["p.x"]), brief(rows["p.x"])
    assert "value" not in rows["arr[0].x"] and "777" not in str(rows["arr[0].x"]), rows
    if not rows["p"].get("unavailable"):
        address_only(rows["p"])
    # An array of raw pointers is not collapsed (`arr[0]` is no "cannot expand 'arr'"): each
    # element shows its address, as one inside a value does.
    if not rows["arr"].get("unavailable"):
        assert rows["arr"].get("view") != "unproven", brief(rows["arr"])
        for element in ("arr[0]", "arr[1]"):
            address_only(rows[element])
