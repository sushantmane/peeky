"""#203 on a real Rust build: resumed after its last hit, a `--until hits` probe's program
runs on until the probe ends it. Its output read meanwhile was "so far (the program was
still running)" with `output_complete: false`, even when it had exited with code 0
and all of its output was read."""

import json
import os

import pytest

from peeky.cli import main
from peeky.probe import _table

MANIFEST = """[package]
name = "ranon"
version = "0.1.0"
edition = "2021"

[dependencies]
"""
LOCK = """# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4

[[package]]
name = "ranon"
version = "0.1.0"
"""
MAIN = """fn main() {
    let seconds: u64 = std::env::args().nth(1).unwrap().parse().unwrap();
    println!("BEFORE");
    let mut total = 0;
    for i in 0..3 {
        total += i; // HIT
    }
    println!("AFTER {}", total);
    std::thread::sleep(std::time::Duration::from_secs(seconds));
}
"""


@pytest.fixture
def crate(tmp_path, monkeypatch):
    names = ("CARGO", "RUSTC", "DAP", "DWARFDUMP", "LINKER")
    if not all(os.environ.get("PEEKY_RUST_" + name) for name in names):
        pytest.skip("set PEEKY_RUST_* tool paths to enable Rust conformance")
    monkeypatch.setenv("PEEKY_STATE_DIR", str(tmp_path / "state"))
    root = tmp_path / "ranon"
    (root / "src").mkdir(parents=True)
    (root / "Cargo.toml").write_text(MANIFEST)
    (root / "Cargo.lock").write_text(LOCK)
    (root / "src/main.rs").write_text(MAIN)
    return root


@pytest.mark.timeout(400)
@pytest.mark.parametrize("sleep", ["30", "0"])
def test_until_hits_says_the_output_can_follow_the_last_hit(crate, capsys, sleep):
    line = next(i for i, text in enumerate(MAIN.splitlines(), 1) if "HIT" in text)
    argv = ["probe", crate, "--at", f"src/main.rs:{line}", "--capture", "i", "--hits", 2]
    argv += ["--until", "hits", "--arg", sleep, "--json", "--no-save"]
    assert main([str(arg) for arg in argv]) == 0
    result = json.loads(capsys.readouterr().out)
    assert result["status"] == "completed" and result["ended"] == "hits"
    output = result["output"].replace("\r\n", "\n")
    text = _table(result)
    assert "still running" not in text and output.startswith("BEFORE\n")
    assert result.get("output_after_last_hit") is True
    if result["output_complete"]:
        # It exited before Peeky disconnected, and the adapter then ended its stream: all
        # of its output, and its exit.
        assert sleep == "0" and result["exit_code"] == 0 and output == "BEFORE\nAFTER 3\n"
        assert not result["output_truncated"] and "program_ended" not in result
        assert "output (all of it: the program ran on after the last hit, to its exit):" in text
    elif result.get("program_ended"):
        # It ended, but the adapter kept its stream open: more output may have been coming.
        assert sleep == "0" and "after the last hit and ended, but its output may still" in text
    else:
        # Peeky ended it: no exit of its own to report.
        assert "exit_code" not in result
        assert (
            "output so far (the program ran on after the last hit, so this can include text "
            "written after it):\n  BEFORE"
        ) in text
