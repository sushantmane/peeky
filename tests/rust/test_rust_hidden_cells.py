"""A callee given a shared `&` may store a copy where the type doesn't show a cell (#321).
`send(&tx, x)` with `tx` an `mpsc::Sender` keeps `x` in the channel, which `rx.recv()`
reads; `bump(&c, x)` with `c = Counter::new()` keeps it in `c.c`, a `Cell` a call built.
Both left `x` `[settable]` after the call: `--set x=100` was reported, and the output kept
the old value. Now a type is judged by what it holds, however deep: the crate's own types
by the build's debug information, the standard library's by what each is known to hold.
`x` is refused after such a call, naming the holder, and a change before it reaches the
program. A struct without cells, lent by `&`, leaves `x` settable."""

import json
import os

import pytest

from peeky.cli import main

MANIFEST = """[package]
name = "hidden"
version = "0.1.0"
edition = "2024"

[dependencies]
"""
LOCK = """# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4

[[package]]
name = "hidden"
version = "0.1.0"
"""
HIDDEN = """use std::cell::{Cell, RefCell};
use std::env;
use std::rc::Rc;
use std::sync::mpsc;
use std::sync::{Arc, Condvar, LazyLock, Mutex};

#[inline(never)]
fn other() -> u32 {
    1
}

struct Counter {
    c: Cell<u32>,
}

impl Counter {
    #[inline(never)]
    fn new() -> Counter {
        Counter { c: Cell::new(0) }
    }
}

struct Point {
    a: u32,
    v: Vec<u32>,
}

#[inline(never)]
fn point() -> Point {
    Point { a: 3, v: vec![1, 2] }
}

struct Gen<T> {
    inner: T,
}

#[inline(never)]
fn wrap<T>(inner: T) -> Gen<T> {
    Gen { inner }
}

mod shared {
    pub struct Inner {
        pub slot: std::sync::Arc<std::sync::Mutex<u32>>,
    }
}

struct Outer {
    inner: shared::Inner,
}

#[inline(never)]
fn outer() -> Outer {
    Outer { inner: shared::Inner { slot: Arc::new(Mutex::new(0)) } }
}

#[allow(dead_code)]
enum Shape {
    Empty,
    Held { c: Rc<RefCell<u32>> },
}

#[inline(never)]
fn shape() -> Shape {
    Shape::Held { c: Rc::new(RefCell::new(0)) }
}

#[inline(never)]
fn adder() -> impl Fn(u32) -> u32 {
    let c = Rc::new(Cell::new(0));
    move |n| {
        c.set(c.get() + n);
        c.get()
    }
}

#[inline(never)]
fn send(tx: &mpsc::Sender<u32>, x: u32) {
    tx.send(x).unwrap();
}

#[inline(never)]
fn bump(c: &Counter, x: u32) {
    c.c.set(x);
}

#[inline(never)]
fn bump_inner(g: &Gen<Counter>, x: u32) {
    g.inner.c.set(x);
}

#[inline(never)]
fn lock(o: &Outer, x: u32) {
    *o.inner.slot.lock().unwrap() = x;
}

#[inline(never)]
fn fill(s: &Shape, x: u32) {
    if let Shape::Held { c } = s {
        *c.borrow_mut() = x;
    }
}

#[inline(never)]
fn call(f: &impl Fn(u32) -> u32, x: u32) {
    f(x);
}

#[inline(never)]
fn put(c: &Rc<Cell<u32>>, x: u32) {
    c.set(x);
}

#[inline(never)]
fn look<T>(_t: &T, x: u32) {
    std::hint::black_box(x);
}

fn sent(arg: u32) -> u32 {
    let x = std::convert::identity(arg);
    let (tx, rx) = mpsc::channel();
    send(&tx, x); // SEND
    let k = other(); // SENT
    std::hint::black_box(&x);
    rx.recv().unwrap() + k
}

fn counted(arg: u32) -> u32 {
    let x = std::convert::identity(arg);
    let c = Counter::new();
    bump(&c, x); // BUMP
    let k = other(); // COUNTED
    std::hint::black_box(&x);
    c.c.get() + k
}

fn wrapped(arg: u32) -> u32 {
    let x = std::convert::identity(arg);
    let g = wrap(Counter::new());
    bump_inner(&g, x); // WRAP
    let k = other(); // WRAPPED
    std::hint::black_box(&x);
    g.inner.c.get() + k
}

fn nested(arg: u32) -> u32 {
    let x = std::convert::identity(arg);
    let o = outer();
    lock(&o, x); // LOCK
    let k = other(); // NESTED
    std::hint::black_box(&x);
    *o.inner.slot.lock().unwrap() + k
}

fn variant(arg: u32) -> u32 {
    let x = std::convert::identity(arg);
    let s = shape();
    fill(&s, x); // FILL
    let k = other(); // VARIANT
    std::hint::black_box(&x);
    match &s {
        Shape::Held { c } => *c.borrow() + k,
        Shape::Empty => 0,
    }
}

fn closure(arg: u32) -> u32 {
    let x = std::convert::identity(arg);
    let f = adder();
    call(&f, x); // CALL
    let k = other(); // CLOSURE
    std::hint::black_box(&x);
    f(0) + k
}

fn cloned(arg: u32) -> u32 {
    let x = std::convert::identity(arg);
    let a = Rc::new(Cell::new(0));
    let b = Rc::clone(&a);
    put(&a, x); // PUT
    let k = other(); // CLONED
    std::hint::black_box(&x);
    b.get() + k
}

static LAZY: LazyLock<u32> = LazyLock::new(|| 4);

fn plain(arg: u32) -> u32 {
    let x = std::convert::identity(arg);
    let p = point();
    let g = wrap(7u32);
    let gc = wrap(Cell::new(1u32));
    let cv = Condvar::new();
    let r: Rc<u32> = Rc::new(3);
    let (tx, rx) = mpsc::channel::<u32>();
    tx.send(2).unwrap();
    look(&p, x);
    look(&g, x);
    look(&cv, x);
    look(&r, x);
    look(&*LAZY, x);
    look(&rx, x);
    let k = other(); // PLAIN
    let t = p.a + p.v[0] + g.inner + gc.inner.get() + *r + rx.recv().unwrap();
    t + *std::hint::black_box(&x) + k
}

fn main() {
    let x: u32 = env::args().nth(1).unwrap().parse().unwrap();
    println!("SENT {}", sent(x));
    println!("COUNTED {}", counted(x));
    println!("WRAPPED {}", wrapped(x));
    println!("NESTED {}", nested(x));
    println!("VARIANT {}", variant(x));
    println!("CLOSURE {}", closure(x));
    println!("CLONED {}", cloned(x));
    println!("PLAIN {}", plain(x));
}
"""


def line_of(marker):
    return next(i for i, line in enumerate(HIDDEN.splitlines(), 1) if f"// {marker}" in line)


@pytest.fixture
def crate(tmp_path, monkeypatch):
    names = ("CARGO", "RUSTC", "DAP", "DWARFDUMP", "LINKER")
    if not all(os.environ.get("PEEKY_RUST_" + name) for name in names):
        pytest.skip("set PEEKY_RUST_* tool paths to enable Rust conformance")
    monkeypatch.setenv("PEEKY_STATE_DIR", str(tmp_path / "state"))
    root = tmp_path / "hidden"
    (root / "src").mkdir(parents=True)
    (root / "Cargo.toml").write_text(MANIFEST)
    (root / "Cargo.lock").write_text(LOCK)
    (root / "src/main.rs").write_text(HIDDEN)
    return root


def probe(capsys, root, marker, *argv):
    at = ["probe", str(root), "--at", f"src/main.rs:{line_of(marker)}", "--json", "--quiet"]
    code = main([*at, *argv, "--", "5"])
    return code, json.loads(capsys.readouterr().out)


@pytest.mark.timeout(600)
def test_a_copy_a_call_stores_behind_a_cell_or_a_channel_withholds_the_local(crate, capsys):
    # Each line after the call: `x` is never read again (`black_box(&x)` only lends it).
    for marker, holder, made, call in (
        # The issue's two shapes.
        ("SENT", "rx", "SENT", "SEND"),
        ("COUNTED", "c", "COUNTED", "BUMP"),
        # A generic struct holding one, a `Mutex` two structs deep, an enum's variant, a
        # closure a call returned, an `Rc` cloned before the call.
        ("WRAPPED", "g", "WRAPPED", "WRAP"),
        ("NESTED", "o", "NESTED", "LOCK"),
        ("VARIANT", "s", "VARIANT", "FILL"),
        ("CLOSURE", "f", "CLOSURE", "CALL"),
        ("CLONED", "b", "CLONED", "PUT"),
    ):
        code, result = probe(capsys, crate, marker, "--set", "x=100")
        error = result.get("error") or {}
        assert code == 2 and error.get("code") == "MUTATION_REJECTED", (marker, result)
        assert result.get("refused_before_launch") is True, (marker, result)
        message = error["message"]
        assert f"the program's own `{holder}` (at lines " in message, (marker, message)
        assert f" and {line_of(call)}) may hold a copy of `x` that it goes on with" in message, (
            marker,
            message,
        )
        assert "which may be out of Peeky's reach (behind a cell, a lock" in message, (
            marker,
            message,
        )
        # The advice offers no copy to change instead.
        assert "change the copy" not in message + error["hint"], (marker, error)
    # The row says so too, without a `--set`.
    code, result = probe(capsys, crate, "SENT", "--capture", "x")
    assert code == 0, result.get("error")
    (row,) = [row for row in result["rows"] if row["selector"] == "x"]
    assert row["value"] == "5" and row.get("settable") is False, row
    lines = f"lines {line_of('SEND') - 1} and {line_of('SEND')}"
    assert row.get("not_settable") == f"the program may hold a copy ({lines})", row


@pytest.mark.timeout(600)
def test_a_change_before_the_call_still_reaches_the_program(crate, capsys):
    for marker, printed in (
        ("SEND", "SENT 101"),
        ("BUMP", "COUNTED 101"),
        ("WRAP", "WRAPPED 101"),
        ("LOCK", "NESTED 101"),
        ("FILL", "VARIANT 101"),
        ("CALL", "CLOSURE 101"),
        ("PUT", "CLONED 101"),
    ):
        code, result = probe(capsys, crate, marker, "--set", "x=100")
        assert code == 0, (marker, result.get("error"))
        assert printed in result["output"].splitlines(), (marker, result["output"])


@pytest.mark.timeout(600)
def test_a_value_without_cells_lent_by_a_shared_reference_leaves_the_local_settable(crate, capsys):
    # `look(&p, x)` with `p = point()`, a struct of a `u32` and a `Vec<u32>` a call built;
    # `Gen<u32>`, though the program has a `Gen<Cell<u32>>` too; a `Condvar`, an `Rc<u32>`,
    # a `LazyLock<u32>` and a channel's receiving end: through a `&`, none can take `x`.
    code, result = probe(capsys, crate, "PLAIN", "--capture", "x", "--set", "x=100")
    assert code == 0, result.get("error")
    assert result["interventions"][0]["after"] == "100", result["interventions"]
    assert "PLAIN 118" in result["output"].splitlines(), result["output"]
