def line_of(marker, text=HIDDEN):
    return next(i for i, line in enumerate(text.splitlines(), 1) if line.endswith(f"// {marker}"))


def make(tmp_path, monkeypatch, name, text):
    names = ("CARGO", "RUSTC", "DAP", "DWARFDUMP", "LINKER")
    if not all(os.environ.get("PEEKY_RUST_" + name) for name in names):
        pytest.skip("set PEEKY_RUST_* tool paths to enable Rust conformance")
    monkeypatch.setenv("PEEKY_STATE_DIR", str(tmp_path / "state"))
    root = tmp_path / name
    (root / "src").mkdir(parents=True)
    (root / "Cargo.toml").write_text(MANIFEST.format(name=name))
    (root / "Cargo.lock").write_text(LOCK.format(name=name))
    (root / "src/main.rs").write_text(text)
    return root


@pytest.fixture
def crate(tmp_path, monkeypatch):
    return make(tmp_path, monkeypatch, "hidden", HIDDEN)


@pytest.fixture
def sharers(tmp_path, monkeypatch):
    return make(tmp_path, monkeypatch, "sharers", SHARERS)


@pytest.fixture
def stateless(tmp_path, monkeypatch):
    return make(tmp_path, monkeypatch, "stateless", STATELESS)


def probe(capsys, root, marker, *argv, text=HIDDEN):
    line = line_of(marker, text)
    at = ["probe", str(root), "--at", f"src/main.rs:{line}", "--json", "--quiet"]
    code = main([*at, *argv, "--", "5"])
    return code, json.loads(capsys.readouterr().out)


def refused(code, result, marker):
    """The message of a refusal made before the program runs."""
    error = result.get("error") or {}
    assert code == 2 and error.get("code") == "MUTATION_REJECTED", (marker, result)
    assert result.get("refused_before_launch") is True, (marker, result)
    return error["message"], error["hint"]


@pytest.mark.timeout(600)
def test_a_copy_a_call_stores_behind_a_cell_or_a_channel_withholds_the_local(crate, capsys):
    # Each line after the call: `x` is never read again (`black_box(&x)` only lends it).
    for marker, holder, made, call in (
        # The issue's two shapes.
        ("SENT", "rx", "SENT", "SEND"),
        ("COUNTED", "c", "COUNTED", "BUMP"),
        # A generic struct holding one, a `Mutex` two structs deep, an enum's variant, a
        # closure a call returned, an `Rc` cloned before the call.
        ("WRAPPED", "g", "WRAPPED", "WRAP"),
        ("NESTED", "o", "NESTED", "LOCK"),
        ("VARIANT", "s", "VARIANT", "FILL"),
        ("CLOSURE", "f", "CLOSURE", "CALL"),
        ("CLONED", "b", "CLONED", "PUT"),
    ):
        code, result = probe(capsys, crate, marker, "--set", "x=100")
        error = result.get("error") or {}
        assert code == 2 and error.get("code") == "MUTATION_REJECTED", (marker, result)
        assert result.get("refused_before_launch") is True, (marker, result)
        message = error["message"]
        assert f"the program's own `{holder}` (at lines " in message, (marker, message)
        assert f" and {line_of(call)}) may hold a copy of `x` that it goes on with" in message, (
            marker,
            message,
        )
        assert "which may be out of Peeky's reach (behind a cell, a lock" in message, (
            marker,
            message,
        )
        # The advice offers no copy to change instead.
        assert "change the copy" not in message + error["hint"], (marker, error)
    # The row says so too, without a `--set`.
    code, result = probe(capsys, crate, "SENT", "--capture", "x")
    assert code == 0, result.get("error")
    (row,) = [row for row in result["rows"] if row["selector"] == "x"]
    assert row["value"] == "5" and row.get("settable") is False, row
    lines = f"lines {line_of('SEND') - 1} and {line_of('SEND')}"
    assert row.get("not_settable") == f"the program may hold a copy ({lines})", row


