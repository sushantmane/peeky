"""#311 (found fixing #300): at `+ other();`, the second line of `let t = total(vec![x, 1])`,
`x` was `[settable]`, and `--set x=100` reported the change, but `t` used the old value.
`vec!` had stored `x`'s copy in its Box through a raw pointer, a store the copy analysis
skipped. Now `x` is refused there with a true reason, and at the statement's first line a
change still reaches the program. The same holds for a String cloned into a `vec!`, and for
a copy a raw pointer stores in the program's own array, which a later line reads."""

import json
import os
import sys

import pytest

from peeky.cli import main

MANIFEST = """[package]
name = "{name}"
version = "0.1.0"
edition = "2024"

[dependencies]
"""
LOCK = """# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4

[[package]]
name = "{name}"
version = "0.1.0"
"""
# No `unsafe`: a String can be set to a text.
VECS = """use std::env;

#[inline(never)]
fn total(v: Vec<u32>) -> u32 {
    v.iter().sum()
}

#[inline(never)]
fn texts(v: Vec<String>) -> usize {
    v.iter().map(|s| s.len()).sum()
}

#[inline(never)]
fn other() -> u32 {
    1
}

fn main() {
    let x: u32 = env::args().nth(1).unwrap().parse().unwrap();
    let s = env::args().nth(2).unwrap();
    let t = total(vec![x, 1]) // FIRST
        + other(); // SECOND
    let n = texts(vec![s.clone(), String::from("abc")]) // TEXTS
        + other() as usize; // CLONED
    println!("T {} {} N {} {}", t, x, n, s);
}
"""
STORED = """use std::env;

#[inline(never)]
fn other() -> u32 {
    1
}

fn stored(arg: u32) -> u32 {
    let x = std::convert::identity(arg);
    let mut slot = [0u32; 2]; // SLOT
    let p: *mut u32 = slot.as_mut_ptr();
    unsafe {
        *p = x; // STORE
    }
    let k = other(); // AFTER
    let t = unsafe { *p } + k;
    std::hint::black_box(&x);
    t
}

fn main() {
    let x: u32 = env::args().nth(1).unwrap().parse().unwrap();
    println!("STORED {}", stored(x));
}
"""


def line_of(text, marker):
    return next(i for i, line in enumerate(text.splitlines(), 1) if marker in line)


FIRST, SECOND, TEXTS, CLONED = (
    line_of(VECS, f"// {marker}") for marker in ("FIRST", "SECOND", "TEXTS", "CLONED")
)
SLOT, STORE, AFTER = (line_of(STORED, f"// {marker}") for marker in ("SLOT", "STORE", "AFTER"))
# lldb-dap 21 writes memory (macOS here); 18 and 20 cannot, and a String's text is on the heap.
WRITES = sys.platform == "darwin"


@pytest.fixture
def crate(tmp_path, monkeypatch):
    names = ("CARGO", "RUSTC", "DAP", "DWARFDUMP", "LINKER")
    if not all(os.environ.get("PEEKY_RUST_" + name) for name in names):
        pytest.skip("set PEEKY_RUST_* tool paths to enable Rust conformance")
    monkeypatch.setenv("PEEKY_STATE_DIR", str(tmp_path / "state"))

    def make(name, text):
        root = tmp_path / name
        (root / "src").mkdir(parents=True)
        (root / "Cargo.toml").write_text(MANIFEST.format(name=name))
        (root / "Cargo.lock").write_text(LOCK.format(name=name))
        (root / "src/main.rs").write_text(text)
        return root

    return make


def probe(capsys, root, line, *argv):
    at = ["probe", str(root), "--at", f"src/main.rs:{line}", "--json", "--quiet"]
    code = main([*at, *argv])
    return code, json.loads(capsys.readouterr().out)


def refused(code, result):
    """The message of a refusal made before the program runs."""
    error = result.get("error") or {}
    assert code == 2 and error.get("code") == "MUTATION_REJECTED", result
    assert result.get("refused_before_launch") is True and not result["rows"], result
    return error["message"]


@pytest.mark.timeout(400)
def test_a_value_vec_stored_through_its_box_is_refused_on_the_statements_later_line(crate, capsys):
    root = crate("vecs", VECS)
    run = ("--", "5", "hello")
    code, result = probe(capsys, root, SECOND, "--capture", "x", *run)
    assert code == 0, result.get("error")
    (row,) = [row for row in result["rows"] if row["selector"] == "x"]
    assert row["value"] == "5" and row.get("settable") is False, row
    assert row.get("not_settable") == f"a statement under way read it (line {FIRST})", row
    assert result["output"].startswith("T 7 5 "), result["output"]
    # The refusal says the statement has already read it, and where.
    message = refused(*probe(capsys, root, SECOND, "--set", "x=100", *run))
    assert (
        f"every place line {SECOND} can stop at is inside a statement that has already read "
        f"`x` into a temporary (at line {FIRST}), which it uses after the stop"
    ) in message, message
    # Before the statement starts, the change reaches the program: `t` is 100 + 1 + 1.
    code, result = probe(capsys, root, FIRST, "--set", "x=100", *run)
    assert code == 0, result.get("error")
    assert result["output"].startswith("T 102 100 "), result["output"]


@pytest.mark.timeout(400)
def test_a_string_cloned_into_vec_is_refused_on_the_statements_later_line(crate, capsys):
    root = crate("vecs", VECS)
    run = ("--", "5", "hello")
    message = refused(*probe(capsys, root, CLONED, "--set", 's="zz"', *run))
    assert (
        f"every place line {CLONED} can stop at is inside a statement that uses a pointer that "
        f"may point into `s` (at line {TEXTS}), so it may hold a copy"
    ) in message, message
    # At the statement's first line, `texts` counts the new text: 2 + 3 + 1.
    code, result = probe(capsys, root, TEXTS, "--set", 's="zz"', *run)
    if not WRITES:
        error = result.get("error") or {}
        assert code != 0 and error.get("code") == "MUTATION_REJECTED", result
        assert "a String's text is on the heap" in error["message"], error
        return
    assert code == 0, result.get("error")
    assert result["output"].strip().endswith("N 6 zz"), result["output"]


@pytest.mark.timeout(400)
def test_a_copy_a_raw_pointer_stores_in_the_programs_array_is_its_own(crate, capsys):
    # `*p = x;` puts `x`'s copy in `slot`, which the next line reads through `p`; `x` is
    # never read again (`black_box(&x)` only lends it).
    root = crate("stored", STORED)
    message = refused(*probe(capsys, root, AFTER, "--set", "x=100", "--", "5"))
    assert (
        f"the program's own `slot` (at lines {SLOT} and {STORE}) may hold a copy of `x` that "
        "it goes on with"
    ) in message, message
    # Before the store, the change reaches the program: 100 + 1.
    code, result = probe(capsys, root, STORE, "--set", "x=100", "--", "5")
    assert code == 0, result.get("error")
    assert result["output"].strip() == "STORED 101", result["output"]
