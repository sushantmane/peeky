"""The most common string loop in Rust, `for cell in cells` over a `&[&str]`, and a
`Vec<&str>` built with `iter().map(..).collect()`. A `&&str` item shows its text, not only
its pointer; a slice's hint names `length`, not `.len`; a `Vec<&str>` past its last use reads
its own length, with no reason about a Box it is not; and the probe's warnings say which
selector each one is about."""

import json
import os
import re

import pytest

from peeky.cli import main

MANIFEST = """[package]
name = "{name}"
version = "0.1.0"
edition = "2024"

[dependencies]
"""
LOCK = """# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4

[[package]]
name = "{name}"
version = "0.1.0"
"""
ROSTER = """use std::env;
use std::process;

/// One player, from an argument `NAME:CITY:POINTS`.
struct Entry {
    name: String,
    city: String,
    points: u32,
}

/// The table being printed: each column's width, and the rows so far.
struct Table {
    widths: Vec<usize>,
    text: String,
}

impl Table {
    /// Appends one row: text columns padded on the right, numbers on the left.
    fn row(&mut self, cells: [&str; 3]) {
        if !self.text.is_empty() {
            self.text.push(';');
        }
        for (i, cell) in cells.iter().enumerate() {
            if i > 0 {
                self.text.push_str(" | ");
            }
            let width = self.widths[i];
            if i == 2 {
                self.text.push_str(&format!("{cell:>width$}"));
            } else {
                self.text.push_str(&format!("{cell:<width$}"));
            }
        }
    }
}

/// The width a column needs: its title's, or its longest cell's.
fn widest(title: &str, cells: &[&str]) -> usize {
    let mut width = title.len();
    for cell in cells {
        width = width.max(cell.len());
    }
    width
}

fn parse(arg: &str) -> Result<Entry, String> {
    let mut parts = arg.split(':');
    let (Some(name), Some(city), Some(points), None) =
        (parts.next(), parts.next(), parts.next(), parts.next())
    else {
        return Err(format!("expected NAME:CITY:POINTS, got {arg:?}"));
    };
    let points = points.parse().map_err(|_| format!("bad points in {arg:?}"))?;
    Ok(Entry { name: name.to_string(), city: city.to_string(), points })
}

fn main() {
    let mut entries = Vec::new();
    for arg in env::args().skip(1) {
        match parse(&arg) {
            Ok(entry) => entries.push(entry),
            Err(message) => {
                eprintln!("roster: {message}");
                process::exit(2);
            }
        }
    }
    // Most points first; equal points keep the order given.
    entries.sort_by(|a, b| b.points.cmp(&a.points));

    let names: Vec<&str> = entries.iter().map(|e| e.name.as_str()).collect();
    let cities: Vec<&str> = entries.iter().map(|e| e.city.as_str()).collect();
    let points: Vec<String> = entries.iter().map(|e| e.points.to_string()).collect();
    let point_cells: Vec<&str> = points.iter().map(String::as_str).collect();

    let name_width = widest("Name", &names);
    let city_width = widest("City", &cities);
    let points_width = widest("Pts", &point_cells);
    let mut table = Table { widths: vec![name_width, city_width, points_width], text: String::new() };
    table.row(["Name", "City", "Pts"]);
    for (entry, points) in entries.iter().zip(&point_cells) {
        table.row([&entry.name, &entry.city, points]);
    }
    println!("TABLE:{}", table.text);
}
"""
PLAYERS = ["Renée:Malmö:12", "Paul:Oslo:7"]


@pytest.fixture
def state(tmp_path, monkeypatch):
    names = ("CARGO", "RUSTC", "DAP", "DWARFDUMP", "LINKER")
    if not all(os.environ.get("PEEKY_RUST_" + name) for name in names):
        pytest.skip("set PEEKY_RUST_* tool paths to enable Rust conformance")
    monkeypatch.setenv("PEEKY_STATE_DIR", str(tmp_path / "state"))
    return tmp_path / "state"


def crate_at(tmp_path, name, text):
    root = tmp_path / name
    (root / "src").mkdir(parents=True)
    (root / "Cargo.toml").write_text(MANIFEST.format(name=name))
    (root / "Cargo.lock").write_text(LOCK.format(name=name))
    (root / "src/main.rs").write_text(text)
    return root


def line_of(text, marker):
    return next(i for i, line in enumerate(text.splitlines(), 1) if marker in line)


def probe(capsys, crate, line, captures, *argv):
    command = ["probe", str(crate), "--at", f"src/main.rs:{line}", "--capture", captures]
    code = main([*command, *argv, "--json", "--quiet", "--", *PLAYERS])
    result = json.loads(capsys.readouterr().out)
    assert code == 0, result.get("error")
    return {(row["hit"], row["selector"]): row for row in result["rows"]}, result


def reads(row):
    return bool(os.environ.get("PEEKY_EXPECT_READ_MEMORY")) or row.get("view") == "memory"


@pytest.mark.timeout(400)
def test_a_str_loop_item_reads_through_its_reference(tmp_path, state, capsys):
    crate = crate_at(tmp_path, "roster", ROSTER)
    line = line_of(ROSTER, "width = width.max(cell.len());")
    rows, result = probe(capsys, crate, line, "cell,cell.length,cells,cells.len", "--hits", "2")
    cell = rows[(1, "cell")]
    if reads(cell):
        # The `&str` a `&&str` item points at, as an owned String reads: `.len()` counts
        # its 6 bytes, not its 5 characters (the roster's bug).
        assert cell["value"] == '"Renée"' and cell["view"] == "memory", cell
        assert rows[(1, "cell.length")]["value"] == "6", rows[(1, "cell.length")]
        assert rows[(2, "cell")]["value"] == '"Paul"', rows[(2, "cell")]
    # The slice's length is `length`, and the hint, and the warning, say so by selector.
    cells = rows[(1, "cells")]
    assert "Capture cells.length for the length" in cells["note"], cells
    assert "`.len`" not in cells["note"] and "for cell in cells" in cells["note"], cells
    assert "its length is cells.length" in rows[(1, "cells.len")]["error"], rows
    assert any(w.startswith("cells: This value is LLDB's summary") for w in result["warnings"])


@pytest.mark.timeout(400)
def test_a_str_item_past_its_last_use_or_in_unsafe_code_is_not_read(tmp_path, state, capsys):
    # Past its last use, with a call since, what it points at is not proven.
    past = ROSTER.replace(
        "        width = width.max(cell.len());\n    }",
        "        width = width.max(cell.len());\n        std::hint::black_box(width); // PAST\n    }",
    )
    crate = crate_at(tmp_path, "past", past)
    rows, result = probe(capsys, crate, line_of(past, "// PAST"), "cell,cell.length")
    cell = rows[(1, "cell")]
    assert cell["value"].startswith("0x") and cell["view"] == "unproven", cell
    assert cell["note"].startswith("This Rust reference shows only its pointer"), cell
    # The note names what may have run since: the calls on the line before.
    width = line_of(past, "width = width.max(cell.len());")
    assert "Box" not in cell["note"] and "#" not in cell["note"], cell
    assert re.search(
        rf"`cell` is not used ahead, and (a call|calls) on lines? {width}\b", cell["note"]
    )
    assert "this Rust reference shows only its pointer" in rows[(1, "cell.length")]["error"]
    # In a crate with unsafe code, nothing is read from memory.
    unsafe = (
        ROSTER + "\n#[allow(dead_code)]\nfn first(p: *const u8) -> u8 {\n    unsafe { *p }\n}\n"
    )
    crate = crate_at(tmp_path, "risky", unsafe)
    line = line_of(unsafe, "width = width.max(cell.len());")
    rows, _ = probe(capsys, crate, line, "cell")
    assert rows[(1, "cell")].get("view") != "memory", rows[(1, "cell")]
    assert rows[(1, "cell")]["value"].startswith("0x"), rows[(1, "cell")]


@pytest.mark.timeout(400)
def test_a_vec_of_str_past_its_last_use_keeps_its_own_length(tmp_path, state, capsys):
    crate = crate_at(tmp_path, "roster", ROSTER)
    line = line_of(ROSTER, 'table.row(["Name", "City", "Pts"]);')
    rows, result = probe(capsys, crate, line, "names,names.len,point_cells")
    names = rows[(1, "names")]
    # Its own length, in its own storage, reads; the reason is short, and true.
    assert rows[(1, "names.len")]["value"] == "2", rows[(1, "names.len")]
    assert "its items are references" in names["note"] and "Box" not in names["note"], names
    assert "Capture names.len for the length" in names["note"] and len(names["note"]) < 600
    assert any(w.startswith("names: This Rust Vec") for w in result["warnings"]), result
    # A `Vec<&str>` the code still uses says where its items read.
    assert "for cell in point_cells" in rows[(1, "point_cells")]["note"], rows


@pytest.mark.timeout(400)
def test_a_shadowing_str_loop_item_reads(tmp_path, state, capsys):
    # `for (entry, points) in entries.iter().zip(&point_cells)`: the item `points` is a
    # `&&str` beside `main`'s own `points: Vec<String>`.
    crate = crate_at(tmp_path, "roster", ROSTER)
    line = line_of(ROSTER, "table.row([&entry.name, &entry.city, points]);")
    rows, _ = probe(capsys, crate, line, "points @ main.rs:81")
    item = rows[(1, "points @ main.rs:81")]
    if reads(item):
        assert item["value"] == '"12"' and item["view"] == "memory", item


SHOW = """fn show(s: &&str) -> usize {
    let n = s.len();
    n + 1 // STOP
}

fn main() {
    let words = vec!["Renée", "Paul"];
    let total: usize = words.iter().map(show).sum();
    println!("{total}");
}
"""


@pytest.mark.timeout(400)
def test_a_str_reference_parameter_reads(tmp_path, state, capsys):
    # `words.iter().map(show)` hands each item over as a `&&str` parameter, which the IR
    # proves live for the call, as `&String` and `&Vec<T>` parameters are.
    crate = crate_at(tmp_path, "show", SHOW)
    rows, _ = probe(capsys, crate, line_of(SHOW, "// STOP"), "s,s.length", "--hits", "2")
    if reads(rows[(1, "s")]):
        assert [rows[(hit, "s")]["value"] for hit in (1, 2)] == ['"Renée"', '"Paul"'], rows
        assert rows[(1, "s")]["type"] == "&&str" and rows[(1, "s.length")]["value"] == "6"
