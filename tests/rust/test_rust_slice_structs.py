@pytest.mark.timeout(400)
def test_real_layouts_read_strings_and_scalars_and_withhold_every_other_field(
    tmp_path, state, capsys
):
    # The compiler's own layout of a reordered generic struct with padding,
    # a zero-sized field, an `Option<String>`, a `Box<str>`, a nested struct, a `char` and
    # a `u128`: what reads matches the program's own `{:?}`; the rest is withheld by type.
    crate = crate_at(tmp_path, "mixed", MIXED)
    fields = ("flag", "name", "letter", "count", "big", "marker", "nick", "label", "inner")
    captures = ",".join(["items", *(f"items[0].{field}" for field in fields)])
    at = f"src/main.rs:{line_of('// SHOW', MIXED)}"
    code = main(["probe", str(crate), "--at", at, "--capture", captures, "--json", "--quiet"])
    result = json.loads(capsys.readouterr().out)
    assert code == 0, result.get("error")
    row = {found["selector"]: found for found in result["rows"]}
    if not reads(row["items"]):
        return
    printed = result["output"].splitlines()[0]
    assert row["items"]["value"] == printed, (row["items"], printed)
    assert [row[f"items[0].{field}"]["value"] for field in fields[:4]] == [
        "true",
        '"Zoë"',
        "'é'",
        "-3",
    ]
    withheld = {
        "big": "u128",
        "marker": "core::marker::PhantomData<i32>",
        "nick": "Option<String>",
        "label": "Box<str>",
        "inner": "mixed::Inner",
    }
    for field, kind in withheld.items():
        found = row[f"items[0].{field}"]
        assert found["unavailable"] and "value" not in found, found
        assert found["type"] == kind, found
        assert f"`{field}` has type `{kind}`" in found["error"], found
