"""#326: a `session step` from the line before `let y = mclone!(x) + 1;`, with
`macro_rules! mclone { ($v:expr) => {{ $v.clone() }}; }`, stops at the inlined `clone`'s first
instruction, which LLDB shows on the macro's definition. That line has no row of its own, so
`session inspect` failed with DEBUGGER_ERROR "Native stopped line does not match prepared
symbols", and the session was closed. So did a step onto a line whose only code is an
`#[inline(always)]` call. Now the stop keeps the session: it reads no value of the frame and
says why, and `session step` goes on. A breakpoint on such a line is refused before it is
placed, where it was placed on the inlined code (`breakpoint src/main.rs:615 verified`)."""

import json
import os

import pytest

from peeky.cli import main

MANIFEST = """[package]
name = "macros"
version = "0.1.0"
edition = "2024"

[dependencies]
"""
LOCK = """# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4

[[package]]
name = "macros"
version = "0.1.0"
"""
SOURCE = """use std::env;

#[macro_use]
mod helpers;

macro_rules! mclone { ($v:expr) => {{ $v.clone() }}; } // MCLONE
macro_rules! inner { ($v:expr) => {{ $v.clone() }}; } // INNER
macro_rules! outer { ($v:expr) => {{ inner!($v) * 2 }}; }

#[inline(always)]
fn bump(v: &mut u32) {
    *v += 1;
}

fn single(mut x: u32) -> u32 {
    std::hint::black_box(&mut x); // SBEFORE
    let y = mclone!(x) + 1; // SINGLE
    y
}

fn nested(mut x: u32) -> u32 {
    std::hint::black_box(&mut x); // NBEFORE
    let y = outer!(x) + 1; // NESTED
    y
}

fn other(mut x: u32) -> u32 {
    std::hint::black_box(&mut x); // OBEFORE
    let y = hclone!(x) + 1; // OTHER
    y
}

fn bumped(mut x: u32) -> u32 {
    std::hint::black_box(&mut x); // BBEFORE
    bump(&mut x); // BUMP
    std::hint::black_box(&mut x); // BAFTER
    x
}

fn listed(mut x: u32) -> u32 {
    std::hint::black_box(&mut x); // LBEFORE
    let v = vec![x, 2]; // VEC
    println!("LISTED {}", v[0]);
    assert!(v[1] == 2, "two");
    v[0]
}

fn main() {
    let x: u32 = env::args().nth(1).unwrap().parse().unwrap();
    println!("SINGLE {}", single(x));
    println!("NESTED {}", nested(x));
    println!("OTHER {}", other(x));
    println!("BUMP {}", bumped(x));
    println!("LIST {}", listed(x));
}
"""
HELPERS = """// A macro of another file.
macro_rules! hclone {
    ($v:expr) => {{ $v.clone() }}; // HCLONE
}
"""
# `decl_macro`, a nightly feature, makes the crate count as one with unsafe code: apart.
DECLARED = """#![feature(decl_macro)]
use std::env;

macro dclone($v:expr) {
    $v.clone() // DCLONE
}

fn declared(mut x: u32) -> u32 {
    std::hint::black_box(&mut x); // DBEFORE
    let y = dclone!(x) + 1; // DECLARED
    y
}

fn main() {
    let x: u32 = env::args().nth(1).unwrap().parse().unwrap();
    println!("DECLARED {}", declared(x));
}
"""
# #326 review: a macro's line with code of its own in `own`, and only an inlined call's site
# in `inlined`.
MIXED = """use std::env;

macro_rules! pick { (c $v:expr) => {{ $v.clone() }}; (a $v:expr) => {{ $v + 1 }}; } // PICK

fn own(x: u32) -> u32 {
    let y = pick!(a x); // OWN
    y
}

fn inlined(mut x: u32) -> u32 {
    std::hint::black_box(&mut x); // IBEFORE
    let y = pick!(c x) + 1; // INLINED
    y
}

fn main() {
    let x: u32 = env::args().nth(1).unwrap().parse().unwrap();
    println!("OWN {}", own(x));
    println!("INLINED {}", inlined(x));
}
"""
RUN = ("--", "5")


def line_of(marker, text=SOURCE):
    return next(i for i, line in enumerate(text.splitlines(), 1) if f"// {marker}" in line)


@pytest.fixture
def crate(tmp_path, monkeypatch):
    names = ("CARGO", "RUSTC", "DAP", "DWARFDUMP", "LINKER")
    if not all(os.environ.get("PEEKY_RUST_" + name) for name in names):
        pytest.skip("set PEEKY_RUST_* tool paths to enable Rust conformance")
    monkeypatch.setenv("PEEKY_STATE_DIR", str(tmp_path / "state"))

    def make(text=SOURCE):
        root = tmp_path / f"macros{len(list(tmp_path.glob('macros*')))}"
        (root / "src").mkdir(parents=True)
        (root / "Cargo.toml").write_text(MANIFEST)
        (root / "Cargo.lock").write_text(LOCK)
        (root / "src/main.rs").write_text(text)
        (root / "src/helpers.rs").write_text(HELPERS)
        return root

    return make


def command(capsys, *argv):
    """A `--json` session command's exit code and output."""
    code = main(["session", *argv, "--json"])
    return code, json.loads(capsys.readouterr().out)


def frame_line(capsys):
    """The stopped frame's line, from an inspection that must read it."""
    code, snapshot = command(capsys, "inspect")
    assert code == 0, snapshot
    return snapshot["frames"][0]["line"], snapshot


def macro_stop(capsys, macro, line, file="src/main.rs"):
    """After a step that stops in ``macro``'s definition at ``line`` of ``file``: the state
    says so, `inspect` reads none of the frame and keeps the session, and its caller reads."""
    code, state = command(capsys, "step")
    assert code == 0, state
    assert state["location"].endswith(f"{file}:{line}"), state
    # On main: DEBUGGER_ERROR "Native stopped line does not match prepared symbols", and
    # the session was closed.
    code, result = command(capsys, "inspect")
    error = result.get("error") or {}
    assert code != 0 and error.get("code") == "INVALID_REQUEST", result
    assert error["session_closed"] is False, error
    note = state.get("macro_stop") or ""
    assert f"on line {line} of {file}, inside the definition of macro `{macro}!`" in note, state
    assert error["message"] == note, error
    code, caller = command(capsys, "inspect", "--frame", "1")
    assert code == 0 and caller["frames"][1]["name"].startswith("macros::main"), caller


def stepped_on(capsys, line):
    """Steps until the stop is on ``line``, each stop read or refused but never closing the
    session; the inspection there."""
    for _ in range(4):
        code, state = command(capsys, "step")
        assert code == 0, state
        if state.get("macro_stop"):
            continue
        found, snapshot = frame_line(capsys)
        if found == line:
            return snapshot
    raise AssertionError(f"no stop on line {line}")


def output(capsys):
    assert main(["session", "continue", "--to-exit"]) == 0
    capsys.readouterr()
    code, report = command(capsys, "report")
    assert code == 0, report
    return report["output"]


def start(capsys, root, marker, text=SOURCE):
    at = f"src/main.rs:{line_of(marker, text)}"
    assert main(["session", "start", str(root), "--at", at, *RUN]) == 0
    capsys.readouterr()


def close(capsys):
    main(["session", "close"])
    capsys.readouterr()


@pytest.mark.timeout(600)
def test_a_step_onto_a_macros_inlined_code_keeps_the_session(crate, capsys):
    root = crate()
    start(capsys, root, "SBEFORE")
    try:
        # The issue: on main, `inspect` here failed with DEBUGGER_ERROR and closed it.
        macro_stop(capsys, "mclone", line_of("MCLONE"))
        # The next step is past the macro's code, on its invocation's line: the macro's
        # `clone` may have read `x` already.
        snapshot = stepped_on(capsys, line_of("SINGLE"))
        (x,) = [v for s in snapshot["scopes"] for v in s["variables"] if v["name"] == "x"]
        assert x.get("settable") is False, x
        assert x.get("not_settable") == "code inlined before the stop may have read it", x
        assert "SINGLE 6" in output(capsys)
    finally:
        close(capsys)


@pytest.mark.timeout(600)
def test_nested_macros_and_another_files_keep_the_session(crate, capsys):
    root = crate()
    start(capsys, root, "NBEFORE")
    try:
        # `outer!` invokes `inner!`, whose `$v.clone()` is inlined: LLDB shows `inner!`'s.
        macro_stop(capsys, "inner", line_of("INNER"))
        stepped_on(capsys, line_of("NESTED"))
        # `hclone!`, defined in src/helpers.rs.
        assert main(["session", "continue", "--to", str(line_of("OBEFORE"))]) == 0
        capsys.readouterr()
        macro_stop(capsys, "hclone", line_of("HCLONE", HELPERS), "src/helpers.rs")
        stepped_on(capsys, line_of("OTHER"))
        text = output(capsys)
        assert "NESTED 11" in text and "OTHER 6" in text, text
    finally:
        close(capsys)


@pytest.mark.timeout(600)
def test_a_line_whose_only_code_is_inlined_keeps_the_session(crate, capsys):
    # `bump(&mut x);` has no row of its own: its only code is `bump`'s, inlined. LLDB shows
    # a step's stop at its first instruction on line BUMP.
    root = crate()
    start(capsys, root, "BBEFORE")
    try:
        code, state = command(capsys, "step")
        assert code == 0 and state["location"].endswith(f":{line_of('BUMP')}"), state
        assert "macro_stop" not in state
        line, snapshot = frame_line(capsys)
        assert line == line_of("BUMP")
        (x,) = [v for s in snapshot["scopes"] for v in s["variables"] if v["name"] == "x"]
        assert x["value"] == "5", x
        # Nothing of the line has run: never "part-way through" it.
        assert "part-way" not in str(x.get("not_settable")), x
        stepped_on(capsys, line_of("BAFTER"))
        assert "BUMP 6" in output(capsys)
    finally:
        close(capsys)


@pytest.mark.timeout(600)
def test_std_macros_steps_stay_in_the_program_or_leave_it(crate, capsys):
    # A guard: `vec!`, `println!` and `assert!` are collapsed onto their invocation's line,
    # and a step into them stops in the standard library's own sources.
    root = crate()
    start(capsys, root, "LBEFORE")
    try:
        stepped_on(capsys, line_of("VEC"))
        code, state = command(capsys, "step", "--into")
        assert code == 0 and state.get("outside_program") is True, state
        assert "/library/" in state["location"], state
        assert main(["session", "step", "--out"]) == 0
        capsys.readouterr()
        for _ in range(3):
            code, state = command(capsys, "step")
            assert code == 0 and "macro_stop" not in state, state
            frame_line(capsys)
        assert "LIST 5" in output(capsys)
    finally:
        close(capsys)


@pytest.mark.timeout(600)
def test_a_breakpoint_on_such_a_line_is_refused_before_it_is_placed(crate, capsys):
    root = crate()
    # On main, `probe --at` the macro's definition finished without a stop (NO_STOP), or
    # (with one invocation, alone) said `breakpoint src/main.rs:615 verified`, stopped there,
    # and then failed with DEBUGGER_ERROR.
    for file, marker, text, wanted in (
        ("src/main.rs", "MCLONE", SOURCE, "it is in the definition of macro `mclone!`"),
        ("src/helpers.rs", "HCLONE", HELPERS, "it is in the definition of macro `hclone!`"),
        ("src/main.rs", "BUMP", SOURCE, "the build inlined the call of `bump` made there"),
    ):
        line = line_of(marker, text)
        at = ["probe", str(root), "--at", f"{file}:{line}", "--capture", "x", "--json", "--quiet"]
        code = main([*at, *RUN])
        error = json.loads(capsys.readouterr().out).get("error") or {}
        assert code != 0 and error.get("code") == "INVALID_BREAKPOINT", error
        assert error["message"].startswith(f"Line {line} has no code to stop at of its own: ")
        assert wanted in error["message"], error
    # A one-shot `continue --to` is refused, and the session goes on from where it was.
    start(capsys, root, "SBEFORE")
    try:
        code, result = command(capsys, "continue", "--to", str(line_of("MCLONE")))
        error = result.get("error") or {}
        assert code != 0 and error.get("code") == "INVALID_BREAKPOINT", result
        assert "it is in the definition of macro `mclone!`" in error["message"], error
        assert frame_line(capsys)[0] == line_of("SBEFORE")
        assert "SINGLE 6" in output(capsys)
    finally:
        close(capsys)


@pytest.mark.timeout(600)
def test_a_decl_macros_inlined_code_keeps_the_session(crate, capsys):
    root = crate(DECLARED)
    start(capsys, root, "DBEFORE", DECLARED)
    try:
        macro_stop(capsys, "dclone", line_of("DCLONE", DECLARED))
        stepped_on(capsys, line_of("DECLARED", DECLARED))
        assert "DECLARED 6" in output(capsys)
    finally:
        close(capsys)


@pytest.mark.timeout(600)
def test_a_macros_line_with_code_elsewhere_is_withheld_where_it_is_only_inlined(crate, capsys):
    # #326 review: line PICK has code of its own in `own`, so it is the build's line, and a
    # breakpoint there is placed. In `inlined`, LLDB shows the stop at `pick!`'s inlined
    # `clone` on it too. On main that stop was judged as a line of `inlined`: `x` was
    # `[not settable: part-way through line 3]`, which it isn't.
    root, line = crate(MIXED), line_of("PICK", MIXED)
    start(capsys, root, "IBEFORE", MIXED)
    try:
        macro_stop(capsys, "pick", line)
        stepped_on(capsys, line_of("INLINED", MIXED))
        assert "INLINED 6" in output(capsys)
    finally:
        close(capsys)
    # A probe of the line: LLDB (host, 18 and 20) places its breakpoint on `own`'s code
    # alone, since the build's one compile unit has a row of the line. A stop in
    # `inlined` would be withheld, and the probe would go on (unit-tested).
    at = ["probe", str(root), "--at", f"src/main.rs:{line}", "--capture", "x", "--hits", "all"]
    code = main([*at, "--json", "--quiet", *RUN])
    result = json.loads(capsys.readouterr().out)
    assert code == 0 and result["status"] == "completed", result.get("error")
    rows = [row for row in result["rows"] if row["phase"] == "observed"]
    assert [row.get("value") for row in rows if "::own::" in row["function"]] == ["5"], rows
    for row in rows:
        if "::own::" not in row["function"]:
            assert row["error"].startswith("withheld: Peeky reads no value of frame 0"), row
    assert "OWN 6" in result["output"] and "INLINED 6" in result["output"]
