"""#191: a Rust local or parameter whose name is not plain ASCII (`größe`). LLVM IR
quotes it (`%"gr\\C3\\B6\\C3\\9Fe"`), and the IR's proofs matched only plain names, so a
reference parameter so named stayed a raw pointer, where `values: &Vec<i64>` reads."""

import json
import os

import pytest

from peeky.cli import main

MANIFEST = """[package]
name = "{name}"
version = "0.1.0"
edition = "2024"

[dependencies]
"""
LOCK = """# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4

[[package]]
name = "{name}"
version = "0.1.0"
"""
MAIN = """fn summe(größe: &Vec<i64>, faktor: i64) -> i64 {
    let mut zähler = 0i64;
    std::hint::black_box(&mut zähler);
    zähler += größe.len() as i64 * faktor;
    let stücke: Vec<i64> = größe.iter().map(|x| x * faktor).collect();
    println!("{zähler} {}", stücke.len()); // STOP
    zähler
}

fn main() {
    let wörter = vec![3i64, 4, 5];
    println!("{}", summe(&wörter, 2));
}
"""


@pytest.fixture
def crate(tmp_path, monkeypatch):
    names = ("CARGO", "RUSTC", "DAP", "DWARFDUMP", "LINKER")
    if not all(os.environ.get("PEEKY_RUST_" + name) for name in names):
        pytest.skip("set PEEKY_RUST_* tool paths to enable Rust conformance")
    monkeypatch.setenv("PEEKY_STATE_DIR", str(tmp_path / "state"))
    root = tmp_path / "names"
    (root / "src").mkdir(parents=True)
    (root / "Cargo.toml").write_text(MANIFEST.format(name="names"))
    (root / "Cargo.lock").write_text(LOCK.format(name="names"))
    (root / "src/main.rs").write_text(MAIN)
    return root


@pytest.mark.timeout(400)
def test_a_reference_parameter_named_in_unicode_reads_as_its_ascii_twin(crate, capsys):
    line = next(i for i, text in enumerate(MAIN.split("\n"), 1) if "// STOP" in text)
    assert main(["session", "start", str(crate), "--at", f"src/main.rs:{line}"]) == 0
    capsys.readouterr()
    try:
        assert main(["session", "inspect", "--json"]) == 0
        snapshot = json.loads(capsys.readouterr().out)
    finally:
        main(["session", "close"])
    variables = {v["name"]: v for scope in snapshot["scopes"] for v in scope["variables"]}
    parameter = variables["größe"]
    if os.environ.get("PEEKY_EXPECT_READ_MEMORY") or parameter.get("view") == "memory":
        assert parameter["value"] == "[3, 4, 5]" and parameter["view"] == "memory", parameter
        # Its Rust type, as for a reference parameter the IR proves.
        assert parameter["type"] == "&alloc::vec::Vec<i64, alloc::alloc::Global>", parameter
        # An owned Vec so named read already: the MIR names it as the source does.
        owned = variables["stücke"]
        assert owned["value"] == "[6, 8, 10]" and owned["view"] == "memory", owned
    assert variables["zähler"]["value"] == "6", variables["zähler"]
