"""What Rust functions return (#155): integers, bool and floats as Rust prints them,
once per call (a key function std's sort calls, a recursive one); never an enum,
Option or struct. Real Cargo builds."""

import json
import os

import pytest

from peeky.cli import main
from peeky.probe import RETURN

MANIFEST = """[package]
name = "rets"
version = "0.1.0"
edition = "2024"

[dependencies]
"""
LOCK = """# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4

[[package]]
name = "rets"
version = "0.1.0"
"""
MAIN = """struct Task {
    prio: i32,
    deadline: i32,
}

fn key(t: &Task) -> i32 {
    let k = t.prio * 100 + t.deadline; // KEY
    k
}

fn fact(n: u64) -> u64 {
    let r = if n <= 1 { 1 } else { n * fact(n - 1) }; // FACT
    r
}

fn is_even(n: i64) -> bool {
    n % 2 == 0 // EVEN
}

fn first(v: &[i32]) -> Option<i32> {
    v.first().copied() // FIRST
}

fn byte(n: u8) -> u8 {
    n + 1 // BYTE
}

fn main() {
    let mut tasks = vec![
        Task { prio: 2, deadline: 30 },
        Task { prio: 1, deadline: 5 },
        Task { prio: 3, deadline: 1 },
    ];
    tasks.sort_by_key(key);
    let f = fact(4);
    let e = is_even(7);
    let o = first(&[4, 5]);
    let b = byte(64);
    println!("{} {} {} {:?} {}", tasks[0].prio, f, e, o, b);
}
"""


@pytest.fixture
def crate(tmp_path, monkeypatch):
    names = ("CARGO", "RUSTC", "DAP", "DWARFDUMP", "LINKER")
    if not all(os.environ.get("PEEKY_RUST_" + name) for name in names):
        pytest.skip("set PEEKY_RUST_* tool paths to enable Rust conformance")
    monkeypatch.setenv("PEEKY_STATE_DIR", str(tmp_path / "state"))
    root = tmp_path / "rets"
    (root / "src").mkdir(parents=True)
    (root / "Cargo.toml").write_text(MANIFEST)
    (root / "Cargo.lock").write_text(LOCK)
    (root / "src/main.rs").write_text(MAIN)
    return root


def line_of(marker):
    return next(i for i, text in enumerate(MAIN.splitlines(), 1) if marker in text)


def probe(capsys, root, marker, capture="return"):
    code = main(
        ["probe", str(root), "--at", f"src/main.rs:{line_of(marker)}", "--capture", capture]
        + ["--hits", "all", "--json", "--no-save"]
    )
    result = json.loads(capsys.readouterr().out)
    assert code == 0, result.get("error")
    hits = {}
    for row in result["rows"]:
        hits.setdefault(row["hit"], {})[row["selector"]] = row
    return hits


@pytest.mark.timeout(300)
def test_rust_returns_once_per_call_as_rust_prints_them(crate, capsys):
    # Called by std's sort (outside the program's sources), once per comparison.
    keys = probe(capsys, crate, "KEY", "t.prio,t.deadline,return")
    assert len(keys) >= 3
    for rows in keys.values():
        expected = int(rows["t.prio"]["value"]) * 100 + int(rows["t.deadline"]["value"])
        assert (rows[RETURN]["value"], rows[RETURN]["type"]) == (str(expected), "i32"), rows
        # The function as its observed rows name it (LLDB's name, hash included).
        assert rows[RETURN]["function"] == rows["t.prio"]["function"]
        assert "::key" in rows[RETURN]["function"]
        assert "main.rs" not in rows[RETURN].get("location", "")
    facts = probe(capsys, crate, "FACT", "n,return")
    assert sorted(int(rows[RETURN]["value"]) for rows in facts.values()) == [1, 2, 6, 24]
    for rows in facts.values():
        n = int(rows["n"]["value"])
        assert rows[RETURN]["value"] == str([1, 1, 2, 6, 24][n])
    even = probe(capsys, crate, "EVEN")[1][RETURN]
    assert (even["value"], even["type"]) == ("false", "bool")
    # LLDB shows a u8 as a C character ('A'); Rust prints 65.
    byte = probe(capsys, crate, "BYTE")[1][RETURN]
    assert (byte["value"], byte["type"]) == ("65", "u8")
    option = probe(capsys, crate, "FIRST")[1][RETURN]
    assert "value" not in option, option
    # Listed (Apple's LLDB) and refused, or not readable at all (LLDB 18/20 on Linux).
    assert any(
        reason in option["error"]
        for reason in ("Option<i32> is not an integer, bool or float", "reported no value")
    ), option
