"""#382 on a Cargo crate: a probe's `1:pass` reads main's loop counter while add_reading
runs, in one run. A caller's `Vec` keeps LLDB's summary, with the note `session get --frame 1`
gives: a call under way may be changing what it lent."""

import json
import os

import pytest

from peeky.cli import main

MANIFEST = """[package]
name = "ward"
version = "0.1.0"
edition = "2024"

[dependencies]
"""
LOCK = """# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4

[[package]]
name = "ward"
version = "0.1.0"
"""
SOURCE = """#[inline(never)]
fn add_reading(totals: &mut Vec<u32>, reading: u32) -> usize {
    totals.push(reading); // ADD
    totals.len()
}

fn main() {
    let mut totals: Vec<u32> = Vec::new();
    let mut pass: u32 = 0;
    while pass < 3 {
        add_reading(&mut totals, pass * 10); // CALL
        pass += 1;
    }
    println!("{:?} {}", totals, pass);
}
"""


def line_of(marker):
    return next(i for i, line in enumerate(SOURCE.splitlines(), 1) if line.endswith(marker))


@pytest.fixture
def crate(tmp_path, monkeypatch):
    names = ("CARGO", "RUSTC", "DAP", "DWARFDUMP", "LINKER")
    if not all(os.environ.get("PEEKY_RUST_" + name) for name in names):
        pytest.skip("set PEEKY_RUST_* tool paths to enable Rust conformance")
    monkeypatch.setenv("PEEKY_STATE_DIR", str(tmp_path / "state"))
    root = tmp_path / "ward"
    (root / "src").mkdir(parents=True)
    (root / "Cargo.toml").write_text(MANIFEST)
    (root / "Cargo.lock").write_text(LOCK)
    (root / "src/main.rs").write_text(SOURCE)
    return root


@pytest.mark.timeout(600)
def test_a_probe_reads_the_callers_counter_beside_the_callees_values(crate, capsys):
    add, call = line_of("// ADD"), line_of("// CALL")
    argv = ["probe", crate, "--at", f"src/main.rs:{add}", "--hits", "all", "--json"]
    code = main([str(arg) for arg in [*argv, "--capture", "reading,1:pass,1:totals"]])
    result = json.loads(capsys.readouterr().out)
    assert code == 0 and result["status"] == "completed", result.get("error")
    assert result["output"].strip() == "[0, 10, 20] 3"
    rows = {(row["hit"], row["selector"]): row for row in result["rows"]}
    assert [rows[hit, "reading"]["value"] for hit in (1, 2, 3)] == ["0", "10", "20"]
    assert [rows[hit, "1:pass"]["value"] for hit in (1, 2, 3)] == ["0", "1", "2"]
    caller = rows[1, "1:pass"]
    assert (caller["frame"], caller["line"], caller["stop_line"]) == (1, call, add)
    assert caller["function"].startswith("ward::main") and caller.get("settable") is not True
    lent = rows[1, "1:totals"]
    assert lent["frame"] == 1 and lent.get("stale") is True, lent
    assert "is a local of a caller frame" in lent["note"], lent
