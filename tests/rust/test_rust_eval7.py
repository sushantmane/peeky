"""The seventh agent evaluation's Rust findings, on a real build: a field's type shows
its Rust name, as a local's does (18), and `describe` says which locals have settable
fields (16)."""

import json
import os

import pytest

from peeky.cli import main

MANIFEST = """[package]
name = "movavg"
version = "0.1.0"
edition = "2024"

[dependencies]
"""
LOCK = """# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4

[[package]]
name = "movavg"
version = "0.1.0"
"""
# The evaluation's case, as the agent had it.
MAIN = """use std::env;

/// Rolling mean over the last `k` values, printed with one decimal after each value.
struct Window {
    k: usize,
    values: Vec<i64>,
    sum: i64,
}

impl Window {
    fn push(&mut self, v: i64) -> f64 {
        self.values.push(v);
        self.sum += v;
        if self.values.len() >= self.k {
            let old = self.values.remove(0);
            self.sum -= old;
        }
        self.sum as f64 / self.values.len() as f64
    }
}

fn main() {
    let args: Vec<String> = env::args().collect();
    let k: usize = args[1].parse().unwrap();
    let mut w = Window { k, values: Vec::new(), sum: 0 };
    let mut out = Vec::new();
    for v in args[2].split(',') {
        let mean = w.push(v.parse().unwrap());
        out.push(format!("{:.1}", mean));
    }
    println!("MEANS:{}", out.join(","));
}
"""
ARGS = ["--", "3", "3,6,9,12"]


@pytest.fixture
def crate(tmp_path, monkeypatch):
    names = ("CARGO", "RUSTC", "DAP", "DWARFDUMP", "LINKER")
    if not all(os.environ.get("PEEKY_RUST_" + name) for name in names):
        pytest.skip("set PEEKY_RUST_* tool paths to enable Rust conformance")
    monkeypatch.setenv("PEEKY_STATE_DIR", str(tmp_path / "state"))
    root = tmp_path / "movavg"
    (root / "src").mkdir(parents=True)
    (root / "Cargo.toml").write_text(MANIFEST)
    (root / "Cargo.lock").write_text(LOCK)
    (root / "src/main.rs").write_text(MAIN)
    return root


def rows(capsys, crate, line, capture):
    argv = ["probe", str(crate), "--at", f"src/main.rs:{line}", "--capture", capture, "--json"]
    assert main([*argv, *ARGS]) == 0
    result = json.loads(capsys.readouterr().out)
    return {row["selector"]: row for row in result["rows"]}


@pytest.mark.timeout(400)
def test_a_fields_type_is_its_rust_name(crate, capsys):
    # Finding 18: `self.k` and `w.k` showed `unsigned long` while `k` showed `usize`.
    found = rows(capsys, crate, 18, "self.k,self.sum,self.values.len,v")
    assert [found[s]["type"] for s in ("self.k", "self.sum", "self.values.len", "v")] == [
        "usize",
        "i64",
        "usize",
        "i64",
    ], found
    # LLDB's name stays beside it.
    assert found["self.k"]["debugger_type"] == "unsigned long", found["self.k"]
    assert found["self.sum"]["debugger_type"] == "long", found["self.sum"]
    found = rows(capsys, crate, 28, "k,w.k,w.sum")
    assert [found[s]["type"] for s in ("k", "w.k", "w.sum")] == ["usize", "usize", "i64"], found
    # The table shows them too.
    argv = ["probe", str(crate), "--at", "src/main.rs:28", "--capture", "w.k", "--quiet"]
    assert main([*argv, *ARGS]) == 0
    assert " w.k       usize " in capsys.readouterr().out


@pytest.mark.timeout(400)
def test_describe_says_which_rust_locals_have_settable_fields(crate, capsys):
    # Finding 16: `describe`'s `mutable:` line listed only register-bound locals, not
    # that `w.k` is settable.
    assert main(["describe", str(crate)]) == 0
    (mutable,) = [line for line in capsys.readouterr().out.splitlines() if "mutable:" in line]
    # #183: the paths themselves (`w.values`' elements are not settable).
    assert ": movavg::main: w.k, w.sum. Never settable" in mutable, mutable
    # `self` is a reference: its fields are not changed through it.
    assert "push: self" not in mutable.split("Never settable")[0], mutable


SPAN = """#[derive(Debug, Clone, Copy)]
struct Span {
    start: usize,
    end: i32,
}

fn main() {
    let mut s = Span { start: 2, end: 3 };
    std::hint::black_box(&mut s);
    println!("{:?}", s); // HERE
}
"""


@pytest.mark.timeout(400)
def test_every_field_keeps_lldbs_type_name_beside_the_rust_one(crate, capsys):
    # Review of PR #165: a field of a struct previewed from memory (`s.start`) had no
    # `debugger_type`, while a raw field (`w.k`) had one.
    (crate / "src/main.rs").write_text(SPAN)
    line = next(i for i, text in enumerate(SPAN.splitlines(), 1) if "// HERE" in text)
    found = rows(capsys, crate, line, "s,s.start,s.end")
    shown = {s: (found[s]["type"], found[s].get("debugger_type")) for s in ("s.start", "s.end")}
    assert shown == {"s.start": ("usize", "unsigned long"), "s.end": ("i32", "int")}, found
    # The table shows the Rust names.
    argv = ["probe", str(crate), "--at", f"src/main.rs:{line}", "--capture", "s.start", "--quiet"]
    assert main([*argv, *ARGS]) == 0
    assert " s.start   usize " in capsys.readouterr().out
