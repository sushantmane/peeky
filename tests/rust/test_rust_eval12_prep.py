"""Rust Lows found preparing the twelfth agent evaluation, on real builds: a closure's
capture of a struct with no pointer is withheld with a note that fits it, not one about
memory it may own through a pointer; a small struct the program keeps in registers says
so on its own row, as its fields do; and `describe`'s `verify:` line needs no `--at` for
a one-file crate."""

import json
import os

import pytest

from peeky.cli import main
from peeky.probe import _table

MANIFEST = """[package]
name = "prep12"
version = "0.1.0"
edition = "2021"

[dependencies]
"""
LOCK = """# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4

[[package]]
name = "prep12"
version = "0.1.0"
"""
MAIN = """#[derive(Clone, Copy, Debug)]
struct Lap {
    number: u32,
    secs: u32,
    pit: u32,
}

struct Named {
    name: String,
    secs: u32,
}

struct P {
    a: i32,
    b: i32,
}

struct Q {
    a: u32,
    b: u32,
    c: u32,
}

fn secs_of(lap: Lap) -> u32 {
    lap.secs
}

fn fastest(laps: &[Lap]) -> Option<u32> {
    let mut best = None;
    for lap in laps.iter().copied() {
        let beats = laps.iter().filter(|other| {
            other.secs > secs_of(lap) // CAPTURE
        }).count();
        if beats + 1 == laps.len() {
            best = Some(lap.number);
        }
    }
    best
}

fn longest(names: &[Named]) -> usize {
    let mut most = 0;
    for named in names.iter() {
        let own = Named { name: named.name.clone(), secs: named.secs };
        let longer = names.iter().filter(|other| {
            other.name.len() > keep(&own) // NAMED
        }).count();
        most += longer;
    }
    most
}

fn keep(named: &Named) -> usize {
    named.name.len() + named.secs as usize
}

fn main() {
    let mut laps = Vec::new();
    for i in 0..4u32 {
        laps.push(Lap { number: i + 1, secs: 90 - i * 3 + (i % 2) * 10, pit: i % 2 });
    }
    println!("{:?} {}", fastest(&laps), laps[0].pit);
    let names = vec![Named { name: String::from("Ana"), secs: 1 }];
    println!("{}", longest(&names));
    let mut total = 0;
    for i in 1..3 {
        let p = P { a: i + 3, b: i * 10 + 1 };
        let q = Q { a: i as u32, b: 2, c: 3 };
        total += p.a + p.b + (q.a + q.b + q.c) as i32; // PAIR
    }
    println!("{}", total);
}
"""


@pytest.fixture
def crate(tmp_path, monkeypatch):
    names = ("CARGO", "RUSTC", "DAP", "DWARFDUMP", "LINKER")
    if not all(os.environ.get("PEEKY_RUST_" + name) for name in names):
        pytest.skip("set PEEKY_RUST_* tool paths to enable Rust conformance")
    monkeypatch.setenv("PEEKY_STATE_DIR", str(tmp_path / "state"))
    root = tmp_path / "prep12"
    (root / "src").mkdir(parents=True)
    (root / "Cargo.toml").write_text(MANIFEST)
    (root / "Cargo.lock").write_text(LOCK)
    (root / "src/main.rs").write_text(MAIN)
    return root


def line_of(marker):
    return next(i for i, line in enumerate(MAIN.splitlines(), 1) if line.endswith(f"// {marker}"))


def probe(capsys, crate, marker, *selectors, hits=1):
    at = f"src/main.rs:{line_of(marker)}"
    code = main(
        ["probe", str(crate), "--at", at, "--capture", ",".join(selectors), "--hits", str(hits)]
        + ["--json"]
    )
    result = json.loads(capsys.readouterr().out)
    assert code == 0, result
    return result, {row["selector"]: row for row in result["rows"] if row["hit"] == hits}


@pytest.mark.timeout(400)
def test_a_captured_struct_with_no_pointer_is_withheld_with_a_note_that_fits(crate, capsys):
    # The closure's `lap` (three u32s) read `This is (or is inside) a Rust local that may own
    # memory through a pointer … Its fields show leftover bytes, maybe a moved-from copy`.
    result, rows = probe(capsys, crate, "CAPTURE", "lap", "lap.number", hits=2)
    for selector in ("lap", "lap.number"):
        row = rows[selector]
        assert row.get("stale") is True, row
        assert row["note"].startswith(
            "This is (or is inside) a Rust local the MIR does not prove initialized here"
        ), row
        assert "Its type holds no pointer, but its fields may show leftover bytes" in row["note"]
        assert "own memory through a pointer" not in row["note"], row
    # Probe rows mark it as `session inspect` does.
    assert "  [stale]" in _table(result), _table(result)
    # A struct holding a String keeps the note about memory it may own.
    _, rows = probe(capsys, crate, "NAMED", "own")
    assert "may own memory through a pointer" in rows["own"]["note"], rows["own"]


@pytest.mark.timeout(400)
def test_a_struct_kept_in_registers_says_so_as_its_fields_do(crate, capsys):
    # `p P { a: 4, b: 11 } [memory]` above `p.a 4 [memory] [not settable: register]`: rustc
    # keeps a two-field struct in registers, and the debugger reads its own copy.
    _, rows = probe(capsys, crate, "PAIR", "p", "p.a", "q", "q.a")
    assert rows["p.a"].get("not_settable") == "register", rows["p.a"]
    assert rows["p"].get("not_settable") == "register", rows["p"]
    # A three-field struct is in memory: its fields can change, and its row says nothing.
    assert rows["q.a"].get("settable") is True, rows["q.a"]
    assert "not_settable" not in rows["q"], rows["q"]


@pytest.mark.timeout(400)
def test_describe_shows_verify_without_at_for_a_one_file_crate(crate, capsys):
    assert main(["describe", str(crate), "--json"]) == 0
    verify = json.loads(capsys.readouterr().out)["commands"]["verify"]
    assert verify.startswith(f"peeky verify {crate} --check "), verify
