"""`--set-at LINE@HIT name=@before` on a real Rust build (#305): the guard flip that skips a
statement in two `--set-at`s, each restore in the call that made the change; an async body,
whose calls Peeky cannot tell apart, is refused before the run."""

import json
import os

import pytest

from peeky.cli import main
from peeky.probe import _table

MANIFEST = """[package]
name = "trail"
version = "0.1.0"
edition = "2024"

[dependencies]
"""
LOCK = """# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4

[[package]]
name = "trail"
version = "0.1.0"
"""
MAIN = """use std::future::Future;
use std::pin::pin;
use std::task::{Context, Poll, Waker};

/// The tops and bottoms of a trail's height profile, each with its distance and height.
fn find_turns(height: &[i64]) -> String {
    let mut turns = Vec::new();
    let mut turn = 0; // the point where the height last moved
    let mut trend: i64 = 0; // +1 rising, -1 falling, 0 not known yet
    let mut flat: i64 = 0; // points level with the one before
    for i in 1..height.len() {
        if height[i] == height[i - 1] {
            if trend != 0 { // GUARD
                turn = i;
            }
            flat += 1; // FLAT
            continue;
        }
        let now = if height[i] > height[i - 1] { 1 } else { -1 };
        if now != trend && trend != 0 {
            let kind = if trend == 1 { 'T' } else { 'B' };
            turns.push(format!("{kind}@{} {}", turn * 100, height[turn]));
        }
        trend = now;
        turn = i;
    }
    format!("{};FLAT={flat}", turns.join(","))
}

async fn total(height: &[i64]) -> i64 {
    let mut sum: i64 = 0;
    for h in height {
        sum += h; // ADD
    }
    sum // SUM
}

fn main() {
    let height: Vec<i64> = std::env::args().skip(1).map(|arg| arg.parse().unwrap()).collect();
    println!("TRAIL:{}", find_turns(&height));
    let mut sum = pin!(total(&height));
    if let Poll::Ready(sum) = sum.as_mut().poll(&mut Context::from_waker(Waker::noop())) {
        println!("TOTAL:{sum}");
    }
}
"""
HEIGHTS = ("410", "430", "455", "455", "455", "440", "420", "400", "400", "415", "430")


@pytest.fixture
def crate(tmp_path, monkeypatch):
    names = ("CARGO", "RUSTC", "DAP", "DWARFDUMP", "LINKER")
    if not all(os.environ.get("PEEKY_RUST_" + name) for name in names):
        pytest.skip("set PEEKY_RUST_* tool paths to enable Rust conformance")
    monkeypatch.setenv("PEEKY_STATE_DIR", str(tmp_path / "state"))
    root = tmp_path / "trail"
    (root / "src").mkdir(parents=True)
    (root / "Cargo.toml").write_text(MANIFEST)
    (root / "Cargo.lock").write_text(LOCK)
    (root / "src/main.rs").write_text(MAIN)
    return root


def line_of(marker):
    return next(i for i, line in enumerate(MAIN.splitlines(), 1) if f"// {marker}" in line)


def probe(capsys, root, *argv):
    command = ["probe", str(root), *argv, "--json", "--quiet", "--no-save"]
    code = main(command + [f"--arg={arg}" for arg in HEIGHTS])
    return code, json.loads(capsys.readouterr().out)


@pytest.mark.timeout(600)
def test_the_guard_flip_skips_the_move_with_two_set_ats(crate, capsys):
    guard, flat = line_of("GUARD"), line_of("FLAT")
    at = ["--at", f"src/main.rs:{guard}"]
    code, plain = probe(capsys, crate, *at)
    assert code == 0, plain
    assert plain["output"].splitlines()[0] == "TRAIL:T@400 455,B@800 400;FLAT=3", plain
    code, result = probe(
        capsys, crate, *at, "--capture", "trend", "--hits", "all",
        "--set-at", f"{guard}@all", "trend=0", "--set-at", f"{flat}@all", "trend=@before",
    )  # fmt: skip
    assert code == 0, result
    assert result["output"].splitlines()[0] == "TRAIL:T@200 455,B@700 400;FLAT=3", result
    restored = [(c["before"], c["after"], c["restores"]) for c in result["interventions"][1::2]]
    assert restored == [
        ("0", "1", f"{guard}@1"),
        ("0", "1", f"{guard}@2"),
        ("0", "-1", f"{guard}@3"),
    ]
    assert f"(restored, --set-at line {flat}@all, hit 3, in " in _table(result)


@pytest.mark.timeout(600)
def test_a_restore_in_an_async_body_is_refused_before_the_run(crate, capsys):
    add, total = line_of("ADD"), line_of("SUM")
    code, result = probe(
        capsys, crate, "--at", f"src/main.rs:{add}", "--set-at", f"{add}@1", "sum=5",
        "--set-at", f"{total}@1", "sum=@before",
    )  # fmt: skip
    assert code == 2 and result["error"]["code"] == "MUTATION_REJECTED", result
    assert "a coroutine or async body" in result["error"]["message"], result["error"]
