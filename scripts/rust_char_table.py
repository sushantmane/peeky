"""Regenerate src/peeky/rust_chars.py: the scalar values Rust's `{:?}` writes as
`'\\u{..}'`, asked of the pinned toolchain itself (run with PEEKY_RUST_CARGO and PEEKY_RUST_RUSTC set).

Peeky renders a Rust char exactly as the program would print it, so the table must
come from the same Rust version that builds the program; a test ties the two together.
"""

import os
import subprocess
import sys
import tempfile
from pathlib import Path

GENERATOR = r"""fn main() {
    let (major, minor, patch) = char::UNICODE_VERSION;
    println!("{major} {minor} {patch}");
    let mut start: Option<u32> = None;
    let mut last = 0u32;
    for point in 0..=0x10FFFFu32 {
        let Some(c) = char::from_u32(point) else { continue };
        let escaped = format!("{c:?}").starts_with("'\\u{");
        match (escaped, start) {
            (true, None) => start = Some(point),
            (true, Some(s)) if point != last + 1 => {
                println!("{s} {last}");
                start = Some(point);
            }
            (false, Some(s)) => {
                println!("{s} {last}");
                start = None;
            }
            _ => {}
        }
        if escaped {
            last = point;
        }
    }
    if let Some(s) = start {
        println!("{s} {last}");
    }
}
"""


def generate(cargo, rustc):
    """(Rust version, Unicode version, escaped ranges) from this exact toolchain: `cargo`
    builds with `rustc` (RUSTC), never whatever rustc PATH would pick."""
    versions = [
        subprocess.run([tool, "--version"], capture_output=True, text=True, check=True).stdout
        for tool in (cargo, rustc)
    ]
    version = versions[1].split()[1]
    if versions[0].split()[1] != version:
        raise SystemExit(f"cargo and rustc differ: {versions[0].strip()} / {versions[1].strip()}")
    with tempfile.TemporaryDirectory() as scratch:
        root = Path(scratch)
        (root / "src").mkdir()
        (root / "Cargo.toml").write_text(
            '[package]\nname = "chartable"\nversion = "0.1.0"\nedition = "2024"\n'
        )
        (root / "src/main.rs").write_text(GENERATOR)
        out = subprocess.run(
            [cargo, "run", "-q", "--release"],
            cwd=root,
            capture_output=True,
            text=True,
            check=True,
            env={**os.environ, "RUSTC": rustc},
        ).stdout.split("\n")
    unicode = tuple(map(int, out[0].split()))
    ranges = tuple(tuple(map(int, line.split())) for line in out[1:] if line.strip())
    return version, unicode, ranges


def main():
    version, unicode, ranges = generate(
        os.environ["PEEKY_RUST_CARGO"], os.environ["PEEKY_RUST_RUSTC"]
    )
    lines = [
        f'r"""Generated by scripts/rust_char_table.py from Rust {version} (Unicode',
        f"{'.'.join(map(str, unicode))}): the scalar values `{{:?}}` writes as `'\\u{{..}}'`, as",
        "inclusive ranges. Do not edit; regenerate when the pinned Rust changes.",
        '"""',
        "",
        f'RUST_VERSION = "{version}"',
        f"UNICODE_VERSION = {unicode}",
        "ESCAPED = (",
        *(f"    (0x{low:X}, 0x{high:X})," for low, high in ranges),
        ")",
        "",
    ]
    target = Path(__file__).resolve().parents[1] / "src/peeky/rust_chars.py"
    target.write_text("\n".join(lines))
    print(f"{target}: {len(ranges)} ranges, Rust {version}", file=sys.stderr)


if __name__ == "__main__":
    main()
